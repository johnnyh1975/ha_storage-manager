def test_validate_settings() -> None:
    """Types and ranges are enforced."""
    validate = recorder_config.validate_settings
    assert validate(
        {"purge_keep_days": 30.0, "auto_purge": True, "commit_interval": None}, set()
    ) == {
        "purge_keep_days": 30,
        "auto_purge": True,
    }
    for bad in (
        {"x": 1},
        {"auto_purge": 1},
        {"purge_keep_days": 1.5},
        {"purge_keep_days": True},
        {"purge_keep_days": 0},
    ):
        with pytest.raises(ValueError):
            validate(bad, set())
    with pytest.raises(ValueError):
        validate({"purge_keep_days": 5}, {"purge_keep_days"})
    assert recorder_config.block_items(
        {"exclude": {"entities": ["a.b"], "domains": ["x"]}, "auto_purge": True}
    ) == {
        "a.b",
        "domains:x",
        "auto_purge=True",
    }


def test_user_locked_settings(tmp_path: Path) -> None:
    """Keys from configuration.yaml and other packages are locked, ours are not."""
    (tmp_path / "packages").mkdir()
    (tmp_path / "configuration.yaml").write_text(
        "homeassistant:\n  packages: !include_dir_named packages\nrecorder:\n  commit_interval: !secret ci\n"
    )
    (tmp_path / "secrets.yaml").write_text("ci: 3\n")
    (tmp_path / "packages" / "mine.yaml").write_text("recorder:\n  auto_purge: false\n")
    (tmp_path / "packages" / PACKAGE_FILE).write_text("recorder:\n  auto_repack: false\n")
    assert recorder_config.user_locked_settings(str(tmp_path)) == {
        "commit_interval": 3,
        "auto_purge": False,
    }
    (tmp_path / "configuration.yaml").write_text("recorder: [broken")
    assert recorder_config.user_locked_settings(str(tmp_path)) == {}



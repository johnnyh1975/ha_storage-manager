async def test_settings_filters_and_orphans(hass: HomeAssistant, hass_ws_client) -> None:
    """Filters and settings go into the package; locked keys are refused."""
    _write_config(hass, PACKAGES_YAML + "recorder:\n  purge_keep_days: 7\n")
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    assert coordinator.locked_settings == {"purge_keep_days": 7}
    client = await hass_ws_client(hass)
    hass.states.async_set("media_player.tv", "on")

    res = await _ws(
        client,
        {
            "type": f"{DOMAIN}/settings",
            "filters": {
                "domains": ["media_player", "vacuum"],
                "entity_globs": ["sensor.*_rssi", "sensor.gone_*"],
                "event_types": ["call_service"],
            },
            "settings": {"commit_interval": 10, "auto_repack": False},
        },
    )
    assert res["success"], res
    assert res["result"]["restart_required"] is True
    package = Path(hass.config.config_dir) / "packages" / PACKAGE_FILE
    block = recorder_config.read_package(recorder_config.detect_packages(hass.config.config_dir))
    assert block["commit_interval"] == 10
    assert block["auto_repack"] is False
    assert block["exclude"]["event_types"] == ["call_service"]
    assert package.exists()

    status = coordinator.recorder_status()
    assert status["exclusion_orphans"]["domains"] == ["vacuum"]
    assert status["exclusion_orphans"]["entity_globs"] == ["sensor.*_rssi", "sensor.gone_*"]
    removed = (await _ws(client, {"type": f"{DOMAIN}/remove_exclusion_orphans"}))["result"]
    assert removed["removed"] == 3
    assert coordinator.store.data.filters["domains"] == ["media_player"]

    locked = await _ws(client, {"type": f"{DOMAIN}/settings", "settings": {"purge_keep_days": 3}})
    assert locked["success"] is False
    bad = await _ws(client, {"type": f"{DOMAIN}/settings", "settings": {"commit_interval": 99}})
    assert bad["success"] is False
    with pytest.raises(HomeAssistantError):
        await coordinator.async_apply_settings(filters={"bogus": ["x"]})



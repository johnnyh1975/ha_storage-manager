async def test_entity_rows_detail_and_dismiss(hass: HomeAssistant, hass_ws_client) -> None:
    """Advice appears in rows and inbox, details load, dismissals hide advice."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    await _seed(hass)
    await coordinator.async_run_analysis()
    client = await hass_ws_client(hass)

    with (
        patch.object(coord_mod.advisor, "MIN_BYTES", 0),
        patch.object(coord_mod.advisor, "MIN_SHARE", 0),
    ):
        rows = (await _ws(client, {"type": f"{DOMAIN}/entities"}))["result"]
        by_id = {r["entity_id"]: r for r in rows["rows"]}
        assert by_id["sensor.kitchen_rssi"]["advice"]["action"] == "excluded"
        assert by_id["sensor.kitchen_rssi"]["top"] is True
        assert rows["inbox"][0]["entity_id"] == "sensor.kitchen_rssi"
        assert rows["size_history"], "analysis records a size sample"

        detail = (
            await _ws(
                client, {"type": f"{DOMAIN}/entity_detail", "entity_id": "sensor.kitchen_rssi"}
            )
        )["result"]
        assert sum(detail["daily"]) == 60
        assert detail["attributes"][0]["name"] == "big"
        assert detail["attribute_variants"] == 60
        assert detail["usage"]["automations"] == []

        res = await _ws(
            client, {"type": f"{DOMAIN}/dismiss", "entity_ids": ["sensor.kitchen_rssi"]}
        )
        assert res["result"]["dismissed"] == 1
        rows = (await _ws(client, {"type": f"{DOMAIN}/entities"}))["result"]
        assert not [a for a in rows["inbox"] if a["entity_id"] == "sensor.kitchen_rssi"]
        assert rows["dismissed_count"] == 1

        await _ws(client, {"type": f"{DOMAIN}/dismiss", "undo": True})
        rows = (await _ws(client, {"type": f"{DOMAIN}/entities"}))["result"]
        assert rows["dismissed_count"] == 0

    missing = (
        await _ws(client, {"type": f"{DOMAIN}/entity_detail", "entity_id": "sensor.unknown"})
    )["result"]
    assert missing["daily"] == [0] * 14
    assert database.attribute_sizes("not json") == []
    assert database.attribute_sizes("[1, 2]") == []
    assert database.attribute_sizes(None) == []



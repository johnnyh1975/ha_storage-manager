async def _ws(client, payload, _ids=[0]):  # noqa: B006 - simple counter
    _ids[0] += 1
    await client.send_json({"id": _ids[0], **payload})
    while True:
        msg = await client.receive_json()
        if msg.get("id") == _ids[0] and msg["type"] == "result":
            return msg



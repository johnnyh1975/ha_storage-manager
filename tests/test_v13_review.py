async def test_statistics_age_follows_the_plan(hass: HomeAssistant) -> None:
    """Only the statistics and cutoffs the preview showed; changed limits refuse."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    coordinator.store.data.stats_keep_months = 12
    item = {"statistic_id": "sensor.a", "metadata_id": 1, "rows": 10, "cutoff": 100.0}
    shown = {"groups": {}, "rows": 10, "bytes": 1000, "items": [item]}
    later = {
        "groups": {},
        "rows": 30,
        "bytes": 3000,
        "items": [
            {**item, "rows": 20, "cutoff": 200.0},
            {"statistic_id": "sensor.b", "metadata_id": 2, "rows": 10, "cutoff": 200.0},
        ],
    }
    current = AsyncMock(side_effect=[shown, later, shown])
    deleted = AsyncMock(return_value=10)
    with (
        patch.object(coordinator, "async_statistics_age_current", current),
        patch.object(coordinator, "async_delete_old_statistics", deleted),
        patch.object(coordinator, "async_safety", AsyncMock(return_value={})),
        patch.object(coordinator.undo, "async_protect", AsyncMock(return_value=None)),
    ):
        plan_id = (await coordinator.async_preview(["statistics_age"]))["plan_id"]
        await coordinator.async_clean(["statistics_age"], plan_id=plan_id)
        used = deleted.await_args.args[0]
        assert [i["statistic_id"] for i in used["items"]] == ["sensor.a"]
        assert used["items"][0]["cutoff"] == 100.0
        assert used["bytes"] == 2000

        plan_id = (await coordinator.async_preview(["statistics_age"]))["plan_id"]
        coordinator.store.data.stats_keep_months = 6
        with pytest.raises(HomeAssistantError, match="plan_expired"):
            await coordinator.async_clean(["statistics_age"], plan_id=plan_id)



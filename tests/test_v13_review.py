async def test_events_written_during_the_cleanup_stay(hass: HomeAssistant) -> None:
    """Events after the selection are neither in the undo file nor deleted."""
    entry = await setup_entry(hass, {"backup_before_delete": True})
    coordinator = entry.runtime_data
    await _noisy(hass, 4)
    await coordinator.async_run_analysis()
    coordinator.store.data.filters = {"event_types": ["noisy_event"]}

    protect = coordinator.undo.async_protect

    async def protect_then_write(*args):
        info = await protect(*args)
        # the type is still recorded: new rows arrive while the cleanup runs
        await _noisy(hass, 2)
        return info

    with patch.object(coordinator.undo, "async_protect", protect_then_write):
        result = await coordinator.async_clean(["events"], event_types=["noisy_event"])
    assert result["blocked"] is None
    assert result["undo"]["rows"]["events"] == 4
    instance = get_instance(hass)
    assert await instance.async_add_executor_job(_event_rows, hass, "noisy_event") == 2

    # the bound itself
    newest = await database.async_max_event_id(hass)
    await _noisy(hass, 1)
    assert await database.async_delete_events(hass, ["noisy_event"], max_id=newest) > 0
    assert await instance.async_add_executor_job(_event_rows, hass, "noisy_event") == 1

    spec = undo.Spec(event_types=["noisy_event"], events_max_id=newest)
    assert await database.async_read(hass, lambda s: undo.count(s, spec)) == 0
    spec.events_max_id = None
    assert await database.async_read(hass, lambda s: undo.count(s, spec)) == 1



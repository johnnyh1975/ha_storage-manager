def test_scan_yaml(tmp_path: Path) -> None:
    """Literal ids, domain-wide templates and skipped files and folders."""
    (tmp_path / "packages").mkdir()
    (tmp_path / "packages" / "heating.yaml").write_text(
        "sensor:\n"
        "  - platform: template\n"
        "    sensors:\n"
        "      avg:\n"
        "        value_template: \"{{ states('sensor.kitchen_temp') }}\"\n"
        "# sensor.commented_out\n"
        '      all: "{{ states.sensor | count }}"\n'
        "      any: \"{{ expand('group.x') | count }}\"\n"
    )
    (tmp_path / "packages" / "storage_manager.yaml").write_text("exclude: sensor.kitchen_temp\n")
    (tmp_path / "scenes.yaml").write_text("- entities:\n    light.desk: on\n")
    (tmp_path / "automations.yaml").write_text("- trigger: sensor.kitchen_temp\n")
    (tmp_path / "secrets.yaml").write_text("x: sensor.kitchen_temp\n")
    (tmp_path / "custom_components").mkdir()
    (tmp_path / "custom_components" / "x.yaml").write_text("sensor.kitchen_temp\n")
    (tmp_path / ".storage").mkdir()
    (tmp_path / ".storage" / "y.yaml").write_text("sensor.kitchen_temp\n")
    (tmp_path / "big.yaml").write_text("sensor.kitchen_temp " * 50)
    wanted = {"sensor.kitchen_temp", "light.desk", "sensor.commented_out"}
    with patch.object(usage, "YAML_MAX_BYTES", 500):
        refs, dynamic = usage.scan_yaml(str(tmp_path), wanted)
    assert refs["sensor.kitchen_temp"] == [{"file": "packages/heating.yaml", "line": 5}]
    assert refs["light.desk"] == [{"file": "scenes.yaml", "line": 2}]
    assert "sensor.commented_out" not in refs
    assert dynamic == {"sensor": ["packages/heating.yaml"], "*": ["packages/heating.yaml"]}
    with patch.object(usage, "YAML_MAX_FILES", 0):
        assert usage.scan_yaml(str(tmp_path), wanted) == ({}, {})


def test_dashboard_statistics() -> None:
    """Statistics cards need long-term statistics, not state history."""
    config = {
        "views": [
            {
                "cards": [
                    {
                        "type": "statistics-graph",
                        "entities": ["sensor.power", {"entity": "sensor.gas"}],
                    },
                    {"type": "statistic", "entity": "sensor.water"},
                    {"type": "entities", "entities": ["sensor.other"]},
                ]
            }
        ]
    }
    assert usage.dashboard_statistics(config, "Home") == {
        "sensor.power",
        "sensor.gas",
        "sensor.water",
    }


async def test_yaml_history_readers(hass: HomeAssistant) -> None:
    """YAML statistics, history_stats and filter sensors protect their source."""
    stats = SimpleNamespace(entity_id="sensor.avg", _source_entity_id="sensor.temp")
    hist = SimpleNamespace(
        entity_id="sensor.on_time",
        coordinator=SimpleNamespace(_history_stats=SimpleNamespace(entity_id="switch.pump")),
    )
    filt = SimpleNamespace(entity_id="sensor.smooth", _entity="sensor.noisy")
    broken = SimpleNamespace(entity_id="sensor.odd")

    def platforms(_hass, name):
        entities = {
            "statistics": [stats, broken],
            "history_stats": [hist],
            "filter": [filt],
        }[name]
        ui = SimpleNamespace(config_entry=object(), entities={"sensor.ui": stats})
        return [SimpleNamespace(config_entry=None, entities={e.entity_id: e for e in entities}), ui]

    with patch("homeassistant.helpers.entity_platform.async_get_platforms", side_effect=platforms):
        found = usage.yaml_history_readers(hass)
    assert found == {
        "sensor.temp": [{"domain": "statistics", "title": "sensor.avg"}],
        "switch.pump": [{"domain": "history_stats", "title": "sensor.on_time"}],
        "sensor.noisy": [{"domain": "filter", "title": "sensor.smooth"}],
    }

    with (
        patch.object(usage, "yaml_history_readers", return_value=found),
        patch.object(
            usage,
            "scan_yaml",
            return_value=(
                {"sensor.temp": [{"file": "a.yaml", "line": 3}]},
                {"sensor": ["b.yaml"], "*": ["c.yaml"]},
            ),
        ),
    ):
        collected = await usage.async_collect(hass, ["sensor.temp", "switch.pump"])
    temp = collected["sensor.temp"]
    assert temp.history_readers == [{"domain": "statistics", "title": "sensor.avg"}]
    assert temp.yaml == [{"file": "a.yaml", "line": 3}]
    assert temp.dynamic == ["b.yaml"]
    assert collected["switch.pump"].dynamic == []
    assert temp.as_dict()["yaml"] == temp.yaml
    assert not temp.needs_statistics

    with patch.object(usage, "scan_yaml", side_effect=OSError("no access")):
        collected = await usage.async_collect(hass, ["sensor.temp"])
    assert collected["sensor.temp"].yaml == []

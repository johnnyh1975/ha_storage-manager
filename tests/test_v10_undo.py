async def _query(hass: HomeAssistant, sql: str, key: str) -> list[tuple]:
    return await database.async_read(
        hass, lambda s: [tuple(r) for r in s.execute(text(sql), {"e": key})]
    )


async def _seed(hass: HomeAssistant) -> None:
    for value in ("1", "2", "3"):
        hass.states.async_set("sensor.gone", value, {"unit_of_measurement": "W", "v": value})
    hass.states.async_set("sensor.keep", "9")
    for n in range(3):
        hass.bus.async_fire("noisy_event", {"n": n})
    start = dt_util.utcnow().replace(minute=0, second=0, microsecond=0) - timedelta(days=3)
    metadata = {
        "has_mean": False,
        "mean_type": StatisticMeanType.NONE,
        "has_sum": True,
        "name": "Import",
        "source": "demo",
        "statistic_id": "demo:import",
        "unit_of_measurement": "kWh",
        "unit_class": "energy",
    }
    rows = [
        {"start": start + timedelta(hours=h), "sum": float(h), "state": float(h)} for h in range(4)
    ]
    async_add_external_statistics(hass, metadata, rows)
    await async_wait_recording_done(hass)


async def _snapshot(hass: HomeAssistant) -> tuple:
    return (
        await _query(hass, Q_STATES, "sensor.gone"),
        await _query(hass, Q_STATS, "demo:import"),
        await _query(hass, Q_EVENTS, "noisy_event"),
    )


async def _delete(hass: HomeAssistant) -> None:
    await database.async_purge_entities(hass, ["sensor.gone"], 0)
    await database.async_clear_statistics(hass, ["demo:import"])
    await database.async_delete_events(hass, ["noisy_event"])
    await database.async_wait_idle(hass)
    await async_wait_recording_done(hass)


async def _restore(hass: HomeAssistant, path) -> dict:
    result: dict = {}

    def job(instance) -> None:
        result.update(database.run_write(instance, lambda s: undo.restore(s, path)))
        undo.reset_caches(instance)

    assert await repack.async_run_on_recorder(hass, job)
    await async_wait_recording_done(hass)
    return result


async def test_roundtrip(hass: HomeAssistant) -> None:
    """States, statistics and events come back as they were; twice adds nothing."""
    await setup_entry(hass)
    await _seed(hass)
    before = await _snapshot(hass)
    assert len(before[0]) == 3 and len(before[1]) == 4 and len(before[2]) == 3
    spec = undo.Spec(
        states={"sensor.gone": None}, statistics=["demo:import"], event_types=["noisy_event"]
    )
    assert await database.async_read(hass, lambda s: undo.count(s, spec)) == 10
    path = undo.path_for(hass.config.config_dir, undo.new_id())
    info = await database.async_read(hass, lambda s: undo.export(s, path, spec))
    assert info["rows"] == {"states": 3, "statistics": 4, "events": 3}
    assert info["bytes"] > 0

    await _delete(hass)
    assert await _snapshot(hass) == ([], [], [])
    result = await _restore(hass, path)
    assert result["added"] == {"states": 3, "statistics": 4, "events": 3}
    assert await _snapshot(hass) == before
    assert await _query(hass, Q_STATES, "sensor.keep") != []

    again = await _restore(hass, path)
    assert again["added"] == {"states": 0, "statistics": 0, "events": 0}
    assert again["skipped"] == {"states": 3, "statistics": 4, "events": 3}
    assert await _snapshot(hass) == before

    # the recorder keeps writing for the entity after its rows came back
    hass.states.async_set("sensor.gone", "4")
    await async_wait_recording_done(hass)
    assert len(await _query(hass, Q_STATES, "sensor.gone")) == 4



async def test_refusals(hass: HomeAssistant, tmp_path) -> None:
    """Truncated, foreign-format and other-schema files are refused."""
    await setup_entry(hass)
    await _seed(hass)
    spec = undo.Spec(states={"sensor.gone": None})
    path = undo.path_for(hass.config.config_dir, undo.new_id())
    await database.async_read(hass, lambda s: undo.export(s, path, spec))
    lines = gzip.decompress(path.read_bytes()).splitlines()

    def write(name: str, content: list[bytes]):
        target = tmp_path / name
        target.write_bytes(gzip.compress(b"\n".join(content) + b"\n"))
        return target

    with pytest.raises(undo.UndoError) as err:
        undo.read_header(write("cut.gz", lines[:-1]))
    assert err.value.reason == "incomplete"
    with pytest.raises(undo.UndoError) as err:
        undo.read_header(write("tail.gz", [*lines, lines[1]]))
    assert err.value.reason == "damaged"
    header = json.loads(lines[0])
    foreign = write("format.gz", [json.dumps({**header, "format": 99}).encode(), *lines[1:]])
    with pytest.raises(undo.UndoError) as err:
        undo.read_header(foreign)
    assert err.value.reason == "format"
    # an older schema with every needed column: restored, extra columns dropped
    old_rows = []
    for raw in lines[1:]:
        line = json.loads(raw)
        if line.get("t") == "state":
            line["r"]["column_of_the_past"] = 1
        old_rows.append(json.dumps(line).encode())
    other = write("schema.gz", [json.dumps({**header, "schema": 1}).encode(), *old_rows])
    info = undo.describe(other)
    assert (info["schema_ok"], info["schema_changed"], info["missing"]) == (True, True, [])
    await database.async_purge_entities(hass, ["sensor.gone"], 0)
    await async_wait_recording_done(hass)
    assert (await _restore(hass, other))["added"]["states"] == 3
    # a file without a column the restore needs is refused
    stripped = []
    for raw in lines[1:]:
        line = json.loads(raw)
        if line.get("t") == "state":
            line["r"].pop("last_updated_ts", None)
        stripped.append(json.dumps(line).encode())
    broken_columns = write("columns.gz", [lines[0], *stripped])
    info = undo.describe(broken_columns)
    assert info["schema_ok"] is False
    assert info["missing"] == ["states.last_updated_ts"]
    with pytest.raises(HomeAssistantError, match="schema"):
        await _restore(hass, broken_columns)
    assert undo.missing_columns({"unknown": {"x"}}) == []
    broken = tmp_path / "broken.gz"
    broken.write_bytes(b"not gzip")
    with pytest.raises(undo.UndoError) as err:
        undo.read_header(broken)
    assert err.value.reason == "damaged"
    with pytest.raises(undo.UndoError) as err:
        undo.read_header(tmp_path / "missing.gz")
    assert err.value.reason == "missing"
    for bad in ("", "../x", "1/2", "ABC"):
        with pytest.raises(undo.UndoError):
            undo.path_for(hass.config.config_dir, bad)
    err = undo.UndoError("no_space", "12")
    assert str(err) == "no_space: 12"


def test_prune(tmp_path) -> None:
    """Old files and the oldest beyond the size limit go; others stay."""
    config = str(tmp_path)
    assert undo.prune(config) == []
    assert undo.existing(config) == set()
    folder = undo.undo_dir(config)
    folder.mkdir(parents=True)
    now = time.time()
    for name, age, size in (("1-a", 20, 10), ("2-b", 3, 600), ("3-c", 2, 600), ("4-d", 1, 10)):
        p = folder / f"{name}{undo.SUFFIX}"
        p.write_bytes(b"x" * size)
        os.utime(p, (now - age * 86400, now - age * 86400))
    tmp = folder / "x.tmp"
    tmp.write_bytes(b"x")
    os.utime(tmp, (now - 2 * 86400, now - 2 * 86400))
    removed = undo.prune(config, keep_days=14, max_bytes=1000)
    assert sorted(removed) == ["1-a", "2-b"]
    assert undo.existing(config) == {"3-c", "4-d"}
    assert not tmp.exists()


async def test_clean_with_undo(hass: HomeAssistant, hass_ws_client) -> None:
    """A cleanup writes the targeted backup instead of the full one; undo brings it back."""
    entry = await setup_entry(hass, {"backup_before_delete": True})
    coordinator = entry.runtime_data
    await _seed(hass)
    hass.states.async_remove("sensor.gone")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    before = await _query(hass, Q_STATES, "sensor.gone")
    assert "sensor.gone" in coordinator.orphans()["entities"]

    preview = await coordinator.async_preview(["orphans"], entity_ids=["sensor.gone"])
    assert preview["safety"]["backup"] == {"action": "undo", "fallback": True}
    assert preview["safety"]["space"]["undo"] > 0

    create = AsyncMock(side_effect=AssertionError("no full backup expected"))
    with patch.object(safety, "async_create_backup", create):
        result = await coordinator.async_clean(["orphans"], entity_ids=["sensor.gone"])
    assert result["blocked"] is None
    assert result["backup"] is None
    undo_id = result["undo"]["id"]
    assert result["undo"]["rows"]["states"] >= 3
    await database.async_wait_idle(hass)
    await async_wait_recording_done(hass)
    assert await _query(hass, Q_STATES, "sensor.gone") == []
    assert await coordinator.async_undo_available() == [undo_id]
    assert coordinator.store.data.history[-1]["details"]["undo"]["id"] == undo_id

    client = await hass_ws_client(hass)
    overview = await _ws(client, {"type": f"{DOMAIN}/overview"})
    assert overview["result"]["undo_available"] == [undo_id]
    msg = await _ws(client, {"type": f"{DOMAIN}/undo_preview", "undo_id": undo_id})
    assert msg["result"]["rows"]["states"] >= 3
    assert msg["result"]["undone"] is None
    msg = await _ws(client, {"type": f"{DOMAIN}/undo_preview", "undo_id": "../etc"})
    assert not msg["success"]
    msg = await _ws(client, {"type": f"{DOMAIN}/undo_preview", "undo_id": "123-abc"})
    assert not msg["success"]
    assert msg["error"]["message"] == "undo_missing"

    total = coordinator.store.data.freed_total
    freed = coordinator.store.data.history[-1]["freed_bytes"]
    msg = await _ws(client, {"type": f"{DOMAIN}/undo", "undo_id": undo_id})
    assert msg["success"], msg
    assert coordinator.store.data.freed_total == max(total - freed, 0)
    assert msg["result"]["added"]["states"] >= 3
    await async_wait_recording_done(hass)
    assert await _query(hass, Q_STATES, "sensor.gone") == before
    assert coordinator.store.data.history[-1]["action"] == "undo"
    assert (await coordinator.async_undo_preview(undo_id))["undone"]



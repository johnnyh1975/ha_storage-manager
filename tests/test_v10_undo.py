async def test_fallback_to_full_backup(hass: HomeAssistant) -> None:
    """Too many rows or no space: the full backup runs as before."""
    entry = await setup_entry(hass, {"backup_before_delete": True})
    coordinator = entry.runtime_data
    await _seed(hass)
    hass.states.async_remove("sensor.gone")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    backup = {"name": "Safety", "backup_id": "b1"}
    with (
        patch.object(undo, "MAX_ROWS", 0),
        patch.object(safety, "async_recent_backup", AsyncMock(return_value=None)),
        patch.object(safety, "async_create_backup", AsyncMock(return_value=backup)) as create,
        patch.object(database, "async_purge_entities", AsyncMock(return_value=0)),
    ):
        result = await coordinator.async_clean(["orphans"], entity_ids=["sensor.gone"])
    create.assert_awaited_once()
    assert result["undo"] is None
    assert result["backup"] == backup

    # no space: blocked when the full backup is not possible either
    # the mocked purge left the rows; the analysis after the cleanup finds them again
    await hass.async_block_till_done(wait_background_tasks=True)
    await coordinator.async_run_analysis()
    with (
        patch("custom_components.storage_manager.undo_service.UNDO_SPACE_MARGIN", 1 << 60),
        patch.object(
            safety,
            "async_recent_backup",
            AsyncMock(side_effect=safety.SafetyError("backup_failed")),
        ),
        patch.object(database, "async_purge_entities", AsyncMock(return_value=0)) as purge,
    ):
        result = await coordinator.async_clean(["orphans"], entity_ids=["sensor.gone"])
    assert result["blocked"]["reason"] == "backup_failed"
    purge.assert_not_awaited()

    # an unexpected error is logged and the backup is off: the cleanup goes on
    coordinator.config_entry.runtime_data  # noqa: B018
    hass.config_entries.async_update_entry(
        entry, options={**entry.options, "backup_before_delete": False}
    )
    await hass.async_block_till_done()
    coordinator = entry.runtime_data
    await hass.async_block_till_done(wait_background_tasks=True)
    await coordinator.async_run_analysis()
    with (
        patch.object(undo, "export", side_effect=RuntimeError("boom")),
        patch.object(database, "async_purge_entities", AsyncMock(return_value=0)) as purge,
    ):
        result = await coordinator.async_clean(["orphans"], entity_ids=["sensor.gone"])
    assert result["undo"] is None
    purge.assert_awaited()



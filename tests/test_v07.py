def test_retention_whatif() -> None:
    """Fewer days free history, more days grow at today's rate."""
    entities = {
        # ten days of history at 100 rows/day, 10 bytes per row
        "sensor.a": {"rows": 1000, "rows_24h": 100, "est_state_bytes": 10_000},
        # young entity: only two days so far
        "sensor.b": {"rows": 200, "rows_24h": 100, "est_state_bytes": 2_000},
        # own retention of 3 days
        "sensor.c": {"rows": 300, "rows_24h": 100, "est_state_bytes": 3_000},
        "sensor.x": {"rows": 1000, "rows_24h": 100, "est_state_bytes": 10_000},
        "sensor.empty": {"rows": 0, "rows_24h": 0, "est_state_bytes": 0},
    }
    args = {"keep_days": 10, "tiers": {"sensor.c": "3"}, "excluded": {"sensor.x"}}
    seven = advisor.retention_whatif(entities, days=7, **args)
    # a: keeps 700 of 1000 rows (-3000 B); b: unchanged (200 < 700); c: own 3 days
    assert seven == {"days": 7, "bytes": -3000, "rows": -300}
    two = advisor.retention_whatif(entities, days=2, **args)
    assert two["bytes"] == -8000 + 0 - 1000
    twenty = advisor.retention_whatif(entities, days=20, **args)
    # a and b grow by ten days at 100 rows/day; c stays at 3 days
    assert twenty == {"days": 20, "bytes": 10_000 + 10_000, "rows": 2000}
    assert advisor.retention_whatif(entities, days=10, **args)["bytes"] == 0


def test_find_writers_and_baselines() -> None:
    """Ten times the usual rate (and often) is flagged, new entities only when very fast."""
    now = time.time()
    assert health.find_writers({}, {"sensor.new": 50_000}) == []  # first analysis ever
    base = {
        "sensor.calm": [100.0, 5, now],
        "sensor.young": [100.0, 1, now],
        "sensor.busy": [5000.0, 5, now],
    }
    rates = {
        "sensor.calm": 3000,  # 30x, often enough
        "sensor.young": 3000,  # too few days to know its usual rate
        "sensor.busy": 6000,  # only a little more
        "sensor.new": 20_000,
        "sensor.new_slow": 5000,
        "sensor.handled": 50_000,
    }
    found = health.find_writers(base, rates, {"sensor.handled"})
    assert [w["entity_id"] for w in found] == ["sensor.new", "sensor.calm"]
    assert found[1] == {"entity_id": "sensor.calm", "per_day": 3000, "before": 100}
    assert found[0]["before"] is None

    old = {"sensor.gone": [1.0, 4, now - 40 * 86400], "sensor.away": [1.0, 4, now - 86400]}
    updated = health.update_baselines({**base, **old}, {"sensor.calm": 200, "sensor.n": 7}, now)
    assert updated["sensor.calm"][0] == pytest.approx(130.0)
    assert updated["sensor.calm"][1] == 6
    assert updated["sensor.n"] == [7.0, 1, now]
    assert "sensor.gone" not in updated and "sensor.away" in updated

    assert health.writers_check(None)["status"] == health.UNKNOWN
    assert health.writers_check([])["status"] == health.OK
    check = health.writers_check(found)
    assert check["status"] == health.WARNING and check["values"]["count"] == 2


def test_debug_sources(tmp_path: Path) -> None:
    """Explicit debug levels count; inherited levels and placeholders do not."""
    manager = logging.Manager(logging.RootLogger(logging.WARNING))
    manager.getLogger("homeassistant.components.mqtt.client").setLevel(logging.DEBUG)
    manager.getLogger("custom_components.roomba_plus").setLevel(logging.DEBUG)
    manager.getLogger("pyhap.accessory").setLevel(logging.DEBUG)
    manager.getLogger("homeassistant.components.zha").setLevel(logging.INFO)
    manager.getLogger("aiohttp.access")  # leaves a PlaceHolder for "aiohttp"
    assert logs.debug_sources(manager) == ["mqtt", "pyhap", "roomba_plus"]
    manager.root.setLevel(logging.DEBUG)
    assert "default" in logs.debug_sources(manager)
    assert isinstance(logs.debug_sources(), list)

    assert logs.log_file_size(str(tmp_path)) is None
    (tmp_path / logs.LOG_FILE).write_text("x" * 10)
    assert logs.log_file_size(str(tmp_path)) == 10


def test_store_writer_fields() -> None:
    """Baselines survive a restart; malformed rows are dropped."""
    data = ManagerData.from_dict(
        {
            "rate_baselines": {"sensor.a": [1, 2, 3], "sensor.b": [1], "sensor.c": "x"},
            "baselines_at": 5,
            "heavy_writers": [{"entity_id": "sensor.a", "per_day": 1, "before": None}],
        }
    )
    assert data.rate_baselines == {"sensor.a": [1.0, 2.0, 3.0]}
    assert data.baselines_at == 5.0
    assert data.as_dict()["heavy_writers"][0]["entity_id"] == "sensor.a"


async def test_writers_in_coordinator(hass: HomeAssistant, hass_ws_client) -> None:
    """Analysis flags writers, health and repairs show them, acknowledging clears them."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    await _seed(hass)
    data = coordinator.store.data
    # an earlier day: the rssi sensor used to write 1 row per day
    data.rate_baselines = {"sensor.kitchen_rssi": [1.0, 5, time.time()]}
    data.baselines_at = time.time()
    with patch.object(health, "WRITER_MIN_PER_DAY", 10):
        await coordinator.async_run_analysis()
    assert [w["entity_id"] for w in data.heavy_writers] == ["sensor.kitchen_rssi"]
    # the usual rate is learned at most once a day
    assert data.rate_baselines["sensor.kitchen_rssi"][1] == 5

    client = await hass_ws_client(hass)
    res = await _ws(client, {"type": f"{DOMAIN}/health", "force": True})
    writers = next(c for c in res["result"]["database"]["checks"] if c["key"] == "writers")
    assert writers["status"] == "warning"
    repairs.async_update_issues(hass, coordinator)
    issue = ir.async_get(hass).async_get_issue(DOMAIN, ISSUE_HEAVY_WRITERS)
    assert issue is not None
    assert "sensor.kitchen_rssi: 1 → 60 /24 h" in issue.translation_placeholders["entities"]

    res = await _ws(client, {"type": f"{DOMAIN}/ack_writers"})
    assert res["result"] == {"acknowledged": 1}
    assert data.heavy_writers == []
    assert data.rate_baselines["sensor.kitchen_rssi"][0] == 60.0
    repairs.async_update_issues(hass, coordinator)
    assert ir.async_get(hass).async_get_issue(DOMAIN, ISSUE_HEAVY_WRITERS) is None

    # a new day learns the rate; excluded entities are not flagged
    data.baselines_at = 0
    data.excluded = ["sensor.kitchen_rssi"]
    data.rate_baselines["sensor.kitchen_rssi"] = [1.0, 5, time.time()]
    with patch.object(health, "WRITER_MIN_PER_DAY", 10):
        await coordinator.async_run_analysis()
    assert data.heavy_writers == []
    assert data.rate_baselines["sensor.kitchen_rssi"][1] == 6


async def test_whatif_and_debug_in_overview(hass: HomeAssistant, hass_ws_client) -> None:
    """The panel asks for estimates; debug logging becomes a recommendation."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    await _seed(hass)
    await coordinator.async_run_analysis()
    client = await hass_ws_client(hass)
    res = await _ws(client, {"type": f"{DOMAIN}/retention_whatif", "days": [3, 30]})
    assert [r["days"] for r in res["result"]["results"]] == [3, 30]
    res = await _ws(client, {"type": f"{DOMAIN}/retention_whatif", "days": [0]})
    assert not res["success"]

    with (
        patch.object(logs, "debug_sources", return_value=["mqtt"]),
        patch.object(logs, "log_file_size", return_value=5 * 1024**2),
    ):
        await coordinator.async_refresh()
    rec = next(r for r in coordinator.recommendations() if r["id"] == "debug_logging")
    assert rec == {
        "id": "debug_logging",
        "bytes": 5 * 1024**2,
        "count": 1,
        "sources": ["mqtt"],
        "action": "navigate",
        "url": "/config/logs",
    }
    with patch.object(logs, "debug_sources", return_value=[]):
        await coordinator.async_refresh()
    assert "debug_logging" not in [r["id"] for r in coordinator.recommendations()]


async def test_small_log_shows_no_size(hass: HomeAssistant) -> None:
    """A log of a few kilobytes is not presented as a saving."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    with (
        patch.object(logs, "debug_sources", return_value=["default"]),
        patch.object(logs, "log_file_size", return_value=2048),
    ):
        await coordinator.async_refresh()
    rec = next(r for r in coordinator.recommendations() if r["id"] == "debug_logging")
    assert rec["bytes"] == 0 and rec["sources"] == ["default"]

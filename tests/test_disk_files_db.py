def test_sqlite_path_variants(tmp_path: Path) -> None:
    """Absolute, relative, in-memory and non-SQLite URLs."""
    hass = SimpleNamespace(config=SimpleNamespace(path=lambda p: str(tmp_path / p)))
    cases = {
        "sqlite:////data/ha.db": Path("/data/ha.db"),
        "sqlite:///rel.db?timeout=5": tmp_path / "rel.db",
        "sqlite://": None,
        "mysql://u:p@h/db": None,
    }
    for url, expected in cases.items():
        with patch.object(database, "get_instance", return_value=SimpleNamespace(db_url=url)):
            assert database.sqlite_path(hass) == expected, url
    assert database.sqlite_file_size(None) is None
    db = tmp_path / "x.db"
    db.write_bytes(b"1" * 10)
    (tmp_path / "x.db-wal").write_bytes(b"1" * 5)
    assert database.sqlite_file_size(db) == 15



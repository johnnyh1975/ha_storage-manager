def test_forecast_edges() -> None:
    """Short spans, flat usage and constant timestamps give no forecast."""
    gib = 1024**3
    short = [[1000.0 + i, gib, 2 * gib] for i in range(5)]
    assert disk.forecast(short, 1010.0)["growth_per_day"] is None
    flat = [[i * 3600.0, gib, 2 * gib] for i in range(30)]
    result = disk.forecast(flat, 30 * 3600.0)
    assert result["growth_per_day"] == 0
    assert result["days_until_full"] is None
    same = [[0.0, gib, 2 * gib], [0.0, gib, 2 * gib], [0.0, gib, 2 * gib]]
    assert disk.forecast(same, 0.0)["growth_per_day"] is None
    # samples spanning > window: only the window counts, still needs 12 h
    assert (
        disk.forecast([[0.0, 1, 2], [1.0, 1, 2], [2.0, 1, 2]], 30 * 86400.0)["growth_per_day"]
        is None
    )


def test_scan_large_files_and_core_dumps(tmp_path: Path) -> None:
    """Large unknown files are listed, a core dump is a hog, small files are not."""
    big = tmp_path / "www" / "video.mp4"
    big.parent.mkdir()
    with big.open("wb") as fh:
        fh.truncate(files.LARGE_FILE_MIN + 1)
    (tmp_path / "core.123").write_bytes(b"d" * 10)
    (tmp_path / "core").mkdir()  # a directory called core is not a dump
    (tmp_path / ".storage").mkdir()
    with (tmp_path / ".storage" / "huge").open("wb") as fh:
        fh.truncate(files.LARGE_FILE_MIN + 1)
    (tmp_path / "small.txt").write_text("x")
    link = tmp_path / "link.mp4"
    link.symlink_to(big)
    result = files.scan(str(tmp_path))
    assert [f["path"] for f in result["large_files"]] == ["www/video.mp4"]
    hogs = {h["key"]: h for h in result["hogs"]}
    assert hogs["core_dumps"]["size_bytes"] == 10



def _usage(node_id, used, children=None, total=None, label=None):
    return SimpleNamespace(
        id=node_id, used_bytes=used, children=children, total_bytes=total, label=label
    )


def _client(usage=None, addons=None, fail=False):
    client = MagicMock()
    if fail:
        client.host.get_disk_usage = AsyncMock(side_effect=RuntimeError("busy"))
        client.addons.list = AsyncMock(side_effect=RuntimeError("busy"))
    else:
        client.host.get_disk_usage = AsyncMock(return_value=usage)
        client.addons.list = AsyncMock(return_value=addons or [])
    client.supervisor.repair = AsyncMock()
    return client


async def test_supervisor_breakdown(hass: HomeAssistant) -> None:
    """v1 ids are normalized, children sorted by size."""
    tree = _usage(
        "root",
        100,
        total=200,
        children=[
            _usage("addons_data", 10, children=[_usage("core_a", 2), _usage("core_b", 8)]),
            _usage("homeassistant", 50),
            _usage("system", 40, label="System"),
        ],
    )
    client = _client(tree, addons=[SimpleNamespace(slug="core_b", name="B")])
    with (
        patch.object(disk, "is_hassio", return_value=True),
        patch("homeassistant.components.hassio.get_supervisor_client", return_value=client),
    ):
        result = await disk.async_supervisor_breakdown(hass)
        names = await disk.async_addon_names(hass)
        await disk.async_supervisor_repair(hass)
    assert result["total_bytes"] == 200
    assert [c["id"] for c in result["children"]] == ["homeassistant", "system", "apps_data"]
    assert [c["id"] for c in result["children"][2]["children"]] == ["core_b", "core_a"]
    assert names == {"core_b": "B"}
    client.supervisor.repair.assert_awaited_once()



async def test_wait_idle_timeout(prepared_hass: HomeAssistant) -> None:
    """A recorder that never drains times out."""
    hass = prepared_hass
    instance = MagicMock()
    instance.backlog = 5

    def _queue(task):
        task.future.set_result(None)

    instance.queue_task.side_effect = _queue
    with patch.object(database, "get_instance", return_value=instance):
        assert await database.async_wait_idle(hass, timeout=0.5) is False

    def _never(task):
        return None

    instance.queue_task.side_effect = _never
    with patch.object(database, "get_instance", return_value=instance):
        assert await database.async_wait_idle(hass, timeout=0.3) is False



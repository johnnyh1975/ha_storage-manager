def _event_rows(hass: HomeAssistant, event_type: str) -> int:
    with session_scope(hass=hass, read_only=True) as session:
        return int(
            session.execute(
                text(
                    "SELECT COUNT(*) FROM events e JOIN event_types t "
                    "ON t.event_type_id = e.event_type_id WHERE t.event_type = :t"
                ),
                {"t": event_type},
            ).scalar()
        )


async def test_delete_events(hass: HomeAssistant, hass_ws_client) -> None:
    """Old events of a type are deleted in chunks; state_changed never."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    for i in range(7):
        hass.bus.async_fire("noisy_event", {"n": i})
    hass.bus.async_fire("kept_event", {"n": 1})
    await async_wait_recording_done(hass)
    instance = get_instance(hass)
    assert await instance.async_add_executor_job(_event_rows, hass, "noisy_event") == 7

    assert await database.async_delete_events(hass, ["state_changed"]) == 0
    assert await database.async_delete_events(hass, ["no_such_type"]) == 0
    deleted = await database.async_delete_events(hass, ["noisy_event"], chunk=3)
    assert deleted >= 7
    assert await instance.async_add_executor_job(_event_rows, hass, "noisy_event") == 0
    assert await instance.async_add_executor_job(_event_rows, hass, "kept_event") == 1

    # through the cleanup: by default the excluded types
    for _ in range(3):
        hass.bus.async_fire("noisy_event", {"x": 1})
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    coordinator.store.data.filters = {"event_types": ["noisy_event"]}
    overview = {e["event_type"]: e for e in coordinator.events_overview()}
    assert overview["noisy_event"]["excluded"] and overview["noisy_event"]["deletable"]
    assert not overview.get("state_changed", {"deletable": False})["deletable"]
    preview = await coordinator.async_preview(["events"])
    assert [e["event_type"] for e in preview["events"]["items"]] == ["noisy_event"]
    client = await hass_ws_client(hass)
    res = await _ws(client, {"type": f"{DOMAIN}/clean", "targets": ["events"]})
    assert res["success"] and res["result"]["blocked"] is None
    assert await instance.async_add_executor_job(_event_rows, hass, "noisy_event") == 0
    assert "noisy_event" not in [e["event_type"] for e in coordinator.store.data.analysis["events"]]
    log = coordinator.store.data.history[-1]
    assert log["details"]["deleted"]["event_types"] == ["noisy_event"]

    res = await _ws(
        client, {"type": f"{DOMAIN}/preview", "targets": ["events"], "event_types": ["kept_event"]}
    )
    assert [e["event_type"] for e in res["result"]["events"]["items"]] == ["kept_event"]



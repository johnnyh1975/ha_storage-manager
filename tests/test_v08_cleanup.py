def test_package_customize(tmp_path: Path) -> None:
    """Switched-off statistics end up as customize entries in the package."""
    block = recorder_config.build_block(["sensor.x"], {}, {}, ["sensor.b_rssi", "sensor.a_rssi"])
    assert block["customize"] == ["sensor.a_rssi", "sensor.b_rssi"]
    assert "statistics_off:sensor.a_rssi" in recorder_config.block_items(block)
    body = yaml.safe_load(recorder_config.render_package(block, None))
    assert body["recorder"] == {"exclude": {"entities": ["sensor.x"]}}
    assert body["homeassistant"]["customize"]["sensor.a_rssi"] == {"state_class": None}
    merged = yaml.safe_load(
        recorder_config.render_package({"customize": ["sensor.c"]}, "include_dir_merge_named")
    )
    assert "recorder" not in merged["storage_manager"]

    info = recorder_config.PackagesInfo(
        mode="include_dir_named", directory=tmp_path, file=tmp_path / "storage_manager.yaml"
    )
    recorder_config.write_package(info, block)
    assert recorder_config.read_package(info) == block
    (tmp_path / "storage_manager.yaml").write_text(
        "homeassistant:\n  customize:\n    sensor.y: {friendly_name: Y}\n    sensor.z: x\n"
    )
    assert recorder_config.read_package(info) == {}



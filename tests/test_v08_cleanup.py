async def test_unused_statistics(hass: HomeAssistant, hass_ws_client, tmp_path: Path) -> None:
    """Diagnostic statistics are switched off, others deleted, shown ones kept."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    reg = er.async_get(hass)
    off = reg.async_get_or_create("sensor", "t", "off", suggested_object_id="old_power")
    reg.async_update_entity(off.entity_id, disabled_by=er.RegistryEntryDisabler.USER)
    for entity_id in ("sensor.kitchen_rssi", "sensor.hall_rssi", "sensor.temp"):
        hass.states.async_set(entity_id, "1", {"state_class": "measurement"})
    now = time.time()
    info = {"rows": 100, "rows_24h": 50, "est_bytes": 1000, "est_state_bytes": 1000}
    coordinator.store.data.analysis = {
        "generated_at": now,
        "entities": {
            e: dict(info) for e in ("sensor.kitchen_rssi", "sensor.hall_rssi", "sensor.temp")
        },
        "statistics": {
            "sensor.kitchen_rssi": {
                "source": "recorder",
                "rows": 9000,
                "est_bytes": 4 * MB,
                "last": now,
            },
            "sensor.hall_rssi": {"source": "recorder", "rows": 10, "est_bytes": 1000, "last": now},
            "sensor.temp": {"source": "recorder", "rows": 10, "est_bytes": 1000, "last": now},
            off.entity_id: {"source": "recorder", "rows": 10, "est_bytes": 2 * MB, "last": now},
            "tibber:old": {
                "source": "tibber",
                "rows": 10,
                "est_bytes": 3000,
                "last": now - 200 * 86400,
            },
            "tibber:new": {"source": "tibber", "rows": 10, "est_bytes": 3000, "last": now},
            "sensor.gone": {"source": "recorder", "rows": 10, "est_bytes": 3000, "last": now},
        },
    }
    shown = {"sensor.hall_rssi": EntityUsage(statistics_cards=["Home"])}
    with patch.object(coordinator, "async_usage", AsyncMock(return_value=shown)):
        unused = await coordinator.async_unused_statistics()
        kinds = {i["statistic_id"]: i["kind"] for i in unused["items"]}
        assert kinds == {
            "sensor.kitchen_rssi": "noise",
            off.entity_id: "disabled",
            "tibber:old": "stale_import",
        }
        assert unused["packages"] is False
        # without packages a diagnostic value cannot be switched off
        preview = await coordinator.async_preview(["unused_statistics"])
        assert {i["statistic_id"] for i in preview["unused_statistics"]["items"]} == {
            off.entity_id,
            "tibber:old",
        }
        await coordinator.async_refresh()
        assert coordinator.data["unused_statistics"]["count"] == 2
        assert any(r["id"] == "unused_statistics" for r in coordinator.recommendations())

        _packages(coordinator, tmp_path)
        preview = await coordinator.async_preview(
            ["unused_statistics"], statistic_ids=["sensor.kitchen_rssi"]
        )
        assert preview["unused_statistics"]["switch_off"] == 1
        with patch.object(database, "async_clear_statistics", AsyncMock()) as clear:
            result = await coordinator.async_clean(
                ["unused_statistics"], statistic_ids=["sensor.kitchen_rssi", off.entity_id]
            )
    assert result["blocked"] is None
    assert sorted(clear.call_args.args[1]) == sorted(["sensor.kitchen_rssi", off.entity_id])
    assert coordinator.store.data.stats_off == ["sensor.kitchen_rssi"]
    package = yaml.safe_load((tmp_path / "packages" / "storage_manager.yaml").read_text())
    assert package["homeassistant"]["customize"] == {"sensor.kitchen_rssi": {"state_class": None}}
    assert "sensor.kitchen_rssi" not in coordinator.store.data.analysis["statistics"]
    assert coordinator.recorder_status()["restart_required"]

    # after the restart the state has no state_class: leftovers are cleared
    hass.states.async_set("sensor.kitchen_rssi", "1", {})
    with patch.object(database, "async_clear_statistics", AsyncMock()) as clear:
        assert await coordinator.async_sweep_statistics_off() == ["sensor.kitchen_rssi"]
    clear.assert_called_once()
    hass.states.async_set("sensor.kitchen_rssi", "1", {"state_class": "measurement"})
    assert await coordinator.async_sweep_statistics_off() == []

    client = await hass_ws_client(hass)
    with patch.object(coordinator, "async_usage", AsyncMock(return_value={})):
        res = await _ws(client, {"type": f"{DOMAIN}/unused_statistics"})
        assert res["result"]["off"] == ["sensor.kitchen_rssi"]
        res = await _ws(
            client, {"type": f"{DOMAIN}/statistics_on", "entity_ids": ["sensor.kitchen_rssi"]}
        )
    assert res["result"]["stats_off"] == []
    assert not (tmp_path / "packages" / "storage_manager.yaml").exists()



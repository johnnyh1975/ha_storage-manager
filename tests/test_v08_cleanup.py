async def test_analysis_reads_statistics(hass: HomeAssistant) -> None:
    """The analysis keeps rows, size and the newest row per statistic."""
    from datetime import timedelta

    from homeassistant.components.recorder.models import StatisticMeanType
    from homeassistant.components.recorder.statistics import async_add_external_statistics
    from homeassistant.util import dt as dt_util

    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    start = dt_util.utcnow().replace(minute=0, second=0, microsecond=0) - timedelta(days=200)
    metadata = {
        "has_mean": False,
        "mean_type": StatisticMeanType.NONE,
        "has_sum": True,
        "name": "Old import",
        "source": "tibber",
        "statistic_id": "tibber:old_import",
        "unit_of_measurement": "kWh",
        "unit_class": "energy",
    }
    rows = [
        {"start": start + timedelta(hours=h), "sum": float(h), "state": float(h)} for h in range(3)
    ]
    async_add_external_statistics(hass, metadata, rows)
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    stat = coordinator.store.data.analysis["statistics"]["tibber:old_import"]
    assert stat["rows"] == 3
    assert stat["last"] == pytest.approx((start + timedelta(hours=2)).timestamp())
    assert stat["est_bytes"] > 0
    unused = await coordinator.async_unused_statistics()
    assert [i["statistic_id"] for i in unused["items"]] == ["tibber:old_import"]



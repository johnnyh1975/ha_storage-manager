async def test_deleting_events_keeps_the_recorder_writing(hass: HomeAssistant, caplog) -> None:
    """The next event with the same data is recorded, not lost with a database error."""
    await setup_entry(hass)
    instance = get_instance(hass)
    own = {"name": "Light", "entity_id": "automation.x"}
    shared = {"shared": True}
    hass.bus.async_fire("automation_triggered", own)
    hass.bus.async_fire("automation_triggered", shared)
    hass.bus.async_fire("other_event", shared)
    await async_wait_recording_done(hass)
    assert await database.async_delete_events(hass, ["automation_triggered"]) >= 2
    caplog.set_level(logging.ERROR)
    hass.bus.async_fire("automation_triggered", own)
    await async_wait_recording_done(hass)
    rows = await instance.async_add_executor_job(_event_rows, hass, "automation_triggered")
    assert rows == 1
    assert not [r for r in caplog.records if r.levelno >= logging.ERROR]
    # the data row shared with another event type stayed
    hass.bus.async_fire("other_event", shared)
    await async_wait_recording_done(hass)
    assert await instance.async_add_executor_job(_event_rows, hass, "other_event") == 2
    assert not [r for r in caplog.records if r.levelno >= logging.ERROR]



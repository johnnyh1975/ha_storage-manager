# ------------------------------------------------- undo reverts the settings


async def test_undo_reverts_retention_tier(hass: HomeAssistant) -> None:
    """After undo the tier is back, so the next run keeps the restored rows."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    for value in ("1", "2", "3"):
        hass.states.async_set("sensor.noisy", value)
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    result = await coordinator.async_apply_recorder_changes(retention={"sensor.noisy": "drop"})
    await async_wait_recording_done(hass)
    assert await _states(hass, "sensor.noisy") == 0

    preview = await coordinator.async_undo_preview(result["undo"]["id"])
    assert preview["retention"] == {"sensor.noisy": "default"}
    restored = await coordinator.async_undo(result["undo"]["id"])
    await async_wait_recording_done(hass)
    assert restored["retention"] == {"sensor.noisy": "default"}
    assert "sensor.noisy" not in coordinator.store.data.retention
    assert await _states(hass, "sensor.noisy") == 3

    # the hourly run of "last hour only" leaves them alone now
    await coordinator.async_run_retention(include_drop=True, include_daily=False)
    await async_wait_recording_done(hass)
    assert await _states(hass, "sensor.noisy") == 3


async def test_undo_reverts_exclusion_but_not_later_choices(hass: HomeAssistant) -> None:
    """Undo records the entity again; a tier the user changed since stays."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    for entity_id in ("sensor.a", "sensor.b"):
        hass.states.async_set(entity_id, "1")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    coordinator.store.data.retention["sensor.b"] = "7"
    with patch.object(coordinator, "_async_sync_package", AsyncMock(return_value=True)):
        result = await coordinator.async_apply_recorder_changes(
            retention={"sensor.b": "drop"}, excluded={"sensor.a": True}
        )
        await async_wait_recording_done(hass)
        assert "sensor.a" in coordinator.store.data.excluded
        # the user picks another tier for sensor.b afterwards
        coordinator.store.data.retention["sensor.b"] = "3"
        preview = await coordinator.async_undo_preview(result["undo"]["id"])
        assert preview["include"] == ["sensor.a"]
        assert preview["retention"] == {}
        await coordinator.async_undo(result["undo"]["id"])
    assert "sensor.a" not in coordinator.store.data.excluded
    assert coordinator.store.data.retention["sensor.b"] == "3"
    entry_log = next(
        e for e in reversed(coordinator.store.data.history) if e["action"] == "purge_entities"
    )
    assert entry_log["details"]["revert"]["retention"] == {"sensor.b": ["7", "drop"]}



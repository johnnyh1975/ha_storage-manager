async def test_apply_preview(hass: HomeAssistant, hass_ws_client) -> None:
    """The confirmation knows what applying deletes and the safety chain before it."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    for value in ("1", "2"):
        hass.states.async_set("sensor.p", value)
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    preview = await coordinator.async_apply_preview(
        retention={"sensor.p": "drop"}, excluded={"sensor.q": True}
    )
    assert preview["entities"] == 2
    assert preview["bytes"] > 0
    assert preview["safety"]["backup"]["action"] == "undo"
    nothing = await coordinator.async_apply_preview(
        retention={"sensor.p": "default"}, excluded={"sensor.q": False}
    )
    assert nothing == {"entities": 0, "bytes": 0, "safety": None}
    with pytest.raises(HomeAssistantError):
        await coordinator.async_apply_preview(retention={"sensor.p": "x"}, excluded={})

    client = await hass_ws_client(hass)
    msg = await _ws(client, {"type": f"{DOMAIN}/apply_preview", "retention": {"sensor.p": "1"}})
    assert msg["success"]
    assert msg["result"]["entities"] == 1



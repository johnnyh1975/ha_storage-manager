async def test_actions_and_buttons_need_admin(
    hass: HomeAssistant, hass_read_only_user, hass_admin_user
) -> None:
    """A user without admin rights cannot delete through actions or buttons."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    user = Context(user_id=hass_read_only_user.id)
    for action, data in (
        ("cleanup", {"targets": ["files"], "dry_run": True}),
        ("set_retention", {"entity_id": ["sensor.x"], "tier": "drop"}),
        ("run_nightly", {}),
        ("analyze_database", {}),
    ):
        with pytest.raises(Unauthorized):
            await hass.services.async_call(DOMAIN, action, data, blocking=True, context=user)
    with patch.object(coordinator, "async_clean", AsyncMock()) as clean:
        with pytest.raises(Unauthorized):
            await hass.services.async_call(
                "button",
                "press",
                {"entity_id": "button.storage_manager_repack_database"},
                blocking=True,
                context=user,
            )
        clean.assert_not_awaited()
        await hass.services.async_call(
            "button",
            "press",
            {"entity_id": "button.storage_manager_repack_database"},
            blocking=True,
            context=Context(user_id=hass_admin_user.id),
        )
        clean.assert_awaited_once_with(["repack"])
    response = await hass.services.async_call(
        DOMAIN,
        "cleanup",
        {"targets": ["files"], "dry_run": True},
        blocking=True,
        return_response=True,
        context=Context(user_id=hass_admin_user.id),
    )
    assert response["dry_run"] is True



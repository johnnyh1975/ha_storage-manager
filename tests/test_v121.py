async def test_rotation_uses_a_fresh_list(hass: HomeAssistant) -> None:
    """The rotation reads the backups again and stops when a location fails."""
    entry = await setup_entry(hass, {"backup_rotation": True})
    coordinator = entry.runtime_data
    item = {
        "backup_id": "b1",
        "name": "Old",
        "date": "2026-01-01T00:00:00+00:00",
        "automatic": True,
        "local_agents": ["backup.local"],
        "remote_agents": [],
        "local_size": 100,
        "size": 100,
    }
    failing = {"backups": [item], "local_total": 100, "agent_errors": ["cloud"]}
    with (
        patch.object(backup_mod, "async_list", AsyncMock(return_value=failing)) as listing,
        patch.object(backup_mod, "async_apply_rotation", AsyncMock()) as apply,
    ):
        result = await coordinator.async_clean(["backups"])
    listing.assert_awaited()
    apply.assert_not_awaited()
    assert any("not every backup location" in e for e in result["errors"])

    fine = {**failing, "agent_errors": []}
    with (
        patch.object(backup_mod, "async_list", AsyncMock(return_value=fine)),
        patch.object(backup_mod, "plan_rotation", return_value=[]) as plan,
        patch.object(backup_mod, "async_apply_rotation", AsyncMock(return_value=(0, []))),
    ):
        await coordinator.async_clean(["backups"])
    assert plan.call_args.args[0] == [item]



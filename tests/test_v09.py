def test_template_sensor() -> None:
    """State, unit and classes are carried over; attributes get their own sensor."""
    out = template_builder.build(
        "sensor.weather_home",
        name="Wetter Küche",
        attributes={
            "unit_of_measurement": "°C",
            "device_class": "temperature",
            "state_class": "measurement",
            "forecast": [1, 2],
        },
        extra=["forecast", "it's"],
        language="de-DE",
    )
    body = yaml.safe_load(out["yaml"])
    sensors = body["template"][0]["sensor"]
    main = sensors[0]
    assert main["name"] == "Wetter Küche (Verlauf)"
    assert main["unique_id"] == "storage_manager_weather_home_state"
    assert main["state"] == "{{ states('sensor.weather_home') }}"
    assert main["availability"] == "{{ has_value('sensor.weather_home') }}"
    assert (main["unit_of_measurement"], main["device_class"], main["state_class"]) == (
        "°C",
        "temperature",
        "measurement",
    )
    assert sensors[1]["state"] == "{{ state_attr('sensor.weather_home', 'forecast') }}"
    assert "\\'" in sensors[2]["state"]  # the quote inside the name is escaped
    assert out["entity_ids"][0] == "sensor.wetter_kuche_verlauf"
    assert out["entity_ids"][1] == "sensor.wetter_kuche_forecast"


def test_template_binary() -> None:
    """On/off domains become a binary sensor; English names by default."""
    out = template_builder.build(
        "binary_sensor.door",
        name="Door",
        attributes={"device_class": "door", "last_seen": "x"},
        extra=[],
        language="fr",
    )
    body = yaml.safe_load(out["yaml"])
    assert list(body["template"][0]) == ["binary_sensor"]
    main = body["template"][0]["binary_sensor"][0]
    assert main["state"] == "{{ is_state('binary_sensor.door', 'on') }}"
    assert main["device_class"] == "door"
    assert out["entity_ids"] == ["binary_sensor.door_history"]
    switch = template_builder.build(
        "switch.pump",
        name="Pump",
        attributes={"device_class": "outlet"},
        extra=["power"],
        language="en",
    )
    body = yaml.safe_load(switch["yaml"])
    # the attribute sensor comes first, the switch copy has no device class
    assert list(body["template"][0]) == ["sensor"]
    assert "device_class" not in body["template"][1]["binary_sensor"][0]


async def test_attribute_template(hass: HomeAssistant, hass_ws_client) -> None:
    """The template lists what reads the history; errors for unknown input."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    hass.states.async_set(
        "sensor.weather",
        "3",
        {"friendly_name": "Weather", "forecast": [1], "unit_of_measurement": "°C"},
    )
    hass.states.async_set("sensor.weather_history", "1")
    usage = {
        "sensor.weather": EntityUsage(
            automations=["automation.a"],
            dashboards=[{"dashboard": "Home", "card": "history-graph", "days": 2}],
            statistics_cards=["Energy"],
            helpers=[
                {"title": "Avg", "domain": "statistics"},
                {"title": "Group", "domain": "group"},
            ],
            energy=True,
        )
    }
    with patch.object(coordinator, "async_usage", AsyncMock(return_value=usage)):
        result = await coordinator.async_attribute_template("sensor.weather", ["forecast"])
        assert [s["type"] for s in result["switch"]] == [
            "dashboard",
            "statistics_card",
            "helper",
            "energy",
        ]
        assert result["taken"] == ["sensor.weather_history"]
        assert result["packages"] is False
        with pytest.raises(HomeAssistantError):
            await coordinator.async_attribute_template("sensor.nope", [])
        with pytest.raises(HomeAssistantError):
            await coordinator.async_attribute_template("sensor.weather", ["missing"])
        client = await hass_ws_client(hass)
        msg = await _ws(
            client,
            {
                "type": f"{DOMAIN}/attribute_template",
                "entity_id": "sensor.weather",
                "language": "de",
            },
        )
    assert msg["success"]
    assert "(Verlauf)" in msg["result"]["yaml"]
    assert "template" in yaml.safe_load(msg["result"]["yaml"])
    with patch.object(coordinator, "async_usage", AsyncMock(return_value={})):
        result = await coordinator.async_attribute_template("sensor.weather", [])
    assert result["switch"] == []



async def test_dead_without_database(hass: HomeAssistant) -> None:
    """Without the database only the state's own age counts; nothing found is cheap."""
    coordinator, ids, _values, _usage = await _dead_setup(hass)
    with (
        patch.object(database, "async_last_values", AsyncMock(side_effect=RuntimeError)),
        patch.object(coordinator, "async_usage", AsyncMock(return_value={})),
    ):
        dead = await coordinator.async_dead_entities()
    assert {i["entity_id"] for i in dead["items"]} == {ids["unrecorded"], ids["gone"]}
    for entity_id in list(hass.states.async_entity_ids()):
        hass.states.async_remove(entity_id)
    assert (await coordinator.async_dead_entities())["items"] == []



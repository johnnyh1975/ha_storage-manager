async def test_last_values(hass: HomeAssistant) -> None:
    """The newest real value and the oldest row come from the database."""
    await setup_entry(hass)
    hass.states.async_set("sensor.flaky", "5")
    hass.states.async_set("sensor.flaky", "unavailable")
    hass.states.async_set("sensor.never", "unknown")
    hass.states.async_remove("sensor.never")  # recorded as a row without a state
    hass.states.async_set("sensor.never", "unavailable")
    await async_wait_recording_done(hass)
    values = await database.async_last_values(hass, ["sensor.flaky", "sensor.never", "sensor.none"])
    assert values["sensor.flaky"]["last"] is not None
    assert values["sensor.never"]["last"] is None
    assert values["sensor.never"]["oldest"] is not None
    assert "sensor.none" not in values
    assert await database.async_last_values(hass, []) == {}


async def _dead_setup(hass: HomeAssistant):
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    loaded = MockConfigEntry(domain="test", state=ConfigEntryState.LOADED)
    loaded.add_to_hass(hass)
    stopped = MockConfigEntry(domain="test2", state=ConfigEntryState.SETUP_RETRY)
    stopped.add_to_hass(hass)
    reg = er.async_get(hass)
    ids = {}
    for key, cfg in (
        ("old", loaded),
        ("fresh", loaded),
        ("gone", loaded),
        ("used", loaded),
        ("never", loaded),
        ("unrecorded", loaded),
        ("retry", stopped),
        ("free", None),
    ):
        ids[key] = reg.async_get_or_create(
            "sensor", "test", key, suggested_object_id=f"dead_{key}", config_entry=cfg
        ).entity_id
    now = time.time()
    for key, entity_id in ids.items():
        attrs = {"restored": True} if key == "gone" else {}
        stamp = now - 20 * DAY if key == "unrecorded" else None
        hass.states.async_set(entity_id, "unavailable", attrs, timestamp=stamp)
    hass.states.async_set("sensor.yaml_dead", "unavailable")
    hass.states.async_set("sensor.alive", "3")
    values = {
        ids["old"]: {"last": now - 10 * DAY, "oldest": now - 30 * DAY},
        ids["fresh"]: {"last": now - 1 * DAY, "oldest": now - 30 * DAY},
        ids["gone"]: {"last": now - 1 * DAY, "oldest": now - 30 * DAY},
        ids["used"]: {"last": now - 10 * DAY, "oldest": now - 30 * DAY},
        ids["never"]: {"last": None, "oldest": now - 9 * DAY},
        ids["retry"]: {"last": now - 10 * DAY, "oldest": now - 30 * DAY},
        ids["free"]: {"last": now - 10 * DAY, "oldest": now - 30 * DAY},
        "sensor.yaml_dead": {"last": now - 10 * DAY, "oldest": now - 30 * DAY},
    }
    coordinator.store.data.analysis = {
        "generated_at": now,
        "entities": {ids["old"]: {"est_bytes": 5000}, ids["never"]: {"est_bytes": 100}},
        "statistics": {ids["old"]: {"source": "recorder", "est_bytes": 700}},
    }
    usage = {ids["used"]: EntityUsage(automations=["automation.x"])}
    # placeholders count only some time after the start
    coordinator.setup_at = now - 2 * 3600
    return coordinator, ids, values, usage


async def test_dead_entities(hass: HomeAssistant, hass_ws_client) -> None:
    """Detection, usage, disabling, enabling and deleting."""
    coordinator, ids, values, usage = await _dead_setup(hass)
    with (
        patch.object(database, "async_last_values", AsyncMock(return_value=values)),
        patch.object(coordinator, "async_usage", AsyncMock(return_value=usage)),
    ):
        dead = await coordinator.async_dead_entities()
        by_id = {i["entity_id"]: i for i in dead["items"]}
        assert set(by_id) == {
            ids["old"],
            ids["gone"],
            ids["used"],
            ids["never"],
            ids["unrecorded"],
            ids["free"],
            "sensor.yaml_dead",
        }
        assert by_id[ids["gone"]]["kind"] == "gone"
        assert by_id["sensor.yaml_dead"]["kind"] == "yaml"
        assert not by_id["sensor.yaml_dead"]["selectable"]
        assert not by_id[ids["used"]]["selectable"]
        assert by_id[ids["used"]]["used"]["automations"] == ["automation.x"]
        assert by_id[ids["never"]]["no_value_recorded"]
        assert by_id[ids["old"]]["bytes"] == 5700
        assert dead["bytes"] == 5800
        assert dead["items"][0]["entity_id"] == ids["old"]  # biggest selectable first

        await coordinator.async_refresh()
        assert coordinator.data["dead_entities"] == {"count": 5, "bytes": 5800}
        rec = next(r for r in coordinator.recommendations() if r["id"] == "dead_entities")
        assert rec["count"] == 5

        # nothing without an explicit selection
        assert (await coordinator.async_preview(["dead"]))["dead"]["items"] == []
        preview = await coordinator.async_preview(["dead"], entity_ids=[ids["old"], ids["used"]])
        assert [i["entity_id"] for i in preview["dead"]["items"]] == [ids["old"]]
        assert "safety" in preview

        result = await coordinator.async_disable_dead([ids["free"], ids["used"]])
        assert result == {"disabled": [ids["free"]], "skipped": [ids["used"]]}
        reg = er.async_get(hass)
        assert reg.async_get(ids["free"]).disabled_by is er.RegistryEntryDisabler.USER
        assert ids["free"] in coordinator.store.data.disabled_dead

        with (
            patch.object(database, "async_purge_entities", AsyncMock(return_value=0)) as purge,
            patch.object(database, "async_clear_statistics", AsyncMock()) as clear,
            patch.object(database, "async_wait_idle", AsyncMock(return_value=True)),
        ):
            result = await coordinator.async_clean(["dead"], entity_ids=[ids["old"]])
        assert result["blocked"] is None
        assert result["results"]["dead"] == 5700
        purge.assert_awaited_once_with(hass, [ids["old"]], 0)
        clear.assert_awaited_once_with(hass, [ids["old"]])
        assert reg.async_get(ids["old"]).disabled_by is er.RegistryEntryDisabler.USER
        assert ids["old"] not in coordinator.store.data.analysis["entities"]
        assert ids["old"] not in coordinator.store.data.analysis["statistics"]

        dead = await coordinator.async_dead_entities()
        assert {d["entity_id"] for d in dead["disabled"]} == {ids["free"], ids["old"]}

        # someone else disabled it in between: we leave it alone
        reg.async_update_entity(ids["old"], disabled_by=er.RegistryEntryDisabler.INTEGRATION)
        result = await coordinator.async_enable_dead([ids["free"], ids["old"], ids["used"]])
        assert result == {"enabled": [ids["free"]]}
        assert reg.async_get(ids["free"]).disabled_by is None
        assert reg.async_get(ids["old"]).disabled_by is er.RegistryEntryDisabler.INTEGRATION
        assert coordinator.store.data.disabled_dead == {}
        assert [h["action"] for h in coordinator.store.data.history[-3:]] == [
            "disable_dead",
            "cleanup",
            "enable_dead",
        ]

        client = await hass_ws_client(hass)
        msg = await _ws(client, {"type": f"{DOMAIN}/dead_entities"})
        assert msg["success"]
        assert msg["result"]["disabled"] == []
        msg = await _ws(client, {"type": f"{DOMAIN}/disable_dead", "entity_ids": [ids["never"]]})
        assert msg["result"]["disabled"] == [ids["never"]]
        msg = await _ws(client, {"type": f"{DOMAIN}/enable_dead", "entity_ids": [ids["never"]]})
        assert msg["result"]["enabled"] == [ids["never"]]
        msg = await _ws(client, {"type": f"{DOMAIN}/disable_dead", "entity_ids": []})
        assert not msg["success"]
        msg = await _ws(
            client,
            {"type": f"{DOMAIN}/preview", "targets": ["dead"], "entity_ids": [ids["never"]]},
        )
        assert [i["entity_id"] for i in msg["result"]["dead"]["items"]] == [ids["never"]]

    with pytest.raises(HomeAssistantError):
        await coordinator.async_disable_dead([])



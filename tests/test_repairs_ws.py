async def test_ws_commands(hass: HomeAssistant, hass_ws_client) -> None:
    """Remaining websocket commands, errors and the subscription."""
    entry = await setup_entry(hass)
    client = await hass_ws_client(hass)
    msg_id = 0

    async def call(payload):
        nonlocal msg_id
        msg_id += 1
        await client.send_json({"id": msg_id, **payload})
        while True:
            msg = await client.receive_json()
            if msg["id"] == msg_id and msg["type"] == "result":
                return msg

    assert (await call({"type": f"{DOMAIN}/analyze"}))["success"]
    assert (await call({"type": f"{DOMAIN}/orphans"}))["success"]
    assert (await call({"type": f"{DOMAIN}/refresh"}))["result"] == {"ok": True}
    assert (await call({"type": f"{DOMAIN}/backups"}))["success"]
    bad = await call(
        {"type": f"{DOMAIN}/clean", "targets": ["files"], "hog_keys": ["esphome_build"]}
    )
    assert bad["success"]
    entry.runtime_data.analysis_running = True
    err = await call({"type": f"{DOMAIN}/analyze"})
    assert err["success"] is False and err["error"]["code"] == "storage_manager_error"
    entry.runtime_data.analysis_running = False

    sub = await call({"type": f"{DOMAIN}/subscribe"})
    assert sub["success"]
    entry.runtime_data.async_set_updated_data(entry.runtime_data.data)
    event = await client.receive_json()
    assert event["type"] == "event" and event["event"] == {"updated": True}
    await call({"type": "unsubscribe_events", "subscription": sub["id"]})

    assert await hass.config_entries.async_unload(entry.entry_id)
    await hass.async_block_till_done()
    err = await call({"type": f"{DOMAIN}/overview"})
    assert err["success"] is False



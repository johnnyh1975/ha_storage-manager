async def test_buttons_diagnostics_and_schedules(hass: HomeAssistant) -> None:
    """Buttons call the coordinator; diagnostics render; timers fire."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    with patch.object(coordinator, "async_clean", AsyncMock()) as clean:
        await hass.services.async_call(
            "button",
            "press",
            {"entity_id": "button.storage_manager_repack_database"},
            blocking=True,
        )
        clean.assert_awaited_once_with(["repack"])
    diag = await async_get_config_entry_diagnostics(hass, entry)
    assert diag["options"]["low_space_percent"] == 15

    with (
        patch.object(coordinator, "async_run_retention", AsyncMock()) as retention,
        patch.object(coordinator, "async_schedule_analysis") as analysis,
    ):
        now = dt_util.now()
        for target in (
            now.replace(minute=17, second=0, microsecond=0) + timedelta(hours=1),
            now.replace(hour=4, minute=37, second=0, microsecond=0) + timedelta(days=1),
            now.replace(hour=3, minute=5, second=0, microsecond=0) + timedelta(days=2),
        ):
            async_fire_time_changed(hass, target)
            await hass.async_block_till_done()
    assert retention.await_count >= 2
    assert analysis.called


async def test_reload_and_remove(hass: HomeAssistant) -> None:
    """Options reload the entry; removal deletes the package file."""
    config = Path(hass.config.config_dir)
    (config / "configuration.yaml").write_text(
        "homeassistant:\n  packages: !include_dir_named packages\n"
    )
    entry = await setup_entry(hass)
    await entry.runtime_data.async_apply_recorder_changes(
        excluded={"sensor.x": True}, purge_now=False
    )
    assert (config / "packages" / PACKAGE_FILE).exists()
    hass.config_entries.async_update_entry(entry, options={**entry.options, "keep_daily": 3})
    await hass.async_block_till_done()
    assert entry.runtime_data.options["keep_daily"] == 3
    assert await hass.config_entries.async_remove(entry.entry_id)
    await hass.async_block_till_done()
    assert not (config / "packages" / PACKAGE_FILE).exists()

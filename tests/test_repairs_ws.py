def _set_disk(coordinator, free_pct: float, days: float | None = None) -> None:
    data = dict(coordinator.data)
    total = 100 * GB
    data["disk"] = {
        "total": total,
        "used": total * (1 - free_pct / 100),
        "free": total * free_pct / 100,
        "percent_used": 100 - free_pct,
    }
    data["forecast"] = {"growth_per_day": 500 * 1024**2 if days else None, "days_until_full": days}
    coordinator.data = data


async def test_issue_lifecycle(hass: HomeAssistant) -> None:
    """Low space, forecast, restart and packages issues come and go."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    registry = ir.async_get(hass)

    _set_disk(coordinator, 3, days=4)
    coordinator.data["recorder"] = {
        **coordinator.data["recorder"],
        "restart_required": True,
        "pending_restart": ["a"],
        "unwritten": ["a"],
    }
    repairs.async_update_issues(hass, coordinator)
    low = registry.async_get_issue(DOMAIN, "low_space")
    assert low.severity == ir.IssueSeverity.ERROR
    for issue_id in ("disk_full_forecast", "restart_required", "packages_missing"):
        assert registry.async_get_issue(DOMAIN, issue_id) is not None

    _set_disk(coordinator, 10)
    repairs.async_update_issues(hass, coordinator)
    assert registry.async_get_issue(DOMAIN, "low_space").severity == ir.IssueSeverity.WARNING

    _set_disk(coordinator, 80)
    coordinator.data["recorder"] = {
        **coordinator.data["recorder"],
        "restart_required": False,
        "pending_restart": [],
        "unwritten": [],
    }
    repairs.async_update_issues(hass, coordinator)
    for issue_id in ("low_space", "disk_full_forecast", "restart_required", "packages_missing"):
        assert registry.async_get_issue(DOMAIN, issue_id) is None

    coordinator.data = None
    repairs.async_update_issues(hass, coordinator)


async def test_cleanup_fix_flow(hass: HomeAssistant) -> None:
    """The fix flow aborts when nothing is reclaimable and cleans otherwise."""
    assert await async_setup_component(hass, REPAIRS_DOMAIN, {})
    entry = await setup_entry(hass)
    flow = await repairs.async_create_fix_flow(hass, "low_space", None)
    flow.hass = hass
    result = await flow.async_step_init()
    assert result["type"] == "abort"
    assert result["reason"] == "nothing_to_clean"

    build = Path(hass.config.config_dir) / "esphome" / ".esphome" / "build"
    build.mkdir(parents=True)
    (build / "fw.bin").write_bytes(b"x" * 4096)
    entry.runtime_data.invalidate("files")
    flow = await repairs.async_create_fix_flow(hass, "disk_full_forecast", None)
    flow.hass = hass
    result = await flow.async_step_init()
    assert result["type"] == "form"
    assert result["description_placeholders"]["files"] == "4.0 KB"
    result = await flow.async_step_confirm({})
    assert result["type"] == "create_entry"
    assert not build.exists()



async def test_statistics_age_checks_again_after_a_failed_check(hass: HomeAssistant) -> None:
    """A check that could not run is repeated before the nightly limit deletes anything."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    plan = {"items": [{"statistic_id": "s", "metadata_id": 1, "rows": 2, "cutoff": 1.0}]}
    coordinator.store.data.integrity = {"result": safety.RESULT_ERROR, "at": 0}
    deleted = AsyncMock(return_value=2)
    with (
        patch.object(coordinator.statistics_age, "status", return_value={"active": True}),
        patch.object(coordinator.statistics_age, "async_current", AsyncMock(return_value=plan)),
        patch.object(coordinator.statistics_age, "async_delete", deleted),
        patch.object(database, "sqlite_path", return_value="db"),
    ):
        still = AsyncMock(return_value={"result": safety.RESULT_ERROR})
        with patch.object(safety, "async_integrity", still):
            assert await coordinator.async_run_statistics_age() == 0
        still.assert_awaited_once()
        deleted.assert_not_awaited()
        fine = AsyncMock(return_value={"result": safety.RESULT_OK})
        with patch.object(safety, "async_integrity", fine):
            assert await coordinator.async_run_statistics_age() == 2


async def test_detail_says_when_the_analysis_ran(hass: HomeAssistant) -> None:
    """Size, rows and rate come from the analysis: the detail names its time."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    coordinator.store.data.analysis = {
        "generated_at": 1234.5,
        "entities": {"sensor.a": {"rows": 3}},
    }
    detail = await coordinator.async_entity_detail("sensor.a")
    assert detail["analysis_at"] == 1234.5
    assert detail["info"] == {"rows": 3}
    coordinator.store.data.analysis = None
    assert (await coordinator.async_entity_detail("sensor.a"))["analysis_at"] is None

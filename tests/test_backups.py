@dataclass
class _Status:
    size: int


@dataclass
class _Backup:
    backup_id: str
    name: str
    date: str
    agents: dict
    with_automatic_settings: bool | None = True


@dataclass
class FakeManager:
    """Minimal stand-in for homeassistant.components.backup.BackupManager."""

    items: dict = field(default_factory=dict)
    errors: dict = field(default_factory=dict)
    delete_errors: dict = field(default_factory=dict)
    local_backup_agents: dict = field(default_factory=dict)
    deleted: list = field(default_factory=list)

    async def async_get_backups(self):
        return self.items, self.errors

    async def async_delete_backup(self, backup_id, *, agent_ids=None):
        self.deleted.append((backup_id, agent_ids))
        return self.delete_errors.get(backup_id, {})


def _make(n: int, remote: bool = True) -> FakeManager:
    now = datetime(2026, 11, 13, 3, 0, tzinfo=UTC)
    items = {}
    for i in range(n):
        agents = {"hassio.local": _Status(100)}
        if remote:
            agents["hassio.nas"] = _Status(100)
        items[f"b{i}"] = _Backup(
            f"b{i}", f"Backup {i}", (now - timedelta(days=i)).isoformat(), agents
        )
    return FakeManager(items=items)


async def test_list_without_backup_integration(hass: HomeAssistant) -> None:
    """No backup integration -> None."""
    assert await backups.async_list(hass) is None


async def test_list_and_rotate(hass: HomeAssistant) -> None:
    """Local/remote split, totals, rotation deletes only local copies."""
    manager = _make(40)
    manager.errors = {"cloud.cloud": RuntimeError("offline")}
    with patch.object(backups, "_manager", return_value=manager):
        listed = await backups.async_list(hass)
        assert listed["local_total"] == 4000
        assert listed["agent_errors"] == ["cloud.cloud"]
        assert listed["backups"][0]["backup_id"] == "b0"
        plan = backups.plan_rotation(
            listed["backups"], keep_daily=3, keep_weekly=1, keep_monthly=1, require_offsite=True
        )
        manager.delete_errors = {"b39": {"hassio.local": RuntimeError("busy")}}
        freed, errors = await backups.async_apply_rotation(hass, plan)
    to_delete = [p for p in plan if p["action"] == "delete_local"]
    assert freed == (len(to_delete) - 1) * 100
    assert len(errors) == 1 and "busy" in errors[0]
    assert all(agent_ids == ["hassio.local"] for _, agent_ids in manager.deleted)


async def test_apply_without_manager(hass: HomeAssistant) -> None:
    """Without the backup integration nothing happens."""
    freed, errors = await backups.async_apply_rotation(hass, [{"action": "delete_local"}])
    assert freed == 0
    assert errors


def test_plan_handles_bad_dates_and_empty() -> None:
    """Unparseable dates are kept, empty lists give an empty plan."""
    assert (
        backups.plan_rotation(
            [], keep_daily=1, keep_weekly=1, keep_monthly=1, require_offsite=False
        )
        == []
    )
    items = [
        {
            "backup_id": "x",
            "name": "x",
            "date": "2026-11-13T03:00:00+00:00",
            "local_agents": ["backup.local"],
            "remote_agents": [],
            "local_size": 1,
        },
        {
            "backup_id": "y",
            "name": "y",
            "date": "0000-garbage",
            "local_agents": ["backup.local"],
            "remote_agents": [],
            "local_size": 1,
        },
    ]
    plan = backups.plan_rotation(
        items, keep_daily=1, keep_weekly=0, keep_monthly=0, require_offsite=False
    )
    reasons = {p["backup_id"]: p["reason"] for p in plan}
    assert reasons["y"] == "unknown_date"



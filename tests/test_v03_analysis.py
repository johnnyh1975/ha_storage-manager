async def test_coordinator_progress_and_stop(hass: HomeAssistant, hass_ws_client) -> None:
    """Progress is published, stop cancels, the old analysis stays."""
    entry = await setup_entry(hass)
    await hass.async_block_till_done(wait_background_tasks=True)
    coordinator = entry.runtime_data
    await _record(hass)
    first = await coordinator.async_run_analysis()
    assert coordinator.analysis_progress is None
    assert coordinator.stop_analysis() is False

    seen: list[Any] = []
    real = database.async_analyze

    async def _analyze(hass: HomeAssistant, control: Any, previous: Any, **kwargs: Any) -> Any:
        coordinator._set_progress("states", 0.5)
        seen.append(coordinator.data["database"]["analysis_progress"])
        assert coordinator.stop_analysis() is True
        return await real(hass, control, previous, **kwargs)

    with patch.object(database, "async_analyze", _analyze):
        await coordinator.async_refresh()
        with pytest.raises(database.AnalysisCancelled):
            await coordinator.async_run_analysis()
    assert coordinator.store.data.analysis is first
    assert coordinator.analysis_progress is None
    # progress outside a run is ignored
    coordinator._set_progress("states", 0.3)
    assert coordinator.analysis_progress is None

    client = await hass_ws_client(hass)
    with patch.object(database, "async_analyze", _analyze):
        await client.send_json({"id": 1, "type": f"{DOMAIN}/analyze"})
        msg = await client.receive_json()
    assert msg["success"], msg
    assert msg["result"] == {"cancelled": True}
    await client.send_json({"id": 2, "type": f"{DOMAIN}/stop_analysis"})
    msg = await client.receive_json()
    assert msg["result"] == {"stopping": False}
    await client.send_json({"id": 3, "type": f"{DOMAIN}/analyze", "force_sizes": True})
    msg = await client.receive_json()
    assert msg["success"] and msg["result"]["cancelled"] is False

    # the background run swallows a stop and other failures
    with patch.object(
        coordinator, "async_run_analysis", side_effect=database.AnalysisCancelled("x")
    ):
        coordinator.async_schedule_analysis()
        await hass.async_block_till_done(wait_background_tasks=True)
    with patch.object(coordinator, "async_run_analysis", side_effect=RuntimeError("gone")):
        coordinator.async_schedule_analysis()
        await hass.async_block_till_done(wait_background_tasks=True)

    # the executor reports through the event loop
    coordinator.analysis_running = True
    coordinator._on_progress("events", 1.0)
    await hass.async_block_till_done()
    assert coordinator.analysis_progress == {"phase": "events", "share": 1.0}
    coordinator.analysis_running = False
    coordinator.analysis_progress = None



async def test_chunked_equals_single_pass(hass: HomeAssistant) -> None:
    """Tiny chunks give the same numbers as one big chunk; progress ends at 1."""
    await setup_entry(hass)
    await _record(hass)
    progress: list[tuple[str, float]] = []
    small = await database.async_analyze(
        hass, _small_steps(progress=lambda p, s: progress.append((p, s)))
    )
    big = await database.async_analyze(hass, database.AnalysisControl(pause=0))
    for entity_id in ("sensor.chatty", "sensor.counter", "sensor.twin_a"):
        for key in ("rows", "rows_24h", "state_len", "attr_len", "attr_only"):
            assert small["entities"][entity_id][key] == big["entities"][entity_id][key], key
    assert small["totals"]["event_rows"] == big["totals"]["event_rows"]
    assert small["statistics"] == big["statistics"]
    assert progress[-1] == ("events", 1.0)
    shares = [s for _, s in progress]
    assert shares == sorted(shares)
    assert {p for p, _ in progress} >= {"states", "state_attributes", "events"}

    chatty = big["entities"]["sensor.chatty"]
    assert chatty["attr_only"] == 29  # the first row is a real state change
    counter = big["entities"]["sensor.counter"]
    assert counter["attr_only"] == 0
    # the shared attribute row is split, not counted twice
    twin_a = big["entities"]["sensor.twin_a"]["attr_len"]
    twin_b = big["entities"]["sensor.twin_b"]["attr_len"]
    assert twin_a == twin_b
    assert twin_a < 300
    assert big["totals"]["shared_attribute_rows"] >= 1
    assert any(e["event_type"] == "custom_event" for e in big["events"])



async def test_empty_database_and_stop(hass: HomeAssistant) -> None:
    """Empty tables finish at once; a stop request cancels before the next chunk."""
    await setup_entry(hass)
    control = database.AnalysisControl(pause=0)
    with patch.object(database, "_range", return_value=None):
        result = await database.async_analyze(hass, control)
    assert result["totals"]["state_rows"] == 0

    await _record(hass)
    control = _small_steps()
    control.stop.set()
    with pytest.raises(database.AnalysisCancelled):
        await database.async_analyze(hass, control)

    # stopped after the chunks, before the final queries
    calls = {"n": 0}
    control = database.AnalysisControl(pause=0)
    real = database._chunks

    def _chunks(hass: HomeAssistant, ctl: Any, table: str, run: Any) -> None:
        real(hass, ctl, table, run)
        calls["n"] += 1
        if table == "events":
            ctl.stop.set()

    with (
        patch.object(database, "_chunks", _chunks),
        pytest.raises(database.AnalysisCancelled),
    ):
        await database.async_analyze(hass, control)
    assert calls["n"] == 5



def test_attribute_drivers() -> None:
    """Changing keys are drivers and come first; sizes are averaged."""
    blobs = [
        json.dumps({"rssi": -40 - i, "label": "x" * 50, "gone": 1})
        if i < 2
        else json.dumps({"rssi": -40 - i, "label": "x" * 50})
        for i in range(10)
    ]
    blobs.append("not json")
    drivers = database.attribute_drivers(blobs)
    names = [d["name"] for d in drivers]
    assert names[0] == "rssi"
    rssi = drivers[0]
    assert rssi["driver"] is True
    label = next(d for d in drivers if d["name"] == "label")
    assert label["driver"] is False
    assert label["share"] > rssi["share"]
    assert next(d for d in drivers if d["name"] == "gone")["change_rate"] > 0
    assert database.attribute_drivers([]) == []
    single = database.attribute_drivers(['{"a": 1}'])
    assert single == [{"name": "a", "bytes": 6, "share": 1.0, "change_rate": 0.0, "driver": False}]



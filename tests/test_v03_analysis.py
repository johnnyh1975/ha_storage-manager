async def test_table_sizes_cache(hass: HomeAssistant) -> None:
    """SQLite table sizes are reused for a day unless forced."""
    await setup_entry(hass)
    previous = {"table_sizes": {"states": 123}, "table_sizes_at": time.time()}
    result = await database.async_analyze(hass, database.AnalysisControl(pause=0), previous)
    assert result["table_sizes"] == {"states": 123}
    assert result["table_sizes_at"] == previous["table_sizes_at"]
    forced = await database.async_analyze(
        hass, database.AnalysisControl(pause=0), previous, force_sizes=True
    )
    assert forced["table_sizes_at"] > previous["table_sizes_at"]
    stale = {"table_sizes": {"states": 123}, "table_sizes_at": 0}
    again = await database.async_analyze(hass, database.AnalysisControl(pause=0), stale)
    assert again["table_sizes_at"] > 0
    assert again["totals"]["estimated_sizes"] is (not again["table_sizes"])



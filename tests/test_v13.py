async def test_export_in_short_sessions(hass: HomeAssistant) -> None:
    """The export through one session per query writes the same rows."""
    from custom_components.storage_manager import undo

    from .test_v10_undo import _seed

    await setup_entry(hass)
    await _seed(hass)
    spec = undo.Spec(
        states={"sensor.gone": None}, statistics=["demo:import"], event_types=["noisy_event"]
    )
    one = undo.path_for(hass.config.config_dir, undo.new_id())
    many = undo.path_for(hass.config.config_dir, undo.new_id())
    a = await database.async_read(hass, lambda s: undo.export(s, one, spec))
    b = await database.async_read_short(hass, lambda s: undo.export(s, many, spec))
    assert a["rows"] == b["rows"] == {"states": 3, "statistics": 4, "events": 3}
    rows = await database.async_read_short(
        hass, lambda s: s.execute(database.text("SELECT 1 AS one")).mappings().all()
    )
    assert rows[0]["one"] == 1

async def test_analysis_lives_in_its_own_file(hass: HomeAssistant, hass_storage) -> None:
    """The main file stays small; an analysis from before 1.3 moves over."""
    hass_storage["storage_manager.data"] = {
        "version": 1,
        "key": "storage_manager.data",
        "data": {"analysis": {"entities": {"sensor.old": {"rows": 1}}}},
    }
    store = store_mod.ManagerStore(hass)
    await store.async_load()
    assert set(store.data.analysis["entities"]) == {"sensor.old"}
    assert "analysis" not in store._main()

    hass_storage[store_mod.ANALYSIS_KEY] = {
        "version": 1,
        "key": store_mod.ANALYSIS_KEY,
        "data": {"analysis": {"entities": {"sensor.new": {"rows": 2}}}},
    }
    loaded = await store.async_load()
    assert set(loaded.analysis["entities"]) == {"sensor.new"}
    assert store._analysis() == {"analysis": loaded.analysis}

    # many changes in a row do not keep pushing the analysis write back
    with patch.object(store._analysis_store, "async_delay_save") as delayed:
        store._analysis_due = None
        store.schedule_save()
        store.schedule_save()
        assert delayed.call_count == 1
        store._analysis_due = time.monotonic() - 1
        store.schedule_save()
        assert delayed.call_count == 2



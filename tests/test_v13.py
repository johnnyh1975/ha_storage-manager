async def test_undo_survives_a_long_history(hass: HomeAssistant) -> None:
    """After the history rolled over, Undo still sets the retention back."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    for value in ("1", "2", "3"):
        hass.states.async_set("sensor.noisy", value)
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    result = await coordinator.async_apply_recorder_changes(retention={"sensor.noisy": "drop"})
    await async_wait_recording_done(hass)
    undo_id = result["undo"]["id"]
    for n in range(60):
        coordinator.store.log("statistics_retention", 0, {"n": n})
    assert all((h.get("details") or {}).get("undo") is None for h in coordinator.store.data.history)
    # as after a restart: the history and the kept entry are separate objects
    coordinator.store.data.undo_meta[undo_id] = copy.deepcopy(
        coordinator.store.data.undo_meta[undo_id]
    )
    preview = await coordinator.async_undo_preview(undo_id)
    assert preview["retention"] == {"sensor.noisy": "default"}
    await coordinator.async_undo(undo_id)
    await async_wait_recording_done(hass)
    assert "sensor.noisy" not in coordinator.store.data.retention
    assert coordinator.store.data.undo_meta[undo_id]["details"]["undone"]

    # the store keeps it across a reload
    data = coordinator.store.data.as_dict()
    again = type(coordinator.store.data).from_dict(data)
    assert undo_id in again.undo_meta
    assert type(coordinator.store.data).from_dict({"undo_meta": "x"}).undo_meta == {}

    # when the file is gone, so is what Undo knew about it
    with patch("custom_components.storage_manager.undo_service.undo.existing", return_value=[]):
        await coordinator.async_prune_undo()
    assert coordinator.store.data.undo_meta == {}


async def test_history_copy_is_marked_undone(hass: HomeAssistant) -> None:
    """The history line of a cleanup shows it was undone, also after a restart."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    await _orphan(hass, "sensor.gone")
    await coordinator.async_run_analysis()
    result = await coordinator.async_clean(["orphans"])
    undo_id = result["undo"]["id"]
    meta = coordinator.store.data.undo_meta
    meta[undo_id] = copy.deepcopy(meta[undo_id])
    await coordinator.async_undo(undo_id)
    logged = next(
        h
        for h in coordinator.store.data.history
        if isinstance((h.get("details") or {}).get("undo"), dict)
    )
    assert logged["details"]["undone"] == meta[undo_id]["details"]["undone"]



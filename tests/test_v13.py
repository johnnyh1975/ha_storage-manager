async def test_scheduled_runs_wait_for_a_cleanup(hass: HomeAssistant) -> None:
    """Retention and statistics runs never delete next to a cleanup."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    coordinator.store.data.retention = {"sensor.a": "drop"}
    order: list[str] = []

    async def purge(*args, **kwargs):  # noqa: ANN002, ANN003, ANN202 - spy
        order.append(f"purge:{coordinator.store.data.running['action']}")
        return 0

    with patch.object(database, "async_purge_entities", purge):
        await coordinator._lock.acquire()
        run = asyncio.ensure_future(
            coordinator.async_run_retention(include_drop=True, include_daily=False)
        )
        await asyncio.sleep(0.05)
        assert order == []  # waits for the lock
        order.append("cleanup done")
        coordinator._lock.release()
        assert await run == 1
    assert order == ["cleanup done", "purge:retention"]
    assert coordinator.store.data.running is None
    # nothing to do: no lock, no marker
    coordinator.store.data.retention = {}
    assert await coordinator.async_run_retention(include_drop=True, include_daily=True) == 0



async def test_cleanup_deletes_only_what_the_preview_showed(hass: HomeAssistant) -> None:
    """An entity that becomes an orphan after the preview is not deleted with it."""
    entry = await setup_entry(hass, {"targeted_backup": True})
    coordinator = entry.runtime_data
    await _orphan(hass, "sensor.first")
    await coordinator.async_run_analysis()
    preview = await coordinator.async_preview(["orphans"])
    assert preview["orphans"]["items"] == ["sensor.first"]
    plan_id = preview["plan_id"]

    # between preview and confirmation another entity goes away
    await _orphan(hass, "sensor.later")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    assert "sensor.later" in coordinator.orphans()["entities"]
    later = await _states(hass, "sensor.later")
    first = await _states(hass, "sensor.first")

    result = await coordinator.async_clean(["orphans"], plan_id=plan_id)
    await async_wait_recording_done(hass)
    assert result["blocked"] is None
    assert await _states(hass, "sensor.first") == 0
    assert await _states(hass, "sensor.later") == later
    # the targeted backup saved exactly the deleted rows
    assert result["undo"]["rows"]["states"] == first



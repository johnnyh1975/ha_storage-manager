async def test_plan_rules(hass: HomeAssistant, hass_ws_client) -> None:
    """Expired or unknown plans and other targets are refused; empty stays empty."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    with pytest.raises(HomeAssistantError, match="plan_expired"):
        await coordinator.async_clean(["orphans"], plan_id="nope")
    plan_id = (await coordinator.async_preview(["files", "events"]))["plan_id"]
    with pytest.raises(HomeAssistantError, match="plan_targets"):
        await coordinator.async_clean(["orphans"], plan_id=plan_id)
    # a blocked safety chain keeps the plan for the retry
    blocked = AsyncMock(side_effect=safety.SafetyError("no_space", "1"))
    with patch.object(coordinator, "async_safety", blocked):
        result = await coordinator.async_clean(["events"], plan_id=plan_id)
    assert result["blocked"]["reason"] == "no_space"
    assert plan_id in coordinator.cleanup._plans
    # nothing to delete in the preview: nothing is deleted, not "everything"
    hass.bus.async_fire("late_event")
    with patch.object(database, "async_delete_events", AsyncMock(return_value=0)) as delete:
        await coordinator.async_clean(["events"], plan_id=plan_id)
        delete.assert_not_awaited()
    # used up: running it again would delete rows an undo brought back
    with pytest.raises(HomeAssistantError, match="plan_expired"):
        await coordinator.async_clean(["files"], plan_id=plan_id)
    plan_id = (await coordinator.async_preview(["files"]))["plan_id"]
    with patch.object(cleanup.time, "monotonic", return_value=time.monotonic() + 3600):
        with pytest.raises(HomeAssistantError, match="plan_expired"):
            await coordinator.async_clean(["files"], plan_id=plan_id)
        # an old plan is dropped when the next preview keeps its own
        await coordinator.async_preview(["files"])
    assert plan_id not in coordinator.cleanup._plans

    client = await hass_ws_client(hass)
    preview = await _ws(client, {"type": f"{DOMAIN}/preview", "targets": ["files"]})
    msg = await _ws(
        client,
        {"type": f"{DOMAIN}/clean", "targets": ["files"], "plan_id": preview["result"]["plan_id"]},
    )
    assert msg["success"]


async def test_selection_from_a_plan(hass: HomeAssistant) -> None:
    """Every target takes its ids from the plan."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    unused = AsyncMock(return_value=[{"statistic_id": "sensor.u", "bytes": 5, "kind": "imported"}])
    dead = AsyncMock(return_value=[{"entity_id": "sensor.d", "bytes": 7}])
    with (
        patch.object(coordinator, "async_unused_selection", unused),
        patch.object(coordinator, "async_dead_selection", dead),
        patch.object(
            coordinator,
            "events_selection",
            return_value=[{"event_type": "e", "est_bytes": 3, "rows": 1}],
        ),
        patch.object(
            coordinator,
            "orphans",
            return_value={"entities": ["sensor.o"], "statistics": ["sensor.s"], "entity_bytes": 0},
        ),
    ):
        plan = {
            "orphans": ["sensor.o", "sensor.x"],
            "statistics": [],
            "unused_statistics": ["sensor.u"],
            "dead": ["sensor.d"],
            "events": ["e"],
        }
        sel = await coordinator.cleanup.async_select(
            ["orphans", "statistics", "unused_statistics", "dead", "events"], plan=plan
        )
    assert sel.orphans == ["sensor.o"]
    assert sel.statistics == []
    unused.assert_awaited_with(["sensor.u"])
    dead.assert_awaited_with(["sensor.d"])
    assert sel.ids()["events"] == ["e"]
    assert coordinator.cleanup._delete_estimate(["events"], sel) == 15



from __future__ import annotations

from typing import Any

from custom_components.storage_manager import advisor, coordinator
from custom_components.storage_manager.usage import EntityUsage

MB = 1024 * 1024


def _facts(entity_id: str, **kwargs: Any) -> advisor.EntityFacts:
    base: dict[str, Any] = {
        "entity_id": entity_id,
        "rows": 10_000,
        "rows_24h": 1000,
        "attr_len": 0,
        "state_len": 10,
        "est_state_bytes": 50 * MB,
        "est_bytes": 50 * MB,
        "stat_rows": 0,
        "est_attr_bytes": 0,
        "state_class": None,
        "device_class": None,
        "entity_category": None,
        "current": "default",
    }
    base.update(kwargs)
    return advisor.EntityFacts(**base)


def _rule(facts: advisor.EntityFacts) -> tuple[str, str] | None:
    return advisor.base_rule(facts)


def test_kind_rules() -> None:
    """Each kind of sensor gets its own rule; statistics are never dropped."""
    assert _rule(_facts("sensor.time", platform="time_date")) == ("excluded", "time")
    assert _rule(_facts("sensor.date", platform="template")) == ("excluded", "time")
    assert _rule(_facts("sensor.time", platform="template", state_class="measurement")) == (
        "1",
        "time_statistics",
    )
    assert _rule(_facts("sensor.kitchen_time_left", platform="template")) != ("excluded", "time")

    power = _facts(
        "sensor.tv_power", device_class="power", state_class="measurement", platform="powercalc"
    )
    assert _rule(power) == ("3", "power_statistics")
    slow_power = _facts(
        "sensor.tv_power", device_class="power", state_class="measurement", rows_24h=20
    )
    assert _rule(slow_power) != ("3", "power_statistics")

    energy = _facts(
        "sensor.tv_energy", device_class="energy", state_class="total_increasing", rows_24h=200
    )
    assert _rule(energy) == ("7", "energy_statistics")

    gps = _facts("device_tracker.phone", source_type="gps", rows_24h=300)
    assert gps.domain == "device_tracker"
    assert _rule(gps) == ("7", "gps_tracker")
    assert _rule(_facts("device_tracker.phone", source_type="gps", rows_24h=10)) is None
    router = _facts("device_tracker.laptop", source_type="router", rows_24h=300)
    assert _rule(router) is None or _rule(router)[1] != "gps_tracker"

    presence = _facts("sensor.office_moving_target_distance", rows_24h=50_000)
    assert _rule(presence) == ("1", "fast_presence")
    distance = _facts("sensor.mmwave", device_class="distance", rows_24h=5000)
    assert _rule(distance) == ("1", "fast_presence")

    # diagnostic noise still wins over every kind rule
    rssi = _facts("sensor.plug_rssi", device_class="power", state_class="measurement")
    assert _rule(rssi) == ("1", "noise_statistics")


def test_group_makes_small_sensors_count() -> None:
    """500 small power sensors are worth it together, not one by one."""
    small = [
        _facts(
            f"sensor.light_{i}_power",
            device_class="power",
            state_class="measurement",
            platform="powercalc",
            est_state_bytes=2 * MB,
            est_bytes=2 * MB,
            rows_24h=2000,
        )
        for i in range(500)
    ]
    total = 4_000 * MB
    alone = advisor.recommend(small[0], None, keep_days=10, total_bytes=total)
    assert alone["action"] is None

    groups = advisor.group_savings(small + [_facts("sensor.x")])
    key = advisor.group_key(small[0], "power_statistics")
    assert groups[key] > total * advisor.MIN_SHARE
    advice = advisor.recommend(
        small[0], None, keep_days=10, total_bytes=total, group_saving=groups[key]
    )
    assert advice["action"] == "3"
    assert advice["group"] == "power_statistics:powercalc"
    assert advice["group_member"] is True
    assert advice["hint"] == "powercalc"

    # usage protection still applies per entity
    usage = EntityUsage(helpers=[{"domain": "statistics", "title": "Mean"}])
    protected = advisor.recommend(
        small[1], usage, keep_days=10, total_bytes=total, group_saving=groups[key]
    )
    assert protected["action"] is None


def test_hints_by_platform() -> None:
    """Fast sensors get a hint how to throttle them at the source."""
    for platform, hint in (("esphome", "esphome"), ("shelly", "shelly"), ("knx", "generic")):
        facts = _facts(
            "sensor.grid_power",
            device_class="power",
            state_class="measurement",
            platform=platform,
            rows_24h=40_000,
        )
        advice = advisor.recommend(facts, None, keep_days=10, total_bytes=100 * MB)
        assert advice["hint"] == hint
    slow = _facts(
        "sensor.grid_power", device_class="power", state_class="measurement", rows_24h=200
    )
    assert "hint" not in advisor.recommend(slow, None, keep_days=10, total_bytes=100 * MB)


def _row(entity_id: str, saving: int, **advice: Any) -> dict[str, Any]:
    return {
        "entity_id": entity_id,
        "name": entity_id,
        "advice": {"action": "3", "reason": "power_statistics", "saving": saving, **advice},
    }


def test_inbox_groups_many_of_one_kind() -> None:
    """Four or more entities with the same rule and integration become one line."""
    rows = [
        _row(f"sensor.p{i}", 10, group="power_statistics:powercalc", hint="powercalc")
        for i in range(5)
    ]
    rows += [_row("sensor.few1", 5, group="power_statistics:shelly")]
    rows += [_row("sensor.alone", 100)]
    rows += [_row("sensor.conflict", 0, group="power_statistics:powercalc", conflict=True)]
    rows += [{"entity_id": "sensor.none", "name": "x", "advice": {"action": None}}]
    inbox = coordinator._build_inbox(rows)
    assert inbox[0]["entity_id"] == "sensor.conflict"
    grouped = next(i for i in inbox if i.get("entity_ids"))
    assert grouped["count"] == 5
    assert grouped["saving"] == 50
    assert grouped["integration"] == "powercalc"
    assert grouped["hint"] == "powercalc"
    assert {i["entity_id"] for i in inbox if not i.get("entity_ids")} == {
        "sensor.conflict",
        "sensor.alone",
        "sensor.few1",
    }

async def test_nightly_event_and_action(hass: HomeAssistant) -> None:
    """The nightly run fires an event; the action runs it on demand."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    events = async_capture_events(hass, EVENT_NIGHTLY_RUN)
    with (
        patch.object(coordinator, "async_run_retention", AsyncMock(return_value=3)),
        patch.object(coordinator, "async_run_statistics_age", AsyncMock(return_value=40)),
    ):
        summary = await coordinator.async_nightly("schedule")
        assert summary["entities"] == 3
        assert summary["statistics_rows"] == 40
        response = await hass.services.async_call(
            DOMAIN, "run_nightly", {}, blocking=True, return_response=True
        )
        await hass.async_block_till_done()
    assert response["trigger"] == "action"
    assert [e.data["trigger"] for e in events] == ["schedule", "action"]
    assert events[0].data["seconds"] >= 0
    assert events[0].data["errors"] == []

    # a failing step is reported; the other still runs and the event still fires
    with (
        patch.object(coordinator, "async_run_retention", AsyncMock(side_effect=RuntimeError("x"))),
        patch.object(coordinator, "async_run_statistics_age", AsyncMock(return_value=5)) as age,
    ):
        summary = await coordinator.async_nightly("schedule")
    age.assert_awaited_once()
    assert summary["statistics_rows"] == 5
    assert summary["errors"] == ["retention: x"]
    with (
        patch.object(coordinator, "async_run_retention", AsyncMock(return_value=0)),
        patch.object(
            coordinator, "async_run_statistics_age", AsyncMock(side_effect=RuntimeError("y"))
        ),
    ):
        summary = await coordinator.async_nightly("schedule")
    assert summary["errors"] == ["statistics: y"]
    await hass.async_block_till_done()
    assert len(events) == 4


@pytest.mark.parametrize("enabled", [True, False])
async def test_daily_job_honours_option(hass: HomeAssistant, enabled: bool) -> None:
    """The scheduled run only happens when the option is on."""
    entry = await setup_entry(hass, {"nightly_run": enabled})
    coordinator = entry.runtime_data
    with (
        patch.object(coordinator, "async_nightly", AsyncMock()) as nightly,
        patch.object(coordinator, "async_sweep_statistics_off", AsyncMock()),
        patch.object(coordinator, "async_run_retention", AsyncMock(return_value=0)),
    ):
        now = dt_util.now()
        async_fire_time_changed(
            hass, now.replace(hour=4, minute=37, second=0, microsecond=0) + timedelta(days=1)
        )
        # timer jobs run as background tasks
        await hass.async_block_till_done(wait_background_tasks=True)
    assert nightly.await_count == (1 if enabled else 0)

async def test_raw_rows_pages(hass: HomeAssistant, hass_ws_client) -> None:
    """States come newest first with attributes; the cursor loads older ones."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    for i in range(7):
        hass.states.async_set("sensor.inspect", str(i), {"n": i})
    await async_wait_recording_done(hass)

    page = await coordinator.async_raw_rows("sensor.inspect", "states", None, 4)
    assert page["kind"] == "states"
    assert [r["state"] for r in page["rows"]] == ["6", "5", "4", "3"]
    assert '"n":6' in page["rows"][0]["attributes"].replace(" ", "")
    assert page["next"] == page["rows"][-1]["ts"]
    older = await coordinator.async_raw_rows("sensor.inspect", "states", page["next"], 4)
    assert [r["state"] for r in older["rows"]] == ["2", "1", "0"]
    assert older["next"] is None

    client = await hass_ws_client(hass)
    msg = await _ws(
        client,
        {"type": f"{DOMAIN}/raw_rows", "entity_id": "sensor.inspect", "kind": "states", "limit": 2},
    )
    assert msg["success"]
    assert len(msg["result"]["rows"]) == 2
    msg = await _ws(
        client, {"type": f"{DOMAIN}/raw_rows", "entity_id": "sensor.inspect", "kind": "events"}
    )
    assert not msg["success"]
    with pytest.raises(HomeAssistantError):
        await database.async_raw_rows(hass, "sensor.inspect", "events", None, 5)



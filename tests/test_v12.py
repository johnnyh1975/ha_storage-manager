async def test_entity_rows_facet_fields(hass: HomeAssistant) -> None:
    """Rows carry the newest row time, the usage flag and the origin."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    hass.states.async_set("sensor.facet", "1")
    await async_wait_recording_done(hass)
    hass.states.async_remove("sensor.facet")
    hass.states.async_set("sensor.facet_live", "2")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()
    rows = {r["entity_id"]: r for r in (await coordinator.async_entity_rows())["rows"]}
    live = rows["sensor.facet_live"]
    assert live["newest"] == pytest.approx(time.time(), abs=60)
    assert live["used"] == "no"
    assert live["defined_in"] == "yaml_no_id"
    assert rows["sensor.facet"]["defined_in"] == "gone"

    # usage that fails to load leaves the flag unknown, the rows still come
    # (advice reads it first and works; the facet read fails)
    real = coordinator.async_usage
    calls: list[int] = []

    async def _usage(ids):  # noqa: ANN001, ANN202 - spy
        calls.append(1)
        if len(calls) > 1:
            raise RuntimeError
        return await real(ids)

    with patch.object(coordinator, "async_usage", _usage):
        rows = {r["entity_id"]: r for r in (await coordinator.async_entity_rows())["rows"]}
    assert rows["sensor.facet_live"]["used"] is None



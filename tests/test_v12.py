async def test_running_marker_around_changes(hass: HomeAssistant) -> None:
    """Database changes note themselves before they start and clear afterwards."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    store = coordinator.store
    seen: list[str] = []
    original = store.async_mark_running

    async def _mark(action, details):  # noqa: ANN001, ANN202 - spy
        seen.append(action)
        await original(action, details)

    with patch.object(store, "async_mark_running", _mark):
        await coordinator.async_clean(["orphans"])
        hass.states.async_set("sensor.tiered", "1")
        await async_wait_recording_done(hass)
        await coordinator.async_apply_recorder_changes(retention={"sensor.tiered": "drop"})
    assert "cleanup" in seen
    assert "purge_entities" in seen
    assert store.data.running is None

    # a failing change still clears the marker
    with (
        patch.object(store, "async_mark_running", _mark),
        patch.object(
            coord_mod.database, "async_purge_entities", AsyncMock(side_effect=RuntimeError)
        ),
        pytest.raises(RuntimeError),
    ):
        await coordinator.async_apply_recorder_changes(retention={"sensor.tiered": "1"})
    assert store.data.running is None



async def test_writers_in_period(hass: HomeAssistant, hass_ws_client) -> None:
    """Who wrote in a period: states and events, bytes from the analysis."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    start = time.time() - 1
    for i in range(5):
        hass.states.async_set("sensor.chatty", str(i))
    hass.states.async_set("sensor.quiet", "1")
    hass.bus.async_fire("demo_ping")
    hass.bus.async_fire("demo_ping")
    await async_wait_recording_done(hass)
    await coordinator.async_run_analysis()

    result = await coordinator.async_writers(start, time.time() + 1)
    states = {w["entity_id"]: w for w in result["states"]}
    assert states["sensor.chatty"]["rows"] == 5
    assert states["sensor.chatty"]["bytes"] > 0
    # bytes come from the state part only, not the statistics share
    info = coordinator.store.data.analysis["entities"]["sensor.chatty"]
    info["stat_rows"], info["est_bytes"] = 1000, info["est_state_bytes"] + 10**9
    again = await coordinator.async_writers(start, time.time() + 1)
    chatty = next(w for w in again["states"] if w["entity_id"] == "sensor.chatty")
    assert chatty["bytes"] == states["sensor.chatty"]["bytes"]
    assert result["states"][0]["entity_id"] == "sensor.chatty"
    events = {e["event_type"]: e for e in result["events"]}
    assert events["demo_ping"]["rows"] == 2
    keep = coord_mod.get_instance(hass).keep_days
    assert result["complete_from"] == pytest.approx(time.time() - keep * 86400, abs=60)

    # an empty period, and one before anything was written
    with pytest.raises(HomeAssistantError):
        await coordinator.async_writers(10.0, 10.0)
    old = await coordinator.async_writers(10.0, 20.0)
    assert old["states"] == []
    assert old["events"] == []

    client = await hass_ws_client(hass)
    msg = await _ws(client, {"type": f"{DOMAIN}/writers", "start": start, "end": time.time() + 1})
    assert msg["success"]
    assert msg["result"]["states"][0]["entity_id"] == "sensor.chatty"
    msg = await _ws(client, {"type": f"{DOMAIN}/writers", "start": 5.0, "end": 1.0})
    assert not msg["success"]



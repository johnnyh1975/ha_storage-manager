async def test_analysis_and_ws(hass: HomeAssistant, setup_hass, hass_ws_client) -> None:
    """Analysis finds the noisy entity and orphaned data."""
    entry = await _setup(hass)
    await _record(hass)
    coordinator = entry.runtime_data
    result = await coordinator.async_run_analysis()
    noisy = result["entities"]["sensor.noisy"]
    quiet = result["entities"]["sensor.quiet"]
    assert noisy["rows"] == 40
    assert noisy["est_bytes"] > quiet["est_bytes"]
    assert noisy["attr_len"] > 0
    assert "sensor.gone" in coordinator.orphans()["entities"]

    client = await hass_ws_client(hass)
    await client.send_json({"id": 1, "type": f"{DOMAIN}/overview"})
    msg = await client.receive_json()
    assert msg["success"], msg
    assert msg["result"]["data"]["disk"]["total"] > 0
    ids = [r["id"] for r in msg["result"]["recommendations"]]
    assert "orphans" in ids

    await client.send_json({"id": 2, "type": f"{DOMAIN}/entities"})
    msg = await client.receive_json()
    assert msg["success"], msg
    rows = {r["entity_id"]: r for r in msg["result"]["rows"]}
    assert rows["sensor.noisy"]["rows"] == 40
    assert rows["sensor.gone"]["orphan"] is True
    assert (
        msg["result"]["rows"][0]["est_bytes"] >= msg["result"]["rows"][-1]["est_bytes"]
    )

    await client.send_json(
        {"id": 3, "type": f"{DOMAIN}/preview", "targets": ["orphans", "repack"]}
    )
    msg = await client.receive_json()
    assert msg["success"], msg
    assert "sensor.gone" in msg["result"]["orphans"]["items"]

    await client.send_json({"id": 4, "type": f"{DOMAIN}/clean", "targets": ["orphans"]})
    msg = await client.receive_json()
    assert msg["success"], msg
    await async_wait_recording_done(hass)
    result = await coordinator.async_run_analysis()
    assert "sensor.gone" not in result["entities"]


async def test_retention_purges(
    hass: HomeAssistant, setup_hass, hass_ws_client
) -> None:
    """Setting 'keep nothing' purges an entity's history immediately."""
    entry = await _setup(hass)
    await _record(hass)

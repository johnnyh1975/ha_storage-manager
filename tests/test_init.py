async def test_exclusion_with_packages(
    hass: HomeAssistant, setup_hass, hass_ws_client
) -> None:
    """With packages the file is written and a restart is requested."""
    config_dir = Path(hass.config.config_dir)
    (config_dir / "configuration.yaml").write_text(
        "homeassistant:\n  packages: !include_dir_named packages\n", encoding="utf-8"
    )
    entry = await _setup(hass)
    client = await hass_ws_client(hass)
    await client.send_json(
        {
            "id": 1,
            "type": f"{DOMAIN}/apply",
            "excluded": {"sensor.quiet": True},
            "purge_now": False,
        }
    )
    msg = await client.receive_json()
    assert msg["success"], msg
    assert msg["result"]["restart_required"] is True
    content = (config_dir / "packages" / PACKAGE_FILE).read_text(encoding="utf-8")
    assert "sensor.quiet" in content
    await hass.async_block_till_done()
    assert ir.async_get(hass).async_get_issue(DOMAIN, "restart_required") is not None

    # undo: file removed again, no restart needed any more
    await client.send_json(
        {
            "id": 2,
            "type": f"{DOMAIN}/apply",
            "excluded": {"sensor.quiet": False},
            "purge_now": False,
        }
    )
    msg = await client.receive_json()
    assert msg["success"], msg
    assert msg["result"]["restart_required"] is False
    assert not (config_dir / "packages" / PACKAGE_FILE).exists()
    del entry


async def test_cleanup_action_dry_run(hass: HomeAssistant, setup_hass) -> None:
    """The cleanup action returns a preview."""
    await _setup(hass)
    config_dir = Path(hass.config.config_dir)
    build = config_dir / "esphome" / ".esphome" / "build"
    build.mkdir(parents=True)
    (build / "fw.bin").write_bytes(b"x" * 2048)
    entry = hass.config_entries.async_entries(DOMAIN)[0]
    entry.runtime_data.invalidate("files")
    response = await hass.services.async_call(
        DOMAIN,
        "cleanup",
        {"targets": ["files"], "dry_run": True},
        blocking=True,
        return_response=True,
    )
    assert response["dry_run"] is True
    assert response["files"]["bytes"] >= 2048
    response = await hass.services.async_call(
        DOMAIN, "cleanup", {"targets": ["files"]}, blocking=True, return_response=True
    )
    assert response["results"]["files"] >= 2048
    assert not build.exists()



    msg = await client.receive_json()
    assert msg["success"], msg
    assert entry.runtime_data.store.data.retention == {"sensor.noisy": "drop"}
    await async_wait_recording_done(hass)
    result = await entry.runtime_data.async_run_analysis()
    assert result["entities"].get("sensor.noisy", {}).get("rows", 0) <= 1

    # back to default removes the tier
    await client.send_json(
        {"id": 2, "type": f"{DOMAIN}/apply", "retention": {"sensor.noisy": "default"}}
    )
    msg = await client.receive_json()
    assert msg["success"]
    assert entry.runtime_data.store.data.retention == {}



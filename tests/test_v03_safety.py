def _make_db(path: Path, *, rows: int = 4000, incremental: bool = False) -> Path:
    conn = sqlite3.connect(path)
    if incremental:
        conn.execute("PRAGMA auto_vacuum=INCREMENTAL")
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("create table s(id integer primary key, v text)")
    conn.executemany("insert into s(v) values(?)", (("x" * 1000,) for _ in range(rows)))
    conn.commit()
    conn.execute(f"delete from s where id < {rows * 3 // 4}")
    conn.commit()
    conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
    conn.close()
    return path


def _instance(path: Path) -> Any:
    return SimpleNamespace(engine=SimpleNamespace(raw_connection=lambda: sqlite3.connect(path)))



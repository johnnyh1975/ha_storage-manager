async def test_async_repack_methods(hass: HomeAssistant, tmp_path: Path) -> None:
    """Incremental repack loops in steps until no free pages are left."""
    db = _make_db(tmp_path / "r.db", rows=6000, incremental=True)
    instance = _instance(db)

    async def _direct(hass: HomeAssistant, job: Any) -> bool:
        job(instance)
        return True

    progress: list[float] = []
    with (
        patch.object(repack, "async_run_on_recorder", _direct),
        patch.object(repack, "STEP_BYTES", 400 * 4096),
    ):
        await repack.async_repack(
            hass, db, method=repack.METHOD_INCREMENTAL, convert=False, on_progress=progress.append
        )
        layout = repack.read_layout(db)
        assert layout is not None and layout.freelist_count == 0
        assert progress and all(0 <= p <= 1 for p in progress)
        # nothing to do on the second run
        await repack.async_repack(hass, db, method=repack.METHOD_INCREMENTAL, convert=False)

        db2 = _make_db(tmp_path / "f.db")
        instance = _instance(db2)
        await repack.async_repack(hass, db2, method=repack.METHOD_VACUUM, convert=True)
        converted = repack.read_layout(db2)
        assert converted is not None and converted.auto_vacuum == 2

    with pytest.raises(HomeAssistantError, match="Unknown repack method"):
        await repack.async_repack(hass, db, method="shred", convert=False)

    # a step that frees nothing must not loop forever
    db3 = _make_db(tmp_path / "s.db", incremental=True)
    with patch.object(repack, "async_run_on_recorder", AsyncMock(return_value=True)):
        await repack.async_repack(hass, db3, method=repack.METHOD_INCREMENTAL, convert=False)

    assert await repack.async_plan(hass, None, 10) is None
    planned = await repack.async_plan(hass, db3, 10 * 1024 * MB)
    assert planned is not None and planned["method"] == repack.METHOD_INCREMENTAL



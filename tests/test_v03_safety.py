def _backup(
    backup_id: str,
    *,
    age: timedelta = timedelta(hours=1),
    database: bool = True,
    agents: tuple[str, ...] = ("backup.local",),
    failed: tuple[str, ...] = (),
    meta: dict[str, Any] | None = None,
    name: str | None = None,
) -> Any:
    return SimpleNamespace(
        backup_id=backup_id,
        name=name or f"Backup {backup_id}",
        date=(dt_util.utcnow() - age).isoformat(),
        database_included=database,
        homeassistant_included=True,
        agents={a: SimpleNamespace(size=1, protected=False) for a in agents},
        failed_agent_ids=list(failed),
        extra_metadata=meta or {},
    )


class _Manager:
    def __init__(
        self,
        backups: list[Any],
        *,
        agents: tuple[str, ...] = ("backup.local", "cloud.x"),
        configured: tuple[str, ...] = ("cloud.x",),
        create: Any = None,
    ) -> None:
        self.backups = {b.backup_id: b for b in backups}
        self.backup_agents = dict.fromkeys(agents)
        self.local_backup_agents = {a: None for a in agents if a.endswith("local")}
        self.config = SimpleNamespace(
            data=SimpleNamespace(
                create_backup=SimpleNamespace(agent_ids=list(configured), password="pw")
            )
        )
        self.created: list[dict[str, Any]] = []
        self._create = create

    async def async_get_backups(self) -> tuple[dict[str, Any], dict[str, Any]]:
        return self.backups, {}

    async def async_create_backup(self, **kwargs: Any) -> Any:
        self.created.append(kwargs)
        if self._create is not None:
            return self._create(self, kwargs)
        backup = _backup(
            "new",
            age=timedelta(0),
            agents=tuple(kwargs["agent_ids"]),
            meta=kwargs["extra_metadata"],
        )
        self.backups[backup.backup_id] = backup
        return SimpleNamespace(backup_job_id="job")



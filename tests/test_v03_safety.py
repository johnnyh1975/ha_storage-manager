def test_integrity_check_results(tmp_path: Path) -> None:
    """ok, damaged, timed out and unreadable files are told apart."""
    good = _make_db(tmp_path / "good.db", rows=3000)
    assert safety.integrity_check(good) == {"result": "ok", "details": []}
    assert safety.integrity_check(good, timeout=-1)["result"] == safety.RESULT_TIMEOUT
    assert safety.integrity_check(tmp_path / "missing.db")["result"] == safety.RESULT_ERROR

    bad = tmp_path / "bad.db"
    raw = bytearray(good.read_bytes())
    for offset in range(4096 * 3, len(raw) - 4096, 4096 * 2):
        raw[offset : offset + 200] = b"\xff" * 200
    bad.write_bytes(bytes(raw))
    result = safety.integrity_check(bad)
    assert result["result"] == safety.RESULT_CORRUPT
    assert result["details"]

    junk = tmp_path / "junk.db"
    junk.write_bytes(b"x" * 8192)
    assert safety.integrity_check(junk)["result"] == safety.RESULT_CORRUPT



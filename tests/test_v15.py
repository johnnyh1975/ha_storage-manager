async def test_undo_files_leave_nulls_out_and_format_1_still_restores(hass: HomeAssistant) -> None:
    """Format 2 leaves NULL columns out; a format 1 file with them restores the same."""
    import gzip  # noqa: PLC0415
    import json  # noqa: PLC0415

    from custom_components.storage_manager import undo  # noqa: PLC0415

    from .test_v10_undo import _delete, _restore, _seed, _snapshot  # noqa: PLC0415

    await setup_entry(hass)
    await _seed(hass)
    before = await _snapshot(hass)
    spec = undo.Spec(
        states={"sensor.gone": None}, statistics=["demo:import"], event_types=["noisy_event"]
    )
    path = undo.path_for(hass.config.config_dir, undo.new_id())
    await database.async_read(hass, lambda s: undo.export(s, path, spec))
    with gzip.open(path) as handle:
        lines = [json.loads(x) for x in handle.read().splitlines()]
    assert lines[0]["format"] == 2
    rows = [x["r"] for x in lines if x.get("t") == "state"]
    assert rows and all(None not in r.values() for r in rows)

    # the same file as 1.4 wrote it: format 1, every column, NULLs included
    from homeassistant.components.recorder.db_schema import States  # noqa: PLC0415

    states = States.__table__
    old = []
    for x in lines:
        if x.get("kind") == "header":
            x = {**x, "format": 1}
        elif x.get("t") == "state":
            full = {c.name: None for c in states.c if c.name not in ("state_id", "metadata_id")}
            x = {**x, "r": {**full, **x["r"]}}
        old.append(json.dumps(x).encode())
    path_1 = path.with_name("format1.undo.ndjson.gz")
    with gzip.open(path_1, "wb") as out:
        out.write(b"\n".join(old) + b"\n")

    await _delete(hass)
    result = await _restore(hass, path_1)
    assert result["added"] == {"states": 3, "statistics": 4, "events": 3}
    assert await _snapshot(hass) == before
    await _delete(hass)
    result = await _restore(hass, path)
    assert result["added"] == {"states": 3, "statistics": 4, "events": 3}
    assert await _snapshot(hass) == before



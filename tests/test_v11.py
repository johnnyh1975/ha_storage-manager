async def _add_stats(hass: HomeAssistant, statistic_id: str, days_back: list[int]) -> None:
    now = dt_util.utcnow().replace(minute=0, second=0, microsecond=0)
    metadata = {
        "has_mean": False,
        "mean_type": StatisticMeanType.NONE,
        "has_sum": True,
        "name": statistic_id,
        "source": statistic_id.split(":", 1)[0],
        "statistic_id": statistic_id,
        "unit_of_measurement": "kWh",
        "unit_class": "energy",
    }
    rows = [
        {"start": now - timedelta(days=d), "sum": float(i), "state": float(i)}
        for i, d in enumerate(sorted(days_back, reverse=True))
    ]
    async_add_external_statistics(hass, metadata, rows)
    await async_wait_recording_done(hass)


async def _rows(hass: HomeAssistant, statistic_id: str) -> int:
    return int(
        await database.async_read(
            hass,
            lambda s: s.execute(
                text(
                    "SELECT COUNT(*) FROM statistics s JOIN statistics_meta m "
                    "ON m.id = s.metadata_id WHERE m.statistic_id = :e"
                ),
                {"e": statistic_id},
            ).scalar(),
        )
    )


async def test_statistics_by_age(hass: HomeAssistant, hass_ws_client) -> None:
    """Old rows go after a confirmed run; energy keeps its own limit; undo brings them back."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    await _add_stats(hass, "demo:other", [800, 500, 400, 10])
    await _add_stats(hass, "demo:energy", [800, 500, 10])
    energy = AsyncMock(return_value={"demo:energy"})
    with patch.object(usage, "async_energy_statistics", energy):
        plan = await coordinator.async_statistics_age_plan(12, None)
        assert plan["groups"]["other"]["rows"] == 3
        assert plan["groups"]["other"]["statistics"] == 1
        assert plan["groups"]["energy"] == {"months": None, "statistics": 0, "rows": 0, "bytes": 0}
        plan = await coordinator.async_statistics_age_plan(12, 24)
        assert plan["groups"]["energy"]["rows"] == 1
        assert plan["bytes"] > 0

        with pytest.raises(HomeAssistantError):
            coordinator.set_statistics_retention(5, None)
        status = coordinator.set_statistics_retention(12, 24)
        assert status["active"] is False
        assert await coordinator.async_run_statistics_age() == 0

        preview = await coordinator.async_preview(["statistics_age"])
        assert preview["statistics_age"]["rows"] == 4
        assert preview["safety"]["backup"]["action"] == "undo"

        result = await coordinator.async_clean(["statistics_age"])
        assert result["blocked"] is None
        assert result["undo"]["rows"]["statistics"] == 4
        assert await _rows(hass, "demo:other") == 1
        assert await _rows(hass, "demo:energy") == 2
        assert coordinator.statistics_retention()["active"] is True
        assert (
            coordinator.store.data.history[-1]["details"]["deleted"]["statistics_age"]["rows"] == 4
        )

        # undo brings the old rows back; the nightly run deletes them again
        await coordinator.async_undo(result["undo"]["id"])
        await async_wait_recording_done(hass)
        assert await _rows(hass, "demo:other") == 4
        assert await coordinator.async_run_statistics_age() == 4
        assert await _rows(hass, "demo:other") == 1
        assert await coordinator.async_run_statistics_age() == 0

        # a damaged database stops the nightly run
        await _add_stats(hass, "demo:other", [700])
        coordinator.store.data.integrity = {"result": "corrupt", "at": 0}
        assert await coordinator.async_run_statistics_age() == 0
        coordinator.store.data.integrity = None

        # longer limits keep the nightly run, shorter ones wait for a confirmed run
        assert coordinator.set_statistics_retention(24, None)["active"] is True
        assert coordinator.set_statistics_retention(6, None)["active"] is False

        client = await hass_ws_client(hass)
        msg = await _ws(client, {"type": f"{DOMAIN}/statistics_retention"})
        assert msg["result"]["stats_months"] == 6
        msg = await _ws(
            client,
            {"type": f"{DOMAIN}/statistics_retention", "stats_months": None, "energy_months": 12},
        )
        assert msg["result"]["stats_months"] is None
        assert msg["result"]["energy_months"] == 12
        msg = await _ws(client, {"type": f"{DOMAIN}/statistics_retention", "stats_months": 7})
        assert not msg["success"]
        msg = await _ws(client, {"type": f"{DOMAIN}/statistics_age_plan", "stats_months": 12})
        assert "items" not in msg["result"]
        assert msg["result"]["groups"]["other"]["months"] == 12



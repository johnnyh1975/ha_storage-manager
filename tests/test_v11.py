async def test_explorer_ws(hass: HomeAssistant, hass_ws_client) -> None:
    """Only allowed roots, only scanned folders."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    _tree(__import__("pathlib").Path(hass.config.config_dir))
    config = hass.config.config_dir
    client = await hass_ws_client(hass)
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_roots"})
    assert msg["result"]["roots"][0] == {
        "path": config,
        "config": True,
        "scanned_at": None,
        "size": None,
    }
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_browse", "root": config, "path": config})
    assert msg["error"]["message"] == "folder_not_scanned"
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_scan", "root": "/etc"})
    assert msg["error"]["message"] == "folder_not_allowed"
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_scan", "root": config})
    assert msg["success"], msg
    assert msg["result"]["path"] == config
    msg = await _ws(
        client, {"type": f"{DOMAIN}/folder_browse", "root": config, "path": f"{config}/a"}
    )
    assert msg["result"]["size"] == 5100
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_browse", "root": config, "path": "/etc"})
    assert msg["error"]["message"] == "folder_unknown"
    msg = await _ws(client, {"type": f"{DOMAIN}/folder_roots"})
    assert msg["result"]["roots"][0]["size"] > 0
    coordinator._scanning = config
    with pytest.raises(HomeAssistantError, match="running"):
        await coordinator.async_folder_scan(config)

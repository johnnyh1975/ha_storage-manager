def _tree(base) -> None:
    (base / "a" / "deep").mkdir(parents=True)
    (base / "b").mkdir()
    (base / "a" / "deep" / "big.bin").write_bytes(b"x" * 5000)
    (base / "a" / "small.txt").write_bytes(b"x" * 100)
    (base / "b" / "mid.bin").write_bytes(b"x" * 2000)
    (base / "top.txt").write_bytes(b"x" * 10)
    os.link(base / "b" / "mid.bin", base / "b" / "mid_link.bin")
    os.symlink(base / "a", base / "loop")
    os.symlink(base / "top.txt", base / "file_link")


def test_scan_and_browse(tmp_path) -> None:
    """Totals, hard links once, symlinks skipped, largest files and crumbs."""
    root = tmp_path / "root"
    root.mkdir()
    _tree(root)
    result = explorer.scan(str(root))
    top = explorer.browse(result, str(root))
    assert top["size"] == 5000 + 100 + 2000 + 10
    assert [c["name"] for c in top["children"]] == ["a", "b"]
    assert top["own"] == 10
    assert top["largest"][0] == {"path": "a/deep/big.bin", "size": 5000}
    sub = explorer.browse(result, str(root / "a" / "deep"))
    assert [c["name"] for c in sub["crumbs"]] == ["root", "a", "deep"]
    assert sub["largest"] == [{"path": "big.bin", "size": 5000}]
    with pytest.raises(KeyError):
        explorer.browse(result, str(root / "loop"))
    with patch.object(explorer, "CHILDREN_SHOWN", 1):
        assert explorer.browse(result, str(root))["rest"] == {"count": 1, "size": 2000}


def test_scan_limits(tmp_path) -> None:
    """A capped scan says so; unreadable folders are counted; few top files kept."""
    root = tmp_path / "root"
    root.mkdir()
    _tree(root)
    partial = explorer.scan(str(root), max_items=2)
    assert partial["partial"] is True
    real = os.scandir

    def scandir(path):
        if str(path).endswith("/b"):
            raise PermissionError(path)
        return real(path)

    with patch.object(explorer.os, "scandir", scandir), patch.object(explorer, "TOP_FILES", 1):
        result = explorer.scan(str(root))
    assert result["warnings"] == 1
    assert len(result["largest"]) == 1



def test_backup_checks_problems() -> None:
    """Every problem is reported with its own status."""
    info = _info(
        recurrence="never",
        last_attempted=(UTC_NOW - timedelta(hours=2)).isoformat(),
        last_completed=(UTC_NOW - timedelta(days=3)).isoformat(),
        include_database=False,
        protected={"backup.local": False, "cloud.x": False},
        agent_errors=["cloud.x"],
        backups=[_backup(80, size=10 * MB, agents={"backup.local": False}, failed=["nas.y"])]
        + [_backup(100 + 24 * i, agents={"backup.local": False}) for i in range(4)],
    )
    attest = {"restore_test": (UTC_NOW - timedelta(days=400)).isoformat()}
    checks = _by_key(health.backup_checks(info, disk_free=1, attestations=attest, now=UTC_NOW))
    assert checks["schedule"]["status"] == health.WARNING
    assert checks["newest"]["status"] == health.OK  # 80 h is fine without a daily schedule
    assert checks["last_attempt"]["status"] == health.ERROR
    assert checks["offsite"]["status"] == health.WARNING
    assert checks["size"]["status"] == health.WARNING
    assert checks["size"]["values"]["ratio"] == 0.1
    assert checks["encryption"]["values"]["agents"] == ["cloud.x"]
    assert checks["database_included"]["status"] == health.WARNING
    assert checks["space"]["status"] == health.WARNING
    assert checks["agents"]["values"]["agents"] == ["cloud.x", "nas.y"]
    assert checks["emergency_kit"]["status"] == health.INFO
    assert checks["restore_test"]["status"] == health.WARNING
    assert health.summary(list(checks.values())) == health.ERROR



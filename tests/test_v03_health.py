async def test_health_ws_and_attestations(
    hass: HomeAssistant, hass_ws_client, tmp_path: Path
) -> None:
    """The panel reads the checks and records confirmations."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    client = await hass_ws_client(hass)
    db = tmp_path / "home-assistant_v2.db"
    db.write_bytes(b"x" * 10)
    (tmp_path / "home-assistant_v2.db-wal").write_bytes(b"y" * 5)
    with (
        patch.object(coord_mod.database, "sqlite_path", return_value=db),
        patch.object(coord_mod.health, "async_statistics_issues", AsyncMock(return_value={})),
    ):
        await client.send_json({"id": 1, "type": f"{DOMAIN}/health", "force": True})
        msg = await client.receive_json()
    assert msg["success"], msg
    result = msg["result"]
    db_checks = _by_key(result["database"]["checks"])
    assert db_checks["wal"]["values"]["bytes"] == 5
    assert result["backups"]["checks"][0]["key"] == "backup_integration"

    await client.send_json(
        {"id": 2, "type": f"{DOMAIN}/attest", "key": "restore_test", "done": True}
    )
    msg = await client.receive_json()
    assert msg["success"], msg
    assert "restore_test" in coordinator.store.data.attestations
    await client.send_json(
        {"id": 3, "type": f"{DOMAIN}/attest", "key": "restore_test", "done": False}
    )
    msg = await client.receive_json()
    assert "restore_test" not in coordinator.store.data.attestations
    with pytest.raises(HomeAssistantError, match="Unknown confirmation"):
        coordinator.attest("pinky_promise", True)

    assert coord_mod._wal_size(None) is None
    assert coord_mod._wal_size(tmp_path / "missing.db") == 0


async def test_damaged_database_issue(hass: HomeAssistant) -> None:
    """A failed integrity check raises a repair issue until a check passes."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    registry = ir.async_get(hass)
    coordinator.store.data.integrity = {"result": "corrupt", "details": ["page 4"], "at": 0}
    repairs.async_update_issues(hass, coordinator)
    issue = registry.async_get_issue(DOMAIN, "database_damaged")
    assert issue is not None
    assert issue.translation_placeholders == {"details": "page 4"}
    coordinator.store.data.integrity = {"result": "ok", "at": 0}
    repairs.async_update_issues(hass, coordinator)
    assert registry.async_get_issue(DOMAIN, "database_damaged") is None



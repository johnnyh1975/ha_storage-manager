def test_growth_trend() -> None:
    """Recent growth is compared with the four weeks before."""
    assert health.growth([], NOW) is None
    assert health.growth([[NOW - DAY, 1, 1], [NOW, 1, 2]], NOW) is None  # no week yet
    steady = [[NOW - d * DAY, 0, (40 - d) * 10 * MB] for d in range(40, -1, -1)]
    trend = health.growth(steady, NOW)
    assert trend is not None
    assert trend["recent_bytes"] == 70 * MB
    assert trend["recent_rate"] == pytest.approx(10 * MB)
    assert trend["before_rate"] == pytest.approx(10 * MB)
    short = [[NOW - 8 * DAY, 0, 0], [NOW, 0, 500 * MB]]
    assert health.growth(short, NOW)["before_rate"] is None


def test_database_checks() -> None:
    """WAL, growth, integrity and statistics checks."""
    samples = [[NOW - d * DAY, 0, 100 * MB] for d in range(40, 8, -1)]
    samples += [[NOW - 7 * DAY, 0, 100 * MB], [NOW, 0, 400 * MB]]
    checks = _by_key(
        health.database_checks(
            dialect="sqlite",
            file_bytes=3000 * MB,
            wal_bytes=1200 * MB,
            samples=samples,
            integrity={"result": "corrupt", "details": ["page 4"], "at": NOW},
            statistics_issues={"units_changed": 2},
            now=NOW,
        )
    )
    assert checks["wal"]["status"] == health.WARNING
    assert checks["growth"]["status"] == health.WARNING
    assert checks["growth"]["values"]["bytes"] == 300 * MB
    assert checks["integrity"]["status"] == health.ERROR
    assert checks["statistics"]["status"] == health.WARNING
    assert checks["statistics"]["values"]["count"] == 2

    quiet = _by_key(
        health.database_checks(
            dialect="sqlite",
            file_bytes=1000 * MB,
            wal_bytes=10 * MB,
            samples=[[NOW - d * DAY, 0, 100 * MB] for d in range(40, -1, -1)],
            integrity={"result": "ok", "at": NOW - DAY},
            statistics_issues={},
            now=NOW,
        )
    )
    assert {c["status"] for c in quiet.values()} == {health.OK}

    unknown = _by_key(
        health.database_checks(
            dialect="sqlite",
            file_bytes=None,
            wal_bytes=None,
            samples=[],
            integrity={"result": "timeout"},
            statistics_issues=None,
            now=NOW,
        )
    )
    assert "wal" not in unknown
    assert unknown["growth"]["status"] == health.UNKNOWN
    assert unknown["integrity"]["status"] == health.UNKNOWN
    assert unknown["statistics"]["status"] == health.UNKNOWN

    stale = _by_key(
        health.database_checks(
            dialect="sqlite",
            file_bytes=1,
            wal_bytes=0,
            samples=[],
            integrity={"result": "ok", "at": NOW - 40 * DAY},
            statistics_issues={},
            now=NOW,
        )
    )
    assert stale["integrity"]["status"] == health.INFO

    mariadb = _by_key(
        health.database_checks(
            dialect="mysql",
            file_bytes=1,
            wal_bytes=None,
            samples=[],
            integrity=None,
            statistics_issues={},
            now=NOW,
        )
    )
    assert "integrity" not in mariadb and "wal" not in mariadb



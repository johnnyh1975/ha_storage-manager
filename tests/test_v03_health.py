UTC_NOW = datetime(2026, 11, 14, 12, 0, tzinfo=dt_util.UTC)


def _backup(
    hours: float,
    *,
    size: int = 100 * MB,
    agents: dict[str, bool] | None = None,
    database: bool = True,
    failed: list[str] | None = None,
) -> dict[str, Any]:
    return {
        "date": (UTC_NOW - timedelta(hours=hours)).isoformat(),
        "size": size,
        "database_included": database,
        "agents": agents if agents is not None else {"backup.local": False, "cloud.x": True},
        "failed_agent_ids": failed or [],
        "automatic": True,
    }


def _info(**kwargs: Any) -> dict[str, Any]:
    base: dict[str, Any] = {
        "recurrence": "daily",
        "last_attempted": (UTC_NOW - timedelta(hours=10)).isoformat(),
        "last_completed": (UTC_NOW - timedelta(hours=10)).isoformat(),
        "include_database": True,
        "agent_ids": ["backup.local", "cloud.x"],
        "protected": {"backup.local": False, "cloud.x": True},
        "local_ids": ["backup.local"],
        "agent_errors": [],
        "backups": [_backup(10 + 24 * i) for i in range(6)],
    }
    base.update(kwargs)
    return base



async def test_retention_scheduler_and_estimate(hass: HomeAssistant) -> None:
    """Hourly runs purge 'drop', daily runs the day tiers; estimates scale."""
    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    coordinator.store.data.analysis = _analysis(
        {
            "sensor.a": _info(100, 1000, rows_24h=10),
            "sensor.b": _info(10, 100, rows_24h=10),
            "sensor.e": _info(0, 0),
        }
    )
    calls: list[tuple[list[str], int]] = []

    async def _purge(hass, entity_ids, keep_days):
        calls.append((sorted(entity_ids), keep_days))

    with patch.object(coord_mod.database, "async_purge_entities", _purge):
        result = await coordinator.async_apply_recorder_changes(
            retention={"sensor.a": "7", "sensor.b": "drop", "sensor.e": "1", "sensor.unknown": "3"}
        )
        assert result["restart_required"] is False
        calls.clear()
        await coordinator.async_run_retention(include_drop=True, include_daily=False)
        assert calls == [(["sensor.b"], 0)]
        calls.clear()
        await coordinator.async_run_retention(include_drop=False, include_daily=True)
        assert sorted(calls) == [(["sensor.a"], 7), (["sensor.e"], 1), (["sensor.unknown"], 3)]
        # scheduler wiring
        calls.clear()
        async_fire_time_changed(
            hass, dt_util.utcnow().replace(minute=17, second=0) + timedelta(hours=1)
        )
        await hass.async_block_till_done()
    history = coordinator.store.data.history
    assert history and history[-1]["action"] == "purge_entities"
    # 'drop' removed b entirely, a kept 7 days of 10/day -> 70 of 100 rows
    assert coordinator.store.data.analysis["entities"]["sensor.b"]["rows"] == 0
    assert coordinator.store.data.analysis["entities"]["sensor.a"]["rows"] == 70



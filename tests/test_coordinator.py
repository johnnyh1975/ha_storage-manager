async def test_preview_and_clean_all_targets(hass: HomeAssistant) -> None:
    """Preview covers every target; cleaning runs each one."""
    entry = await setup_entry(hass, {"backup_rotation": True})
    coordinator = entry.runtime_data
    hass.states.async_set("sensor.alive", "1")
    await async_wait_recording_done(hass)
    coordinator.store.data.analysis = _analysis(
        {"sensor.alive": _info(1, 10), "sensor.gone": _info(5, 500)},
        statistics={"sensor.gone": {"source": "recorder", "rows": 3}},
    )
    build = Path(hass.config.config_dir) / "esphome" / ".esphome" / "build"
    build.mkdir(parents=True)
    (build / "fw.bin").write_bytes(b"x" * 100)
    coordinator.invalidate("files")
    plan = [_plan_item(1, "delete_local", "rotated")]

    with (
        patch.object(
            backup_mod,
            "async_list",
            AsyncMock(return_value={"backups": plan, "local_total": GB, "agent_errors": []}),
        ),
        patch.object(backup_mod, "plan_rotation", return_value=plan),
        patch.object(
            backup_mod, "async_apply_rotation", AsyncMock(return_value=(GB, []))
        ) as rotate,
        patch.object(coord_mod, "is_hassio", return_value=True),
        patch.object(coord_mod.disk, "async_supervisor_repair", AsyncMock()) as repair,
        patch.object(coord_mod.database, "async_wait_idle", AsyncMock(return_value=True)),
        patch.object(coord_mod.database, "async_clear_statistics", AsyncMock()) as clear,
    ):
        coordinator.invalidate("backups")
        targets = ["backups", "files", "orphans", "statistics", "repack", "docker"]
        preview = await coordinator.async_preview(targets)
        assert set(targets) <= set(preview)
        assert preview["backups"]["bytes"] == GB
        assert preview["statistics"]["items"] == ["sensor.gone"]
        result = await coordinator.async_clean(targets)
    rotate.assert_awaited_once()
    repair.assert_awaited_once()
    clear.assert_awaited_once_with(hass, ["sensor.gone"])
    assert result["results"]["backups"] == GB
    assert result["results"]["files"] == 100
    assert result["freed"] >= GB
    assert coordinator.store.data.freed_total >= GB



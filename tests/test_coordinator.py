def _analysis(entities: dict, statistics: dict | None = None, freelist: int = 0) -> dict:
    return {
        "generated_at": dt_util.utcnow().timestamp(),
        "dialect": "sqlite",
        "entities": entities,
        "statistics": statistics or {},
        "events": [],
        "table_sizes": {"states": 1},
        "freelist_bytes": freelist,
        "totals": {"calibrated": True},
    }


def _info(rows: int, est: int, rows_24h: int = 0) -> dict:
    return {
        "rows": rows,
        "rows_24h": rows_24h,
        "state_len": 0,
        "attr_len": 0,
        "oldest": None,
        "stat_rows": 0,
        "est_state_bytes": est,
        "est_bytes": est,
    }


def _plan_item(i: int, action: str, reason: str, remote: bool = True) -> dict:
    return {
        "backup_id": f"b{i}",
        "name": f"B{i}",
        "date": "2026-11-13T00:00:00+00:00",
        "local_agents": ["hassio.local"],
        "remote_agents": ["hassio.nas"] if remote else [],
        "local_size": GB,
        "action": action,
        "reason": reason,
    }



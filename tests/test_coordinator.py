async def test_recommendations_all_kinds(hass: HomeAssistant) -> None:
    """Every recommendation kind appears when its condition holds."""
    entry = await setup_entry(hass, {"backup_rotation": True})
    coordinator = entry.runtime_data
    big = {f"sensor.big{i}": _info(1000, 10 * MB) for i in range(10)}
    big["sensor.gone"] = _info(10, MB)
    coordinator.store.data.analysis = _analysis(
        big, statistics={"sensor.removed": {"source": "recorder", "rows": 5}}, freelist=60 * MB
    )
    for i in range(10):
        hass.states.async_set(f"sensor.big{i}", "1")
    plan = [_plan_item(1, "delete_local", "rotated"), _plan_item(2, "keep", "newest")]
    listing = {"backups": plan, "local_total": 2 * GB, "agent_errors": []}
    with (
        patch.object(backup_mod, "async_list", AsyncMock(return_value=listing)),
        patch.object(backup_mod, "plan_rotation", return_value=plan),
    ):
        coordinator.invalidate("backups")
        await coordinator.async_refresh()
        ids = [r["id"] for r in coordinator.recommendations()]
        assert {"backups", "orphans", "statistics", "repack", "top_entities"} <= set(ids)
        assert ids == sorted(
            ids,
            key=lambda i: -next(r["bytes"] for r in coordinator.recommendations() if r["id"] == i),
        )

        # rotation off -> navigate instead of clean
        coordinator.options["backup_rotation"] = False
        await coordinator.async_refresh()
        ids = [r["id"] for r in coordinator.recommendations()]
        assert "backups_rotation_off" in ids

    only_local = [_plan_item(3, "keep", "only_local", remote=False)]
    with (
        patch.object(
            backup_mod,
            "async_list",
            AsyncMock(return_value={"backups": only_local, "local_total": GB, "agent_errors": []}),
        ),
        patch.object(backup_mod, "plan_rotation", return_value=only_local),
    ):
        coordinator.invalidate("backups")
        await coordinator.async_refresh()
        assert "backups_offsite" in [r["id"] for r in coordinator.recommendations()]



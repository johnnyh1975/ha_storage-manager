def test_policy_overrides_builtin_rule() -> None:
    """The user's rule per kind replaces the built-in tier or switches it off."""
    power = _facts("sensor.p", device_class="power", state_class="measurement", rows_24h=500)
    assert advisor.base_rule(power) == ("3", "power_statistics")
    assert advisor.base_rule(power, {"power": "7"}) == ("7", "power_statistics")
    assert advisor.base_rule(power, {"power": advisor.OFF}) is None
    assert advisor.base_rule(power, {"energy": "1"}) == ("3", "power_statistics")
    # statistics are never dropped: "don't record" becomes one day
    noisy = _facts("sensor.x_rssi", state_class="measurement")
    assert advisor.base_rule(noisy, {"noise": advisor.EXCLUDED}) == ("1", "noise_statistics")
    plain = _facts("sensor.x_rssi")
    assert advisor.base_rule(plain, {"noise": "3"}) == ("3", "noise")
    # switched off means no recommendation at all, not the next rule
    rec = advisor.recommend(
        power, None, keep_days=10, total_bytes=100 * MB, policy={"power": advisor.OFF}
    )
    assert rec["action"] is None
    rec = advisor.recommend(power, None, keep_days=10, total_bytes=100 * MB, policy={"power": "1"})
    assert rec["action"] == "1"
    assert advisor.group_savings([power], {"power": advisor.OFF}) == {}


def test_kind_summary() -> None:
    """Every kind is listed with its entities and what its rule saves."""
    facts = [
        _facts("sensor.p1", device_class="power", state_class="measurement", rows_24h=500),
        _facts("sensor.p2", device_class="power", state_class="measurement", rows_24h=500),
        _facts("sensor.calm", rows_24h=2),
        _facts("sensor.x_rssi", current=advisor.EXCLUDED),
    ]
    summary = {k["kind"]: k for k in advisor.kind_summary(facts)}
    assert list(summary) == list(advisor.KINDS)
    assert summary["power"]["entities"] == 2
    assert summary["power"]["bytes"] == 100 * MB
    assert summary["power"]["saving"] == 2 * advisor.saving(facts[0], "3")
    assert summary["power"]["statistics_only"] is True
    # already excluded: counted, but nothing left to save
    assert summary["noise"]["entities"] == 1 and summary["noise"]["saving"] == 0
    off = {k["kind"]: k for k in advisor.kind_summary(facts, {"power": advisor.OFF})}
    assert off["power"]["saving"] == 0 and off["power"]["value"] == advisor.OFF



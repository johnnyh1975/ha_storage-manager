async def test_kind_rules_and_overview(hass: HomeAssistant, hass_ws_client) -> None:
    """Rules change the inbox; open recommendations show up as a saving."""
    from .conftest import setup_entry

    entry = await setup_entry(hass)
    coordinator = entry.runtime_data
    await _seed(hass)
    await coordinator.async_run_analysis()
    client = await hass_ws_client(hass)

    async def entities() -> dict[str, Any]:
        return (await _ws(client, {"type": f"{DOMAIN}/entities"}))["result"]

    with (
        patch.object(coord_mod.advisor, "MIN_BYTES", 0),
        patch.object(coord_mod.advisor, "MIN_SHARE", 0),
    ):
        rows = await entities()
        kinds = {k["kind"]: k for k in rows["kinds"]}
        assert kinds["noise"]["entities"] >= 1
        assert "sensor.kitchen_rssi" in [a["entity_id"] for a in rows["inbox"]]

        coordinator._potential_key = None  # computed before the thresholds were patched
        await coordinator.async_refresh()
        overview = (await _ws(client, {"type": f"{DOMAIN}/overview"}))["result"]
        potential = overview["data"]["retention_potential"]
        assert potential["count"] >= 1 and potential["bytes"] > 0
        # cached until something changes
        assert await coordinator._async_retention_potential() is coordinator._potential

        res = await _ws(client, {"type": f"{DOMAIN}/kind_rules", "rules": {"noise": "off"}})
        assert res["result"] == {"kind_rules": {"noise": "off"}, "kind_auto": {}}
        rows = await entities()
        assert "sensor.kitchen_rssi" not in [a["entity_id"] for a in rows["inbox"]]
        after = coordinator.data["retention_potential"]
        assert after["count"] < potential["count"]
        assert after["bytes"] < potential["bytes"]

        # back to the built-in rule: None or the default value
        res = await _ws(client, {"type": f"{DOMAIN}/kind_rules", "rules": {"noise": None}})
        assert res["result"]["kind_rules"] == {}
        coordinator.set_kind_rules({"power": "7"})
        assert coordinator.set_kind_rules({"power": "3"}) == {}

        res = await _ws(client, {"type": f"{DOMAIN}/kind_rules", "rules": {"power": "excluded"}})
        assert not res["success"]
        res = await _ws(client, {"type": f"{DOMAIN}/kind_rules", "rules": {"bogus": "1"}})
        assert not res["success"]
    with pytest.raises(HomeAssistantError, match="Unknown kind"):
        coordinator.set_kind_rules({"bogus": "1"})
    with pytest.raises(HomeAssistantError, match="Unknown value"):
        coordinator.set_kind_rules({"power": "9"})



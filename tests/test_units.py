def _backup(days_ago: int, remote: bool = True) -> dict:
    when = datetime(2026, 11, 13, 3, 0, tzinfo=UTC) - timedelta(days=days_ago)
    return {
        "backup_id": f"b{days_ago}",
        "name": f"Backup {days_ago}",
        "date": when.isoformat(),
        "local_agents": ["hassio.local"],
        "remote_agents": ["hassio.nas"] if remote else [],
        "local_size": 100,
    }


def test_rotation_keeps_schedule() -> None:
    """GFS keeps daily/weekly/monthly and deletes the rest."""
    items = [_backup(d) for d in range(0, 120)]
    plan = backups.plan_rotation(
        items, keep_daily=7, keep_weekly=4, keep_monthly=3, require_offsite=True
    )
    kept = [p for p in plan if p["action"] == "keep"]
    deleted = [p for p in plan if p["action"] == "delete_local"]
    assert plan[0]["reason"] == "newest"
    assert 7 <= len(kept) <= 7 + 4 + 3
    assert len(deleted) == 120 - len(kept)
    assert all(p["remote_agents"] for p in deleted)


def test_rotation_requires_offsite() -> None:
    """Without a remote copy nothing is deleted."""
    items = [_backup(d, remote=False) for d in range(0, 30)]
    plan = backups.plan_rotation(
        items, keep_daily=3, keep_weekly=0, keep_monthly=0, require_offsite=True
    )
    assert not [p for p in plan if p["action"] == "delete_local"]
    assert any(p["reason"] == "only_local" for p in plan)


def test_forecast() -> None:
    """Linear growth of 100 MiB/day on a 10 GiB disk."""
    gib, mib = 1024**3, 1024**2
    now = 1_800_000_000.0
    samples = [
        [now - h * 3600, 5 * gib - h * (100 * mib / 24), 10 * gib] for h in range(48, -1, -1)
    ]
    fc = disk.forecast(samples, now)
    assert abs(fc["growth_per_day"] - 100 * mib) < mib
    assert 49 < fc["days_until_full"] < 53


def test_forecast_not_enough_data() -> None:
    """Few samples produce no forecast."""
    assert disk.forecast([[1.0, 1.0, 2.0]], 2.0)["days_until_full"] is None


def test_files_scan_and_safety(tmp_path: Path) -> None:
    """Only catalogued paths inside the config dir are found."""
    (tmp_path / "home-assistant.log.1").write_bytes(b"a" * 100)
    build = tmp_path / "esphome" / ".esphome" / "build" / "dev"
    build.mkdir(parents=True)
    (build / "firmware.bin").write_bytes(b"b" * 300)
    (tmp_path / "home-assistant_v2.db.corrupt.2026").write_bytes(b"c" * 50)
    outside = tmp_path.parent / "outside_target"
    outside.mkdir(exist_ok=True)
    (outside / "keep.txt").write_text("keep")
    (tmp_path / "zigbee2mqtt").mkdir()
    (tmp_path / "zigbee2mqtt" / "log").symlink_to(outside)

    result = files.scan(str(tmp_path))
    hogs = {h["key"]: h for h in result["hogs"]}
    assert hogs["rotated_logs"]["size_bytes"] == 100
    assert hogs["esphome_build"]["size_bytes"] == 300
    assert hogs["corrupt_databases"]["safety"] == "review"
    assert "zigbee2mqtt_logs" not in hogs  # symlink is ignored
    assert hogs["rotated_logs"]["safety"] == "review"
    assert result["reclaimable_safe"] == 300

    freed = files._delete_paths(str(tmp_path), files.HOGS_BY_KEY["esphome_build"])
    assert freed == 300
    assert not (tmp_path / "esphome" / ".esphome" / "build").exists()
    assert (outside / "keep.txt").exists()


def test_packages_detection_and_render(tmp_path: Path) -> None:
    """Both directory package modes are detected and rendered correctly."""
    (tmp_path / "configuration.yaml").write_text(
        "default_config:\nhomeassistant:\n  name: Home\n  packages: !include_dir_merge_named pkgs\n"
    )
    info = recorder_config.detect_packages(str(tmp_path))
    assert info.mode == "include_dir_merge_named"
    assert info.directory == (tmp_path / "pkgs").resolve()
    recorder_config.write_package(
        info, recorder_config.build_block(["sensor.b", "sensor.a"], {}, {})
    )
    data = yaml.safe_load(info.file.read_text())
    assert data == {
        "storage_manager": {"recorder": {"exclude": {"entities": ["sensor.a", "sensor.b"]}}}
    }
    assert recorder_config.block_entities(recorder_config.read_package(info)) == [
        "sensor.a",
        "sensor.b",
    ]
    recorder_config.write_package(info, {})
    assert not info.file.exists()



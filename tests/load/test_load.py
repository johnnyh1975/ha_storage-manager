"""Load tests: analysis, undo export and deletions on a large recorder database.

Run with ``pytest tests/load --load-rows=10000000 -s``. The database is
generated on the recorder thread straight into the recorder's own tables:
500 entities, one entity that no longer exists (5 % of the rows), 50
attribute variants and one noisy event type (10 % of the rows).

Each phase has a time limit per million rows and a limit for how much the
process's peak memory may grow, so a change that reads a whole table into
memory, or a quadratic loop, fails here.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
import json
import random
import resource
import time
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers.recorder import session_scope
import pytest
from pytest_homeassistant_custom_component.components.recorder.common import (
    async_wait_recording_done,
)

from custom_components.storage_manager import database, undo
from custom_components.storage_manager.recorder_tasks import async_run_on_recorder

from ..conftest import setup_entry

pytestmark = pytest.mark.usefixtures("prepared_hass")

ENTITIES = 500
ORPHAN = "sensor.load_orphan"
EVENT = "load_noise"
MB = 1024 * 1024

# limits: seconds per million rows, and MB of Python memory at the peak
LIMITS = {
    "analysis": (60.0, 256),
    "undo_export": (60.0, 128),
    "purge_orphan": (240.0, 256),
    "delete_events": (60.0, 256),
}


def _generate(instance: Any, rows: int) -> dict[str, int]:
    """Fill the recorder tables (recorder thread)."""
    rng = random.Random(4)
    now = time.time()
    span = 9 * 86400
    orphan_rows = rows // 20
    event_rows = rows // 10
    per_entity = (rows - orphan_rows) // ENTITIES
    with session_scope(session=instance.get_session()) as session:
        conn = session.connection().connection.driver_connection
        cur = conn.cursor()
        # after what Home Assistant has written since the start
        attr0 = cur.execute(
            "SELECT COALESCE(MAX(attributes_id), 0) FROM state_attributes"
        ).fetchone()[0]
        meta0 = cur.execute("SELECT COALESCE(MAX(metadata_id), 0) FROM states_meta").fetchone()[0]
        data0 = cur.execute("SELECT COALESCE(MAX(data_id), 0) FROM event_data").fetchone()[0]
        cur.executemany(
            "INSERT INTO state_attributes (attributes_id, hash, shared_attrs) VALUES (?, ?, ?)",
            [
                (
                    attr0 + i,
                    i,
                    json.dumps(
                        {
                            "unit_of_measurement": "W",
                            "friendly_name": f"Load {i}",
                            "v": "x" * (i * 4),
                        }
                    ),
                )
                for i in range(1, 51)
            ],
        )
        names = [f"sensor.load_{i}" for i in range(ENTITIES)] + [ORPHAN]
        cur.executemany(
            "INSERT INTO states_meta (metadata_id, entity_id) VALUES (?, ?)",
            [(meta0 + i + 1, name) for i, name in enumerate(names)],
        )

        def states() -> Any:
            for meta in range(meta0 + 1, meta0 + ENTITIES + 1):
                for n in range(per_entity):
                    ts = now - span + n * span / per_entity
                    yield (str(n % 100), attr0 + rng.randint(1, 50), meta, ts, ts, 0)
            for n in range(orphan_rows):
                ts = now - span + n * span / orphan_rows
                yield ("1", attr0 + rng.randint(1, 50), meta0 + ENTITIES + 1, ts, ts, 0)

        cur.executemany(
            "INSERT INTO states (state, attributes_id, metadata_id, last_updated_ts, "
            "last_changed_ts, origin_idx) VALUES (?, ?, ?, ?, ?, ?)",
            states(),
        )
        cur.execute("INSERT INTO event_types (event_type) VALUES (?)", (EVENT,))
        type_id = cur.lastrowid
        cur.executemany(
            "INSERT INTO event_data (data_id, hash, shared_data) VALUES (?, ?, ?)",
            [(data0 + i, i, json.dumps({"n": i})) for i in range(1, 101)],
        )
        cur.executemany(
            "INSERT INTO events (event_type_id, data_id, time_fired_ts, origin_idx) "
            "VALUES (?, ?, ?, 0)",
            (
                (type_id, data0 + rng.randint(1, 100), now - span + n * span / event_rows)
                for n in range(event_rows)
            ),
        )
    return {
        "states": per_entity * ENTITIES + orphan_rows,
        "orphan_rows": orphan_rows,
        "events": event_rows,
    }


async def _measure(name: str, rows: int, job: Callable[[], Awaitable[Any]]) -> tuple[Any, dict]:
    """Time and growth of the process's peak memory for one phase.

    The peak (ru_maxrss) covers Python and SQLite alike; it only grows, so a
    phase shows what it needed beyond everything before it.
    """
    rss_before = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    started = time.monotonic()
    result = await job()
    seconds = time.monotonic() - started
    growth_mb = (resource.getrusage(resource.RUSAGE_SELF).ru_maxrss - rss_before) / 1024
    per_million, max_mb = LIMITS[name]
    stats = {
        "phase": name,
        "rows": rows,
        "seconds": round(seconds, 1),
        "peak_memory_growth_mb": round(growth_mb, 1),
    }
    print(json.dumps(stats))
    assert seconds <= per_million * max(rows / 1e6, 1), stats
    assert growth_mb <= max_mb, stats
    return result, stats


async def test_large_database(hass: HomeAssistant, load_rows: int, tmp_path) -> None:
    """Analysis, undo export, purge and event deletion stay within their limits."""
    await setup_entry(hass)
    await async_wait_recording_done(hass)
    made: dict[str, int] = {}

    def generate(instance: Any) -> None:
        made.update(_generate(instance, load_rows))

    started = time.monotonic()
    assert await async_run_on_recorder(hass, generate)
    await async_wait_recording_done(hass)
    print(json.dumps({"generated": made, "seconds": round(time.monotonic() - started, 1)}))
    size = await database.async_database_size(hass, None)
    print(json.dumps({"database_mb": round((size or 0) / MB, 1)}))

    analysis, _ = await _measure(
        "analysis",
        load_rows,
        lambda: database.async_analyze(hass, database.AnalysisControl(pause=0)),
    )
    entities = analysis["entities"]
    assert len(entities) >= ENTITIES + 1
    assert entities[ORPHAN]["rows"] == made["orphan_rows"]
    assert {e["event_type"]: e["rows"] for e in analysis["events"]}[EVENT] == made["events"]

    spec = undo.Spec(states={ORPHAN: None})
    path = tmp_path / "load.undo.ndjson.gz"
    info, _ = await _measure(
        "undo_export",
        made["orphan_rows"],
        lambda: database.async_read_short(hass, lambda s: undo.export(s, path, spec)),
    )
    assert info["rows"]["states"] == made["orphan_rows"]

    async def purge() -> None:
        await database.async_purge_entities(hass, [ORPHAN], 0)
        await database.async_wait_idle(hass)
        await async_wait_recording_done(hass)

    await _measure("purge_orphan", made["orphan_rows"], purge)
    remaining = await database.async_read(
        hass,
        lambda s: s.execute(
            database.text(
                "SELECT COUNT(*) FROM states s JOIN states_meta m ON m.metadata_id = s.metadata_id "
                "WHERE m.entity_id = :e"
            ),
            {"e": ORPHAN},
        ).scalar(),
    )
    assert remaining == 0

    deleted, _ = await _measure(
        "delete_events", made["events"], lambda: database.async_delete_events(hass, [EVENT])
    )
    assert deleted >= made["events"]

#!/usr/bin/env python3
"""strings.json, every translations/*.json and the panel dictionaries must match.

Checks that all languages have exactly the same keys and the same
{placeholders} for every text, and that every option and every action
has its texts (a new option without a label shows its raw key).

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
INTEGRATION = ROOT / "custom_components" / "storage_manager"
PANEL_I18N = ROOT / "frontend" / "src" / "i18n.js"
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def flatten(data: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for key, value in data.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            out.update(flatten(value, path))
        else:
            out[path] = str(value)
    return out


def compare(name: str, reference: dict[str, str], other: dict[str, str]) -> list[str]:
    errors: list[str] = []
    for key in sorted(set(reference) - set(other)):
        errors.append(f"{name}: missing {key}")
    for key in sorted(set(other) - set(reference)):
        errors.append(f"{name}: extra {key}")
    for key in sorted(set(reference) & set(other)):
        want = set(PLACEHOLDER.findall(reference[key]))
        have = set(PLACEHOLDER.findall(other[key]))
        if want != have:
            errors.append(f"{name}: placeholders differ at {key}: {sorted(want)} vs {sorted(have)}")
    return errors


def panel_dicts() -> dict[str, dict[str, str]]:
    text = PANEL_I18N.read_text(encoding="utf-8")
    dicts: dict[str, dict[str, str]] = {}
    for match in re.finditer(r"const (\w+) = \{(.*?)\n\};", text, re.S):
        entries = re.findall(r'^\s{2}(\w+):\s*"((?:[^"\\]|\\.)*)"', match.group(2), re.M)
        dicts[match.group(1)] = dict(entries)
    return dicts


def completeness(strings: dict) -> list[str]:
    errors = []
    const = (INTEGRATION / "const.py").read_text(encoding="utf-8")
    names = dict(re.findall(r'^(CONF_\w+): Final = "(\w+)"', const, re.M))
    block = const.split("DEFAULT_OPTIONS", 1)[1].split("}", 1)[0]
    step = strings["options"]["step"]["init"]
    for conf in re.findall(r"(CONF_\w+):", block):
        key = names[conf]
        if key not in step.get("data", {}):
            errors.append(f"strings.json: option {key} has no label")
    services = (INTEGRATION / "services.py").read_text(encoding="utf-8")
    yaml_text = (INTEGRATION / "services.yaml").read_text(encoding="utf-8")
    for action in re.findall(r'^SERVICE_\w+ = "(\w+)"', services, re.M):
        if action not in strings.get("services", {}):
            errors.append(f"strings.json: action {action} has no texts")
        if not re.search(rf"^{action}:", yaml_text, re.M):
            errors.append(f"services.yaml: action {action} is missing")
    return errors


def main() -> int:
    errors: list[str] = []
    strings = json.loads((INTEGRATION / "strings.json").read_text(encoding="utf-8"))
    errors += completeness(strings)
    reference = flatten(strings)
    translations = sorted((INTEGRATION / "translations").glob("*.json"))
    if not translations:
        errors.append("no translations found")
    for path in translations:
        errors += compare(
            path.name, reference, flatten(json.loads(path.read_text(encoding="utf-8")))
        )

    dicts = panel_dicts()
    if "en" not in dicts:
        errors.append("panel i18n: no 'en' dictionary")
    else:
        for lang, values in dicts.items():
            if lang != "en":
                errors += compare(f"panel i18n {lang}", dicts["en"], values)

    if errors:
        print("\n".join(errors))
        return 1
    print(
        f"OK: strings.json, {len(translations)} translations and {len(dicts)} panel dictionaries match."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

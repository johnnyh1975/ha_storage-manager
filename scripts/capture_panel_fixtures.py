#!/usr/bin/env python3
"""Record the WebSocket answers the panel smoke test replays.

Run against a test instance with example data only (never a real home):

    HA_URL=ws://127.0.0.1:8123/api/websocket HA_TOKEN=... python3 scripts/capture_panel_fixtures.py

Paths of the machine are replaced; check the result with
scripts/check_private_data.py before committing it.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

import asyncio
import json
import os
from pathlib import Path
import time

import aiohttp

B = os.environ.get("HA_URL", "ws://127.0.0.1:8123/api/websocket")
tok = os.environ["HA_TOKEN"]
OUT = Path(__file__).resolve().parent.parent / "frontend" / "test" / "fixtures" / "ws.json"
HOME = os.path.expanduser("~")
CONFIG = os.environ.get("HA_CONFIG_DIR", "")
D = "storage_manager/"


async def main():
    async with aiohttp.ClientSession() as s, s.ws_connect(B, max_msg_size=0) as ws:
        await ws.receive_json()
        await ws.send_json({"type": "auth", "access_token": tok})
        await ws.receive_json()
        n = [0]

        async def call(t, **kw):
            n[0] += 1
            await ws.send_json({"id": n[0], "type": D + t, **kw})
            while True:
                m = await ws.receive_json()
                if m.get("id") == n[0] and m["type"] == "result":
                    if not m["success"]:
                        raise SystemExit(f"{t}: {m['error']}")
                    return m["result"]

        out = {}
        for t in [
            "overview",
            "entities",
            "backups",
            "health",
            "dead_entities",
            "unused_statistics",
            "kind_rules",
            "statistics_retention",
            "folder_roots",
        ]:
            out[t] = await call(t)
        ents = out["entities"]["rows"]
        big = max(ents, key=lambda r: r["est_bytes"])["entity_id"]
        out["entity_detail"] = await call("entity_detail", entity_id=big)
        out["raw_rows"] = await call("raw_rows", entity_id=big, kind="states", limit=5)
        out["writers"] = await call("writers", start=time.time() - 86400, end=time.time())
        out["retention_whatif"] = await call("retention_whatif", days=[3, 7, 14, 30])
        out["statistics_age_plan"] = await call("statistics_age_plan", stats_months=12)
        out["preview"] = await call("preview", targets=["files", "orphans", "statistics"])
        out["apply_preview"] = await call("apply_preview", retention={big: "drop"})
        undo_ids = [
            h["details"]["undo"]["id"]
            for h in out["overview"]["history"]
            if isinstance((h.get("details") or {}).get("undo"), dict)
        ]
        for uid in undo_ids:
            try:
                out["undo_preview"] = await call("undo_preview", undo_id=uid)
                break
            except SystemExit:
                continue
        roots = out["folder_roots"]["roots"]
        out["folder_scan"] = await call("folder_scan", root=roots[0]["path"])
        text = json.dumps(out, indent=1, sort_keys=True)
        # no paths of this machine in the repository
        if CONFIG:
            text = text.replace(CONFIG, "/config")
        text = text.replace(HOME, "/home/user")
        OUT.write_text(text + "\n")
        print(
            "written",
            len(text),
            "bytes;",
            "undo entries:",
            sum(1 for h in out["overview"]["history"] if (h.get("details") or {}).get("undo")),
        )


asyncio.run(main())

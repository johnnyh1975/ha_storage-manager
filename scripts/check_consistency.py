#!/usr/bin/env python3
"""Version numbers agree and relative Markdown links resolve.

- manifest.json version == const.VERSION == frontend/package.json version
  == the version badge in README.md
- every relative link/image in *.md points to an existing file
- README.md uses absolute links only (the Marketplace and HACS render it
  outside GitHub), and absolute links into this repository's main branch
  point to existing files

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
INTEGRATION = ROOT / "custom_components" / "storage_manager"
LINK = re.compile(r"!?\[[^\]]*\]\(([^)\s]+)\)")
REPO = "johnnyh1975/ha_storage-manager"
OWN = re.compile(
    rf"^https://(?:raw\.githubusercontent\.com/{REPO}/main|github\.com/{REPO}/(?:blob|tree)/main)/"
    r"([^#?]+)"
)


def versions() -> list[str]:
    errors = []
    manifest = json.loads((INTEGRATION / "manifest.json").read_text())["version"]
    const = re.search(r'VERSION: Final = "([^"]+)"', (INTEGRATION / "const.py").read_text())
    package = json.loads((ROOT / "frontend" / "package.json").read_text())["version"]
    badge = re.search(r"badge/version-([0-9][^-)]*)-", (ROOT / "README.md").read_text())
    found = {
        "const.VERSION": const.group(1) if const else None,
        "frontend/package.json": package,
        "README badge": badge.group(1) if badge else None,
    }
    for name, value in found.items():
        if value != manifest:
            errors.append(f"{name} is {value!r}, manifest.json is {manifest!r}")
    return errors


def links() -> list[str]:
    errors = []
    for md in ROOT.glob("**/*.md"):
        if "node_modules" in md.parts:
            continue
        readme = md == ROOT / "README.md"
        for target in LINK.findall(md.read_text(encoding="utf-8")):
            own = OWN.match(target)
            if own:
                if not (ROOT / own.group(1)).exists():
                    errors.append(f"{md.relative_to(ROOT)}: broken link {target}")
                continue
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                continue
            if readme:
                errors.append(f"README.md: use an absolute link instead of {target}")
                continue
            path = (md.parent / target.split("#", 1)[0]).resolve()
            if not path.exists():
                errors.append(f"{md.relative_to(ROOT)}: broken link {target}")
    return errors


def main() -> int:
    errors = versions() + links()
    if errors:
        print("\n".join(errors))
        return 1
    print("OK: versions agree and all relative Markdown links resolve.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

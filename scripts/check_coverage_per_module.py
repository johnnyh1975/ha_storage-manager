#!/usr/bin/env python3
"""Fail when any module of the integration is below the line-coverage threshold.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import argparse
import sys
import xml.etree.ElementTree as ET


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("report", help="coverage.xml (Cobertura format)")
    parser.add_argument(
        "--min", type=float, default=95.0, help="minimum line coverage per module in %%"
    )
    args = parser.parse_args()

    root = ET.parse(args.report).getroot()
    failures: list[str] = []
    rows: list[tuple[str, float]] = []
    for cls in root.iter("class"):
        filename = cls.get("filename", "")
        if "custom_components/storage_manager/" not in filename and not filename.endswith(".py"):
            continue
        lines = cls.find("lines")
        if lines is None:
            continue
        total = len(lines)
        covered = sum(1 for line in lines if int(line.get("hits", "0")) > 0)
        rate = 100.0 if total == 0 else covered / total * 100
        rows.append((filename, rate))
        if rate < args.min:
            failures.append(f"{filename}: {rate:.1f} % < {args.min:.0f} %")

    for filename, rate in sorted(rows):
        print(f"{rate:6.1f} %  {filename}")
    if not rows:
        print("No modules found in the coverage report.")
        return 1
    if failures:
        print("\nModules below the threshold:")
        print("\n".join(failures))
        return 1
    print(f"\nAll {len(rows)} modules at or above {args.min:.0f} % line coverage.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

from __future__ import annotations

import logging
from pathlib import Path

LOG_FILE = "home-assistant.log"
PREFIXES = ("homeassistant.components.", "custom_components.")


def _source(name: str) -> str:
    """Integration domain for an integration logger, else the library name."""
    for prefix in PREFIXES:
        if name.startswith(prefix):
            return name[len(prefix) :].split(".", 1)[0]
    return name.split(".", 1)[0]


def debug_sources(manager: logging.Manager | None = None) -> list[str]:
    """Integrations and libraries whose logger is set to debug explicitly.

    Only loggers with an explicit level count: what the logger integration,
    the "Enable debug logging" button or ``logger.set_level`` set. "default"
    stands for the root logger.
    """
    manager = manager or logging.Logger.manager
    found: set[str] = set()
    if manager.root.level == logging.DEBUG:
        found.add("default")
    for name, logger in list(manager.loggerDict.items()):
        if isinstance(logger, logging.Logger) and logger.level == logging.DEBUG:
            found.add(_source(name))
    return sorted(found)


def log_file_size(config_dir: str) -> int | None:
    """Size of Home Assistant's own log file, None if there is none."""
    path = Path(config_dir) / LOG_FILE
    try:
        return path.stat().st_size
    except OSError:
        return None

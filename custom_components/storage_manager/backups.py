"""Grandfather-father-son rotation of *local* backup copies.

Only the copy on the Home Assistant data disk is deleted. With
``require_offsite`` a local copy is kept unless at least one other
backup location (NAS, cloud, ...) holds the same backup.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import logging
from datetime import datetime
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.util import dt as dt_util

from .const import LOCAL_BACKUP_AGENTS

_LOGGER = logging.getLogger(__name__)


def _manager(hass: HomeAssistant) -> Any | None:
    try:
        from homeassistant.components.backup import (  # noqa: PLC0415
            async_get_manager,
        )

        return async_get_manager(hass)
    except Exception:  # noqa: BLE001 - backup integration not loaded
        return None


def _local_agent_ids(manager: Any) -> set[str]:
    ids = set(LOCAL_BACKUP_AGENTS)
    ids.update(getattr(manager, "local_backup_agents", {}) or {})
    return ids


async def async_list(hass: HomeAssistant) -> dict[str, Any] | None:
    """All backups with location info, newest first. None without backup integration."""
    manager = _manager(hass)
    if manager is None:
        return None
    backups, errors = await manager.async_get_backups()
    local_ids = _local_agent_ids(manager)
    items: list[dict[str, Any]] = []
    for backup in backups.values():
        agents = dict(backup.agents)
        local = [a for a in agents if a in local_ids]
        remote = [a for a in agents if a not in local_ids]
        local_size = sum(agents[a].size for a in local)
        items.append(
            {
                "backup_id": backup.backup_id,
                "name": backup.name,
                "date": backup.date,
                "automatic": bool(backup.with_automatic_settings),
                "local_agents": local,
                "remote_agents": remote,
                "local_size": int(local_size),
                "size": int(max((s.size for s in agents.values()), default=0)),
            }
        )
    items.sort(key=lambda b: b["date"], reverse=True)
    return {
        "backups": items,
        "local_total": sum(b["local_size"] for b in items),
        "agent_errors": sorted(errors),
    }


def plan_rotation(
    backups: list[dict[str, Any]],
    *,
    keep_daily: int,
    keep_weekly: int,
    keep_monthly: int,
    require_offsite: bool,
) -> list[dict[str, Any]]:
    """Decide for each local copy whether it stays and why (pure function)."""
    local = [b for b in backups if b["local_agents"]]
    local.sort(key=lambda b: b["date"], reverse=True)

    keep_reason: dict[str, str] = {}
    if local:
        keep_reason[local[0]["backup_id"]] = "newest"

    def bucket_keep(key_fn, limit: int, label: str) -> None:
        seen: list[Any] = []
        for item in local:
            when = _parse(item["date"])
            if when is None:
                keep_reason.setdefault(item["backup_id"], "unknown_date")
                continue
            key = key_fn(when)
            if key in seen:
                continue
            if len(seen) >= limit:
                break
            seen.append(key)
            keep_reason.setdefault(item["backup_id"], label)

    bucket_keep(lambda d: d.date(), keep_daily, "daily")
    bucket_keep(lambda d: tuple(d.isocalendar())[:2], keep_weekly, "weekly")
    bucket_keep(lambda d: (d.year, d.month), keep_monthly, "monthly")

    plan: list[dict[str, Any]] = []
    for item in local:
        reason = keep_reason.get(item["backup_id"])
        action = "keep"
        if reason is None:
            if require_offsite and not item["remote_agents"]:
                reason = "only_local"
            else:
                action = "delete_local"
                reason = "rotated"
        plan.append({**item, "action": action, "reason": reason})
    return plan


def _parse(value: str) -> datetime | None:
    parsed = dt_util.parse_datetime(value)
    return dt_util.as_local(parsed) if parsed else None


async def async_apply_rotation(
    hass: HomeAssistant, plan: list[dict[str, Any]]
) -> tuple[int, list[str]]:
    """Delete the local copies marked in plan. Returns (freed bytes, errors)."""
    manager = _manager(hass)
    if manager is None:
        return 0, ["backup integration not available"]
    freed = 0
    errors: list[str] = []
    for item in plan:
        if item["action"] != "delete_local":
            continue
        agent_errors = await manager.async_delete_backup(
            item["backup_id"], agent_ids=list(item["local_agents"])
        )
        if agent_errors:
            errors.extend(f"{item['name']}: {err}" for err in agent_errors.values())
            continue
        freed += item["local_size"]
        _LOGGER.info("Deleted local copy of backup %s", item["name"])
    return freed, errors

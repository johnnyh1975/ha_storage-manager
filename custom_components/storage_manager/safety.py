def backup_targets(manager: Any) -> tuple[list[str], str | None]:
    """Where the safety backup goes: the automatic-backup locations, else local."""
    available = set(getattr(manager, "backup_agents", {}) or {})
    config = getattr(getattr(manager, "config", None), "data", None)
    create = getattr(config, "create_backup", None)
    configured = [a for a in (getattr(create, "agent_ids", None) or []) if a in available]
    if configured:
        return configured, getattr(create, "password", None)
    local = [a for a in (getattr(manager, "local_backup_agents", {}) or {}) if a in available]
    local += [a for a in LOCAL_BACKUP_AGENTS if a in available and a not in local]
    return local[:1], None


def _usable(backup: Any) -> bool:
    agents = set(getattr(backup, "agents", {}) or {})
    failed = set(getattr(backup, "failed_agent_ids", []) or [])
    return bool(
        getattr(backup, "database_included", False)
        and getattr(backup, "homeassistant_included", False)
        and agents - failed
    )


def _when(backup: Any) -> datetime | None:
    return dt_util.parse_datetime(str(getattr(backup, "date", "")))


def _describe(backup: Any, *, created: bool) -> dict[str, Any]:
    agents = set(getattr(backup, "agents", {}) or {})
    failed = set(getattr(backup, "failed_agent_ids", []) or [])
    return {
        "backup_id": backup.backup_id,
        "name": backup.name,
        "date": backup.date,
        "agents": sorted(agents - failed),
        "created": created,
    }


async def async_recent_backup(
    hass: HomeAssistant, max_age: timedelta = BACKUP_REUSE_AGE
) -> dict[str, Any] | None:
    """Newest usable backup with the database that is recent enough."""
    manager = backup_mod.backup_manager(hass)
    if manager is None:
        return None
    backups, _errors = await manager.async_get_backups()
    limit = dt_util.utcnow() - max_age
    best: tuple[datetime, Any] | None = None
    for backup in backups.values():
        when = _when(backup)
        if when is None or when < limit or not _usable(backup):
            continue
        if best is None or when > best[0]:
            best = (when, backup)
    return _describe(best[1], created=False) if best else None


async def async_backup_size(hass: HomeAssistant, fallback: int) -> tuple[int, str]:
    """Expected size of a new backup: the newest one with the database, else the file."""
    manager = backup_mod.backup_manager(hass)
    if manager is not None:
        backups, _errors = await manager.async_get_backups()
        dated = [
            (when, b)
            for b in backups.values()
            if getattr(b, "database_included", False) and (when := _when(b)) is not None
        ]
        if dated:
            newest = max(dated, key=lambda item: item[0])[1]
            size = max((s.size for s in newest.agents.values()), default=0)
            if size:
                return int(size * BACKUP_MARGIN), "previous"
    return fallback, "file"


async def async_create_backup(hass: HomeAssistant) -> dict[str, Any]:
    """Create a backup of Home Assistant with the database and verify it."""
    manager = backup_mod.backup_manager(hass)
    if manager is None:
        raise SafetyError("backup_unavailable")
    agent_ids, password = backup_targets(manager)
    if not agent_ids:
        raise SafetyError("backup_no_location")
    started = dt_util.utcnow() - timedelta(minutes=1)
    name = f"Storage Manager {dt_util.now().strftime('%Y-%m-%d %H:%M')}"
    try:
        await manager.async_create_backup(
            agent_ids=agent_ids,
            extra_metadata={BACKUP_META_KEY: BACKUP_META_VALUE},
            include_addons=None,
            include_all_addons=False,
            include_database=True,
            include_folders=None,
            include_homeassistant=True,
            name=name,
            password=password,
        )
    except Exception as err:  # noqa: BLE001 - any failure stops the deletion
        raise SafetyError("backup_failed", str(err)) from err

    backups, _errors = await manager.async_get_backups()
    for backup in backups.values():
        meta = getattr(backup, "extra_metadata", {}) or {}
        ours = meta.get(BACKUP_META_KEY) == BACKUP_META_VALUE or backup.name == name
        when = _when(backup)
        if ours and when is not None and when >= started and _usable(backup):
            _LOGGER.info("Safety backup %s created", backup.name)
            return _describe(backup, created=True)
    raise SafetyError("backup_not_verified")



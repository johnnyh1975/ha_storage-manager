"""Safety chain before anything is deleted from the database.

1. Enough free space for the work and for a backup.
2. A full SQLite ``PRAGMA integrity_check``; a clean result is reused
   for three days, a damaged database stops the deletion.
3. A verified backup of Home Assistant including the database. A backup
   with the database that is at most six hours old is reused.

The chain follows ideas from HA Housekeeper (MIT licence).

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Callable
from datetime import datetime, timedelta
import logging
from pathlib import Path
import sqlite3
import time
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.exceptions import HomeAssistantError
from homeassistant.util import dt as dt_util

from . import backups as backup_mod
from .const import LOCAL_BACKUP_AGENTS
from .store import ManagerStore

_LOGGER = logging.getLogger(__name__)

MIB = 1024 * 1024
MIN_FREE = 512 * MIB
INTEGRITY_MAX_AGE = 3 * 86400
INTEGRITY_TIMEOUT = 15 * 60
INTEGRITY_MAX_ERRORS = 10
BACKUP_REUSE_AGE = timedelta(hours=6)
BACKUP_META_KEY = "storage_manager"
BACKUP_META_VALUE = "before_cleanup"

RESULT_OK = "ok"
RESULT_CORRUPT = "corrupt"
RESULT_TIMEOUT = "timeout"
RESULT_ERROR = "error"
RESULT_UNSUPPORTED = "unsupported"


class SafetyError(HomeAssistantError):
    """A step of the safety chain failed; ``reason`` is a translation key."""

    def __init__(self, reason: str, detail: str = "") -> None:
        """Initialize."""
        super().__init__(f"{reason}: {detail}" if detail else reason)
        self.reason = reason
        self.detail = detail


# ----------------------------------------------------------------------
# free space
# ----------------------------------------------------------------------


WORK_FACTOR = 3
BACKUP_MARGIN = 1.1


def work_space(live_bytes: int, delete_bytes: int) -> int:
    """Room the deletion itself needs.

    Deleting rows writes the touched pages to the write-ahead log and frees
    pages inside the file; the file does not grow. A few times the deleted
    bytes is plenty, half of the data is the upper bound (HA Housekeeper's
    rule) and 512 MB the floor.
    """
    return max(MIN_FREE, min(live_bytes // 2, delete_bytes * WORK_FACTOR))


def space_needed(*, live_bytes: int, delete_bytes: int, backup_bytes: int) -> int:
    """Free space the deletion needs: work space plus room for a new backup."""
    return work_space(live_bytes, delete_bytes) + backup_bytes



# integrity
# ----------------------------------------------------------------------


def integrity_check(path: Path, timeout: float = INTEGRITY_TIMEOUT) -> dict[str, Any]:
    """Full integrity check on a read-only connection (blocking)."""
    deadline = time.monotonic() + timeout
    try:
        conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=30)
    except sqlite3.Error as err:
        return {"result": RESULT_ERROR, "details": [str(err)]}
    conn.set_progress_handler(lambda: int(time.monotonic() > deadline), 1000)
    try:
        rows = conn.execute(f"PRAGMA integrity_check({INTEGRITY_MAX_ERRORS})").fetchall()
    except sqlite3.OperationalError as err:
        if "interrupt" in str(err):
            return {"result": RESULT_TIMEOUT, "details": []}
        return {"result": RESULT_ERROR, "details": [str(err)]}
    except sqlite3.DatabaseError as err:
        # "database disk image is malformed" and friends
        return {"result": RESULT_CORRUPT, "details": [str(err)]}
    finally:
        conn.close()
    lines = [str(row[0]) for row in rows]
    if lines == ["ok"]:
        return {"result": RESULT_OK, "details": []}
    return {"result": RESULT_CORRUPT, "details": lines[:INTEGRITY_MAX_ERRORS]}


def integrity_fresh(cached: dict[str, Any] | None, now: float) -> bool:
    """A clean result that is recent enough to skip the check."""
    return bool(
        cached
        and cached.get("result") == RESULT_OK
        and now - float(cached.get("at") or 0) < INTEGRITY_MAX_AGE
    )


async def async_integrity(
    hass: HomeAssistant, path: Path | None, store: ManagerStore, *, force: bool = False
) -> dict[str, Any]:
    """Integrity of the recorder file, reusing a recent clean result."""
    if path is None:
        return {"result": RESULT_UNSUPPORTED, "details": []}
    cached = store.data.integrity
    if not force and integrity_fresh(cached, time.time()):
        return {**(cached or {}), "cached": True}
    result = await hass.async_add_executor_job(integrity_check, path)
    result["at"] = time.time()
    store.data.integrity = result
    store.schedule_save()
    return {**result, "cached": False}



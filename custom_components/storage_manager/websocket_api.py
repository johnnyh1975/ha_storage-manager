async def _remove_exclusion_orphans(hass: HomeAssistant, c: StorageCoordinator, msg: Msg) -> Msg:
    return await c.async_remove_exclusion_orphans()


async def _dismiss(hass: HomeAssistant, c: StorageCoordinator, msg: Msg) -> Msg:
    if not msg.get("undo"):
        await c.async_advice()
    c.dismiss(msg.get("entity_ids") or [], undo=msg.get("undo", False))
    return {"dismissed": len(c.store.data.dismissed)}


async def _kind_rules(hass: HomeAssistant, c: StorageCoordinator, msg: Msg) -> Msg:
    rules = c.set_kind_rules(msg["rules"])
    await c.async_refresh()
    return {"kind_rules": rules}


async def _apply(hass: HomeAssistant, c: StorageCoordinator, msg: Msg) -> Msg:
    return await c.async_apply_recorder_changes(
        retention=msg.get("retention") or {},
        excluded=msg.get("excluded") or {},
        purge_now=msg.get("purge_now", True),
        skip_backup=msg.get("skip_backup", False),
    )


async def _analyze(hass: HomeAssistant, c: StorageCoordinator, msg: Msg) -> Msg:
    try:
        result = await c.async_run_analysis(force_sizes=msg.get("force_sizes", False))
    except database.AnalysisCancelled:
        return {"cancelled": True}
    return {
        "generated_at": result["generated_at"],
        "duration_s": result["duration_s"],
        "cancelled": False,
    }



# how long a preview's selection can be confirmed
PLAN_MAX_AGE = 15 * 60


@dataclass
class Selection:
    """What one cleanup deletes, chosen once.

    The preview, the targeted backup and the deletion all use the same
    selection, so the deletion never removes rows the backup did not save.
    """

    orphans: list[str] = field(default_factory=list)
    orphan_bytes: int = 0
    statistics: list[str] = field(default_factory=list)
    statistics_bytes: int = 0
    unused: list[dict[str, Any]] = field(default_factory=list)
    dead: list[dict[str, Any]] = field(default_factory=list)
    events: list[dict[str, Any]] = field(default_factory=list)
    # the newest event when chosen: later events are neither saved nor deleted
    events_max_id: int | None = None
    age: dict[str, Any] | None = None

    def ids(self) -> dict[str, list[str]]:
        """The chosen ids per target, as a preview keeps them."""
        return {
            "orphans": list(self.orphans),
            "statistics": list(self.statistics),
            "unused_statistics": [i["statistic_id"] for i in self.unused],
            "dead": [i["entity_id"] for i in self.dead],
            "events": [e["event_type"] for e in self.events],
        }


def _bound(planned: list[str] | None, valid: list[str]) -> list[str]:
    """Ids of a preview that are still valid; an empty preview stays empty."""
    allowed = set(valid)
    return [i for i in planned or [] if i in allowed]


def _bound_age(current: dict[str, Any], planned: dict[str, Any] | None) -> dict[str, Any]:
    """Old statistics as the preview showed them: its statistics, its cutoffs at most.

    Time moves the cutoffs on; rows that aged past the limit after the
    preview wait for the next run.
    """
    cutoffs: dict[str, float] = (planned or {}).get("cutoffs") or {}
    items = [
        {**i, "cutoff": min(float(i["cutoff"]), float(cutoffs[i["statistic_id"]]))}
        for i in current.get("items") or []
        if i["statistic_id"] in cutoffs
    ]
    rows = int(current.get("rows") or 0)
    kept = sum(int(i["rows"]) for i in items)
    share = kept / rows if rows else 0.0
    return {
        **current,
        "items": items,
        "rows": kept,
        "bytes": int(int(current.get("bytes") or 0) * share),
    }


class CleanupService:
    """Runs the cleanups of one coordinator."""

    def __init__(self, coordinator: StorageCoordinator) -> None:
        """Initialize."""
        self._c = coordinator
        self._plans: dict[str, tuple[float, frozenset[str], dict[str, Any]]] = {}

    async def async_select(
        self,
        targets: list[str],
        *,
        entity_ids: list[str] | None = None,
        statistic_ids: list[str] | None = None,
        event_types: list[str] | None = None,
        plan: dict[str, Any] | None = None,
    ) -> Selection:
        """Choose what the targets delete: from a preview's plan, else fresh.

        From a plan, only ids that are still valid stay: never more than
        the preview showed, never something that stopped being an orphan.
        """
        c = self._c
        sel = Selection()
        analysis = c.store.data.analysis or {}
        if "orphans" in targets:
            valid = c.orphans()["entities"]
            if plan is not None:
                sel.orphans = _bound(plan.get("orphans"), valid)
            else:
                sel.orphans = _chosen(entity_ids if "dead" not in targets else None, valid)
            entities = analysis.get("entities") or {}
            sel.orphan_bytes = sum(
                int(entities[e].get("est_state_bytes", entities[e].get("est_bytes", 0)))
                for e in sel.orphans
                if e in entities
            )
        if "statistics" in targets:
            valid = c.orphans()["statistics"]
            sel.statistics = (
                _bound(plan.get("statistics"), valid)
                if plan is not None
                else _chosen(statistic_ids, valid)
            )
            known = analysis.get("statistics") or {}
            sel.statistics_bytes = sum(
                int((known.get(i) or {}).get("est_bytes") or 0) for i in sel.statistics
            )
        if "unused_statistics" in targets:
            wanted = plan.get("unused_statistics") if plan is not None else statistic_ids
            sel.unused = (
                [] if plan is not None and not wanted else await c.async_unused_selection(wanted)
            )
        if "dead" in targets:
            sel.dead = await c.async_dead_selection(
                plan.get("dead") if plan is not None else entity_ids
            )
        if "events" in targets:
            wanted = plan.get("events") if plan is not None else event_types
            sel.events = [] if plan is not None and not wanted else c.events_selection(wanted)
            if sel.events:
                sel.events_max_id = await database.async_max_event_id(c.hass)
        if "statistics_age" in targets:
            sel.age = await c.async_statistics_age_current()
            if plan is not None:
                sel.age = _bound_age(sel.age, plan.get("statistics_age"))
        return sel

    def _keep_plan(self, targets: list[str], sel: Selection, extra: dict[str, Any]) -> str:
        now = time.monotonic()
        self._plans = {k: v for k, v in self._plans.items() if now - v[0] < PLAN_MAX_AGE}
        plan_id = secrets.token_hex(8)
        kept: dict[str, Any] = {**sel.ids(), **extra}
        if sel.age is not None:
            data = self._c.store.data
            kept["statistics_age"] = {
                "limits": [data.stats_keep_months, data.energy_stats_keep_months],
                "cutoffs": {i["statistic_id"]: i["cutoff"] for i in sel.age.get("items") or []},
            }
        self._plans[plan_id] = (now, frozenset(targets), kept)
        return plan_id

    def _take_plan(self, plan_id: str, targets: list[str]) -> dict[str, Any]:
        """The ids a preview showed, only for the targets it covered.

        It stays until it expires or a cleanup ran with it: a retry after a
        blocked safety chain (without the backup) still deletes only what the
        preview showed.
        """
        found = self._plans.get(plan_id)
        if found is None or time.monotonic() - found[0] >= PLAN_MAX_AGE:
            raise HomeAssistantError("plan_expired")
        if not set(targets) <= found[1]:
            raise HomeAssistantError("plan_targets")
        age = found[2].get("statistics_age")
        data = self._c.store.data
        if (
            "statistics_age" in targets
            and age is not None
            and age["limits"]
            != [
                data.stats_keep_months,
                data.energy_stats_keep_months,
            ]
        ):
            # the limits changed since the preview: what it showed no longer holds
            raise HomeAssistantError("plan_expired")
        return found[2]

    async def async_preview(
        self,
        targets: list[str],
        *,
        statistic_ids: list[str] | None = None,
        event_types: list[str] | None = None,
        entity_ids: list[str] | None = None,
    ) -> dict[str, Any]:
        """What a cleanup would do, without doing it.

        The selection is kept under a plan id: confirming the preview with it
        deletes exactly what was shown, as far as it is still valid.
        """
        await self._c.async_refresh()
        data = self._c.data
        preview: dict[str, Any] = {}
        sel = await self.async_select(
            targets, entity_ids=entity_ids, statistic_ids=statistic_ids, event_types=event_types
        )
        if "unused_statistics" in targets:
            items = sel.unused
            preview["unused_statistics"] = {
                "bytes": sum(i["bytes"] for i in items),
                "items": items,
                "switch_off": sum(1 for i in items if i["kind"] in ("noise", "time")),
            }
        if "events" in targets:
            items = sel.events
            preview["events"] = {
                "bytes": sum(int(i.get("est_bytes") or 0) for i in items),
                "rows": sum(int(i["rows"]) for i in items),
                "items": items,
            }
        if "dead" in targets:
            preview["dead"] = {"bytes": sum(i["bytes"] for i in sel.dead), "items": sel.dead}
        if sel.age is not None:
            preview["statistics_age"] = {k: v for k, v in sel.age.items() if k != "items"}
        extra: dict[str, Any] = {}
        if "backups" in targets:
            plan = [p for p in self._c.backup_plan() if p["action"] == "delete_local"]
            extra["backups"] = [p["backup_id"] for p in plan]
            preview["backups"] = {
                "bytes": sum(p["local_size"] for p in plan),
                "items": [
                    {"name": p["name"], "date": p["date"], "bytes": p["local_size"]} for p in plan
                ],
            }
        if "files" in targets:
            hogs = [h for h in (data["files"] or {}).get("hogs", []) if h["safety"] == "safe"]
            extra["files"] = [h["key"] for h in hogs]
            preview["files"] = {
                "bytes": sum(h["size_bytes"] for h in hogs),
                "items": [
                    {"name": h["key"], "bytes": h["size_bytes"], "paths": h["paths"]} for h in hogs
                ],
            }
        if "orphans" in targets:
            preview["orphans"] = {"bytes": sel.orphan_bytes, "items": sel.orphans}
        if "statistics" in targets:
            preview["statistics"] = {"bytes": sel.statistics_bytes, "items": sel.statistics}
        if "purge" in targets:
            obsolete = (self._c.store.data.analysis or {}).get("obsolete") or {}
            preview["purge"] = {
                "bytes": int(obsolete.get("bytes") or 0),
                "rows": int(obsolete.get("states") or 0) + int(obsolete.get("events") or 0),
            }
        if "repack" in targets:
            preview["repack"] = {
                "bytes": data["reclaimable"]["repack"],
                "possible": self._c.repack_possible(),
                "plan": data["database"].get("repack"),
            }
        if "docker" in targets:
            preview["docker"] = {"bytes": None, "possible": bool(data["is_hassio"])}
        preview["total"] = sum(int(p.get("bytes") or 0) for p in preview.values())
        db_targets: list[str] = [t for t in DB_DELETE_TARGETS if t in targets]
        if db_targets:
            preview["safety"] = await self._c.async_safety_plan(
                delete_bytes=sum(int((preview.get(t) or {}).get("bytes") or 0) for t in db_targets),
                backup_needed=_needs_backup(db_targets),
                undo=self._c.undo.planned(db_targets),
            )
        preview["plan_id"] = self._keep_plan(targets, sel, extra)
        return preview

    async def async_clean(
        self,
        targets: list[str],
        *,
        hog_keys: list[str] | None = None,
        statistic_ids: list[str] | None = None,
        entity_ids: list[str] | None = None,
        skip_backup: bool = False,
        repack_method: str | None = None,
        convert: bool = True,
        event_types: list[str] | None = None,
        plan_id: str | None = None,
    ) -> dict[str, Any]:
        """Execute cleanup targets. Returns freed bytes per target.

        Order: what frees space without touching the database first, then
        the safety chain, then deletions in the database, then the repack.
        With ``plan_id`` (from the preview) only what the preview showed goes.
        """
        unknown = set(targets) - set(ALL_CLEAN_TARGETS)
        if unknown:
            raise HomeAssistantError(f"Unknown cleanup targets: {', '.join(sorted(unknown))}")
        plan = self._take_plan(plan_id, targets) if plan_id is not None else None
        if self._c.lock.locked():
            raise HomeAssistantError("Another cleanup is running")
        async with self._c.lock:
            await self._c.async_refresh()
            before = self._c.data["disk"]["free"] if self._c.data else 0
            results: dict[str, Any] = {}
            errors: list[str] = []
            deleted: dict[str, Any] = {}
            blocked: dict[str, str] | None = None
            safety_result: dict[str, Any] | None = None
            undo_info: dict[str, Any] | None = None
            failure: Exception | None = None
            try:
                await self._clean_outside_database(targets, hog_keys, results, errors, plan)
                db_targets: list[str] = [t for t in DB_DELETE_TARGETS if t in targets]
                # chosen once: the backup and the deletion work on the same rows
                sel = await self.async_select(
                    db_targets,
                    entity_ids=entity_ids,
                    statistic_ids=statistic_ids,
                    event_types=event_types,
                    plan=plan,
                )
                if db_targets or "repack" in targets:
                    try:
                        if db_targets:
                            estimate = self._delete_estimate(db_targets, sel)
                            planned = self._c.undo.planned(db_targets)
                            safety_result = await self._c.async_safety(
                                skip_backup=skip_backup or planned,
                                delete_bytes=estimate,
                                backup_needed=_needs_backup(db_targets),
                            )
                            if planned:
                                spec = self._c.undo.spec_for(db_targets, sel)
                                undo_info = await self._c.undo.async_protect(
                                    spec, estimate, skip_backup, safety_result
                                )
                        else:
                            await self._async_require_integrity()
                    except safety.SafetyError as err:
                        blocked = {"reason": err.reason, "detail": err.detail}
                if blocked is None and db_targets:
                    await self._c.store.async_mark_running("cleanup", {"targets": db_targets})
                if blocked is None:
                    await self._clean_database(db_targets, sel, results, deleted)
                    if "unused_statistics" in db_targets:
                        await self._clean_unused_statistics(sel, results, deleted, errors)
                    if "events" in db_targets:
                        await self._clean_events(sel, results, deleted)
                    if "dead" in db_targets:
                        await self._clean_dead(sel, results, deleted)
                    if "statistics_age" in db_targets:
                        await self._clean_statistics_age(results, deleted, sel.age)
                    if db_targets:
                        # a fresh sample for the effect chart and fresh sizes
                        self._c.schedule_reanalysis()
                    if "repack" in targets:
                        await self._clean_repack(repack_method, convert, results, errors)
            except Exception as err:  # noqa: BLE001 - logged with what was done, then raised
                # what was deleted until here, and the backup for undo, must
                # stay in the history
                failure = err
            finally:
                self._c.set_busy(None)
                if self._c.store.data.running is not None:
                    await self._c.store.async_clear_running()
                if plan_id is not None and blocked is None:
                    # used up: a second run would delete restored rows again
                    self._plans.pop(plan_id, None)

            # the Supervisor breakdown is cached for an hour; it changed now
            self._c.invalidate("breakdown")
            await self._c.async_refresh()
            after = self._c.data["disk"]["free"] if self._c.data else before
            measured = max(after - before, 0)
            reported = sum(int(v or 0) for v in results.values())
            freed = max(measured, reported)
            backup_info = (safety_result or {}).get("backup")
            if freed or results or blocked or failure is not None:
                details: dict[str, Any] = {"targets": targets, "results": results, "errors": errors}
                if failure is not None:
                    details["failed"] = str(failure)[:200] or type(failure).__name__
                if deleted:
                    details["deleted"] = deleted
                if backup_info:
                    details["backup"] = backup_info["name"]
                if undo_info and blocked is None:
                    details["undo"] = undo_info
                if blocked:
                    details["blocked"] = blocked["reason"]
                self._c.store.log("cleanup", freed, details)
                self._c.store.schedule_save()
                self._c.async_set_updated_data(
                    {**self._c.data, "freed_total": self._c.store.data.freed_total}
                )
            if failure is not None:
                raise failure
            return {
                "freed": freed,
                "measured": measured,
                "results": results,
                "errors": errors,
                "blocked": blocked,
                "backup": backup_info,
                "undo": undo_info if blocked is None else None,
            }

    def _delete_estimate(self, db_targets: list[str], sel: Selection) -> int:
        """Bytes the database targets are expected to delete."""
        total = sel.orphan_bytes + sel.statistics_bytes
        total += sum(int(i["bytes"]) for i in sel.unused) + sum(int(i["bytes"]) for i in sel.dead)
        total += sum(int(e.get("est_bytes") or 0) for e in sel.events)
        if sel.age is not None:
            total += int(sel.age["bytes"])
        if "purge" in db_targets:
            obsolete = (self._c.store.data.analysis or {}).get("obsolete") or {}
            total += int(obsolete.get("bytes") or 0)
        return total

    async def _clean_outside_database(
        self,
        targets: list[str],
        hog_keys: list[str] | None,
        results: dict[str, Any],
        errors: list[str],
        plan: dict[str, Any] | None = None,
    ) -> None:
        if "backups" in targets:
            self._c.set_busy("backups")
            # a fresh list: a copy elsewhere may have gone since the last poll
            fresh = await backup_mod.async_list(self._c.hass)
            if fresh is not None and fresh["agent_errors"]:
                # a location did not answer: whether a copy is there is unknown
                errors.append(
                    "backup rotation skipped, not every backup location answered: "
                    + ", ".join(fresh["agent_errors"])
                )
                results["backups"] = 0
            else:
                rotation = self._c.backup_plan(fresh) if fresh is not None else []
                if plan is not None:
                    # only copies the preview listed; a backup that arrived since waits
                    shown = set(plan.get("backups") or [])
                    rotation = [p for p in rotation if p["backup_id"] in shown]
                freed, errs = await backup_mod.async_apply_rotation(self._c.hass, rotation)
                results["backups"] = freed
                errors += errs
            self._c.invalidate("backups", "breakdown")
        if "files" in targets:
            self._c.set_busy("files")
            scan = (self._c.data or {}).get("files") or {}
            keys = hog_keys or [h["key"] for h in scan.get("hogs", []) if h["safety"] == "safe"]
            if plan is not None:
                shown_keys = set(plan.get("files") or [])
                keys = [k for k in keys if k in shown_keys]
            freed = 0
            for key in keys:
                if key not in files.HOGS_BY_KEY:
                    errors.append(f"unknown file category {key}")
                    continue
                freed += await files.async_clean_hog(self._c.hass, key)
            results["files"] = freed
            self._c.invalidate("files", "breakdown")
        if "docker" in targets:
            if not is_hassio(self._c.hass):
                errors.append("docker cleanup needs the Supervisor")
            else:
                self._c.set_busy("docker")
                await disk.async_supervisor_repair(self._c.hass)
                results["docker"] = 0
                self._c.invalidate("breakdown")

    async def _async_require_integrity(self) -> None:
        """A repack alone needs no backup, but never runs on a damaged file."""
        self._c.set_busy("safety_integrity")
        result = await safety.async_integrity(
            self._c.hass, database.sqlite_path(self._c.hass), self._c.store
        )
        if result["result"] == safety.RESULT_CORRUPT:
            raise safety.SafetyError("corrupt", "; ".join(result.get("details") or []))
        if result["result"] == safety.RESULT_ERROR:
            # a repack rewrites the whole file: not after a check that could not run
            raise safety.SafetyError("integrity_error", "; ".join(result.get("details") or []))

    async def _clean_database(
        self,
        db_targets: list[str],
        sel: Selection,
        results: dict[str, Any],
        deleted: dict[str, Any],
    ) -> None:
        if "orphans" in db_targets:
            self._c.set_busy("orphans")
            await database.async_purge_entities(self._c.hass, sel.orphans, 0)
            results["orphans"] = sel.orphan_bytes
            deleted["entities"] = sel.orphans[:LOG_IDS_MAX]
            self._c.drop_from_analysis(sel.orphans)
        if "statistics" in db_targets:
            self._c.set_busy("statistics")
            await database.async_clear_statistics(self._c.hass, sel.statistics)
            results["statistics"] = sel.statistics_bytes
            deleted["statistics"] = sel.statistics[:LOG_IDS_MAX]
            known = (self._c.store.data.analysis or {}).get("statistics") or {}
            for sid in sel.statistics:
                known.pop(sid, None)
        if "purge" in db_targets:
            self._c.set_busy("purge")
            obsolete = (self._c.store.data.analysis or {}).get("obsolete") or {}
            await database.async_purge(self._c.hass)
            await database.async_wait_idle(self._c.hass)
            results["purge"] = int(obsolete.get("bytes") or 0)
            deleted["older_than_days"] = get_instance(self._c.hass).keep_days
            if self._c.store.data.analysis is not None:
                self._c.store.data.analysis["obsolete"] = {
                    **obsolete,
                    "states": 0,
                    "events": 0,
                    "bytes": 0,
                }

    async def _clean_unused_statistics(
        self,
        sel: Selection,
        results: dict[str, Any],
        deleted: dict[str, Any],
        errors: list[str],
    ) -> None:
        self._c.set_busy("unused_statistics")
        items = sel.unused
        switch_off = [i["statistic_id"] for i in items if i["kind"] in ("noise", "time")]
        if switch_off:
            data = self._c.store.data
            data.stats_off = sorted({*data.stats_off, *switch_off})
            self._c.store.schedule_save()
            if not await self._c.async_sync_package():  # pragma: no cover - checked above
                errors.append("packages_missing")
        ids = [i["statistic_id"] for i in items]
        await database.async_clear_statistics(self._c.hass, ids)
        await database.async_wait_idle(self._c.hass)
        results["unused_statistics"] = sum(i["bytes"] for i in items)
        deleted["unused_statistics"] = ids[:LOG_IDS_MAX]
        if switch_off:
            deleted["statistics_off"] = switch_off[:LOG_IDS_MAX]
        stats = (self._c.store.data.analysis or {}).get("statistics") or {}
        for sid in ids:
            stats.pop(sid, None)

    async def _clean_dead(
        self,
        sel: Selection,
        results: dict[str, Any],
        deleted: dict[str, Any],
    ) -> None:
        """Disable dead entities, then delete their history and statistics."""
        self._c.set_busy("dead")
        items = sel.dead
        ids = [i["entity_id"] for i in items]
        self._c.disable_entities(ids)
        await database.async_purge_entities(self._c.hass, ids, 0)
        await database.async_clear_statistics(self._c.hass, ids)
        await database.async_wait_idle(self._c.hass)
        results["dead"] = sum(i["bytes"] for i in items)
        deleted["dead"] = ids
        self._c.drop_from_analysis(ids)
        stats = (self._c.store.data.analysis or {}).get("statistics") or {}
        for entity_id in ids:
            stats.pop(entity_id, None)

    async def _clean_events(
        self,
        sel: Selection,
        results: dict[str, Any],
        deleted: dict[str, Any],
    ) -> None:
        items = sel.events
        if not items:
            results["events"] = 0
            return
        self._c.set_busy("events")
        types = [e["event_type"] for e in items]
        rows = await database.async_delete_events(self._c.hass, types, max_id=sel.events_max_id)
        results["events"] = sum(int(e.get("est_bytes") or 0) for e in items) if rows else 0
        deleted["event_types"] = types
        deleted["event_rows"] = rows
        analysis = self._c.store.data.analysis
        if analysis is not None:
            analysis["events"] = [
                e for e in analysis.get("events") or [] if e["event_type"] not in set(types)
            ]

    async def _clean_statistics_age(
        self,
        results: dict[str, Any],
        deleted: dict[str, Any],
        plan: dict[str, Any] | None = None,
    ) -> None:
        self._c.set_busy("statistics_age")
        # the plan the targeted backup was written for, so both use the same cutoffs
        plan = plan if plan is not None else await self._c.async_statistics_age_current()
        rows = await self._c.async_delete_old_statistics(plan)
        data = self._c.store.data
        if data.stats_keep_months or data.energy_stats_keep_months:
            data.stats_limits_applied = [data.stats_keep_months, data.energy_stats_keep_months]
            self._c.store.schedule_save()
        results["statistics_age"] = plan["bytes"] if rows else 0
        deleted["statistics_age"] = {
            "rows": rows,
            "statistics": len(plan["items"]),
            "stats_months": data.stats_keep_months,
            "energy_months": data.energy_stats_keep_months,
        }

    async def _clean_repack(
        self,
        method: str | None,
        convert: bool,
        results: dict[str, Any],
        errors: list[str],
    ) -> None:
        await self._c.async_refresh()  # free space and free pages after the deletions
        size_before = self._c.data["database"]["size"] or 0
        path = database.sqlite_path(self._c.hass)
        plan = self._c.data["database"].get("repack")
        if path is None or plan is None or not tasks_available():
            if not self._c.repack_possible():
                errors.append("not enough free space for repack")
                return
            self._c.set_busy("repack")
            await database.async_repack(self._c.hass)
            await database.async_wait_idle(self._c.hass)
        else:
            method = method or plan["method"]
            option = plan["options"].get(method or "") if method else None
            if option is None or not option["possible"]:
                errors.append("not enough free space for repack")
                return
            self._c.set_busy("repack")
            await repack.async_repack(
                self._c.hass,
                path,
                method=str(method),
                convert=convert and not plan["incremental_ready"],
                on_progress=self._repack_progress,
            )
        size_after = await database.async_database_size(self._c.hass, self._c.store.data.analysis)
        results["repack"] = max(size_before - (size_after or size_before), 0)
        if self._c.store.data.analysis is not None:
            self._c.store.data.analysis["freelist_bytes"] = 0
        # new size sample for the effect chart and fresh sizes per entity
        self._c.schedule_reanalysis()

    def _repack_progress(self, share: float) -> None:
        self._c.busy = f"repack:{round(share * 100)}"
        self._c.notify()

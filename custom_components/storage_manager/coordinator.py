    def recorder_status(self) -> dict[str, Any]:
        """Status of tiers/exclusions/settings incl. pending restart."""
        data = self.store.data
        written = recorder_config.block_items(data.package_written)
        at_start = recorder_config.block_items(self.package_at_start)
        desired = recorder_config.block_items(self.desired_block())
        instance = get_instance(self.hass)
        return {
            "packages": self.packages.as_dict(),
            "excluded_count": len(data.excluded),
            "core_entity_options": self.core_entity_options,
            "retention_count": len(data.retention),
            "restart_required": written != at_start,
            "pending_restart": sorted(written ^ at_start),
            "unwritten": sorted(desired ^ written),
            "yaml_filters": self.yaml_filters,
            "keep_days": instance.keep_days,
            "tiers": dict(RETENTION_TIERS),
            "filters": {k: data.filters.get(k, []) for k in recorder_config.FILTER_KEYS},
            "exclusion_orphans": self.exclusion_orphans(),
            "settings": data.settings,
            "locked_settings": self.locked_settings,
            "effective_settings": {
                "purge_keep_days": instance.keep_days,
                "commit_interval": instance.commit_interval,
                "auto_purge": instance.auto_purge,
                "auto_repack": instance.auto_repack,
            },
        }

    async def _async_sync_package(self) -> bool:
        """Write the package file if it differs. False when packages are missing."""
        data = self.store.data
        desired = self.desired_block()
        if (
            recorder_config.block_items(desired)
            == recorder_config.block_items(data.package_written)
            and desired == data.package_written
        ):
            return True
        if not self.packages.available:
            return False
        await self.hass.async_add_executor_job(
            recorder_config.write_package, self.packages, desired
        )
        data.package_written = desired
        data.excluded_written = list(data.excluded)
        self.store.schedule_save()
        return True

    async def async_apply_settings(
        self,
        *,
        filters: dict[str, list[str]] | None = None,
        settings: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Change exclusion filters and/or global recorder settings."""
        data = self.store.data
        if filters is not None:
            unknown = set(filters) - set(recorder_config.FILTER_KEYS)
            if unknown:
                raise HomeAssistantError(f"Unknown filter {', '.join(sorted(unknown))}")
            data.filters = {
                key: sorted({str(v).strip() for v in values if str(v).strip()})
                for key, values in filters.items()
            }
        if settings is not None:
            try:
                data.settings = recorder_config.validate_settings(
                    settings, set(self.locked_settings)
                )
            except ValueError as err:
                raise HomeAssistantError(str(err)) from err
        self.store.schedule_save()
        written = await self._async_sync_package()
        self.store.log("recorder_changes", 0, {"settings": True})
        await self.async_refresh()
        status = self.recorder_status()
        return {
            "packages_missing": not written,
            "restart_required": status["restart_required"],
            "status": status,
        }

    def exclusion_orphans(self) -> dict[str, list[str]]:
        """Our exclusions that match nothing that exists any more."""
        known = self._known_entities()
        data = self.store.data
        domains = {e.split(".", 1)[0] for e in known}
        globs = [
            g for g in data.filters.get("entity_globs", []) if not any(fnmatch(e, g) for e in known)
        ]
        return {
            "entities": sorted(e for e in data.excluded if e not in known),
            "domains": sorted(d for d in data.filters.get("domains", []) if d not in domains),
            "entity_globs": sorted(globs),
        }

    async def async_remove_exclusion_orphans(self) -> dict[str, Any]:
        """Drop exclusions that match nothing."""
        orphans = self.exclusion_orphans()
        data = self.store.data
        data.excluded = [e for e in data.excluded if e not in orphans["entities"]]
        for key in ("domains", "entity_globs"):
            data.filters[key] = [v for v in data.filters.get(key, []) if v not in orphans[key]]
        self.store.schedule_save()
        written = await self._async_sync_package()
        await self.async_refresh()
        return {"removed": sum(map(len, orphans.values())), "packages_missing": not written}

    async def async_apply_recorder_changes(
        self,
        *,
        retention: dict[str, str] | None = None,
        excluded: dict[str, bool] | None = None,
        purge_now: bool = True,
        skip_backup: bool = False,
        log_action: str = "recorder_changes",
        log_details: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Apply a draft from the panel or an action call.

        Settings are always saved. The immediate purge runs only after the
        safety chain; if that stops it, the nightly retention applies the
        new tiers later.
        """
        data = self.store.data
        retention = retention or {}
        excluded = excluded or {}
        for entity_id, tier in retention.items():
            if tier not in ALL_TIERS:
                raise HomeAssistantError(f"Unknown tier {tier}")
            if tier == TIER_DEFAULT:
                data.retention.pop(entity_id, None)
            else:
                data.retention[entity_id] = tier

        new_excluded = set(data.excluded)
        for entity_id, flag in excluded.items():
            if flag:
                new_excluded.add(entity_id)
            else:
                new_excluded.discard(entity_id)
        data.excluded = sorted(new_excluded)
        self.store.schedule_save()

        result: dict[str, Any] = {
            "restart_required": False,
            "packages_missing": False,
            "blocked": None,
            "backup": None,
            "undo": None,
        }
        if not await self._async_sync_package():
            result["packages_missing"] = True

        by_tier: dict[int, list[str]] = {}
        undo_info: dict[str, Any] | None = None
        if purge_now:
            newly_excluded = [e for e, f in excluded.items() if f]
            for entity_id, tier in retention.items():
                if tier in RETENTION_TIERS:
                    by_tier.setdefault(RETENTION_TIERS[tier], []).append(entity_id)
            by_tier.setdefault(0, []).extend(newly_excluded)
            by_tier = {k: v for k, v in by_tier.items() if v}
            if by_tier:
                try:
                    if self._lock.locked():
                        raise HomeAssistantError("Another cleanup is running")
                    async with self._lock:
                        planned = undo.AVAILABLE and bool(self.options[CONF_TARGETED_BACKUP])
                        estimate = self._estimate_purge(by_tier)
                        chain = await self._async_safety(
                            skip_backup=skip_backup or planned,
                            delete_bytes=estimate,
                        )
                        if planned:
                            spec = undo.Spec()
                            cutoff = time.time() + UNDO_CUTOFF_MARGIN
                            for keep_days, ids in by_tier.items():
                                before = None if keep_days == 0 else cutoff - keep_days * 86400
                                spec.states.update(dict.fromkeys(ids, before))
                            undo_info = await self._async_protect(
                                spec, estimate, skip_backup, chain
                            )
                        self._set_busy(None)
                    result["backup"] = chain.get("backup")
                    result["undo"] = undo_info
                except safety.SafetyError as err:
                    result["blocked"] = {"reason": err.reason, "detail": err.detail}
                    self.store.log(
                        "recorder_changes",
                        0,
                        {"entities": len(retention) + len(excluded), "blocked": err.reason},
                    )
                    by_tier = {}
            estimate = self._estimate_purge(by_tier)
            if by_tier:
                await self.store.async_mark_running(
                    "purge_entities", {"entities": sum(len(v) for v in by_tier.values())}
                )
            try:
                for keep_days, entity_ids in by_tier.items():
                    await database.async_purge_entities(self.hass, entity_ids, keep_days)
            finally:
                if by_tier:
                    await self.store.async_clear_running()
            self._adjust_analysis(by_tier)
            if estimate:
                details: dict[str, Any] = {
                    "entities": sum(map(len, by_tier.values())),
                    "deleted": {str(k): v[:LOG_IDS_MAX] for k, v in sorted(by_tier.items())},
                }
                if result["backup"]:
                    details["backup"] = result["backup"]["name"]
                if result.get("undo"):
                    details["undo"] = result["undo"]
                self.store.log("purge_entities", estimate, details)
            if any(by_tier.values()):
                self._schedule_reanalysis()
        changed = len(retention) + len(excluded)
        if changed and not result["blocked"] and not (purge_now and any(by_tier.values())):
            self.store.log(log_action, 0, {"entities": changed, **(log_details or {})})
        for entity_id in [*retention, *excluded]:
            self.store.data.dismissed.pop(entity_id, None)
        self._usage_at = 0.0

        status = self.recorder_status()
        result["restart_required"] = status["restart_required"]
        result["status"] = status
        self.invalidate("files")
        await self.async_refresh()
        return result

    def _schedule_reanalysis(self) -> None:
        """Measure the effect once the queued purges are done."""

        async def _run() -> None:
            await database.async_wait_idle(self.hass)
            if not self.analysis_running:
                await self._async_analysis_quietly()

        self.config_entry.async_create_background_task(self.hass, _run(), f"{DOMAIN}_reanalysis")

    def _estimate_purge(self, by_tier: dict[int, list[str]]) -> int:
        """Rough bytes freed when purging entities down to keep_days."""
        analysis = self.store.data.analysis or {}
        entities = analysis.get("entities") or {}
        total = 0
        for keep_days, entity_ids in by_tier.items():
            for entity_id in entity_ids:
                info = entities.get(entity_id)
                if not info or not info.get("rows"):
                    continue
                # long-term statistics are not touched by purge_entities
                state_part = info.get("est_state_bytes", info.get("est_bytes", 0))
                if keep_days == 0:
                    share = 1.0
                else:
                    per_day = info.get("rows_24h", 0)
                    kept = min(per_day * keep_days, info["rows"])
                    share = 1 - kept / info["rows"]
                total += int(state_part * max(share, 0))
        return total

    async def async_nightly(self, trigger: str) -> dict[str, Any]:
        """Retention tiers and statistics limits, then the event for own automations."""
        started = time.time()
        errors: list[str] = []
        entities = statistics_rows = 0
        # one failing step must not stop the other or the event
        try:
            entities = await self.async_run_retention(include_drop=False, include_daily=True)
        except Exception as err:  # noqa: BLE001 - reported in the event and the log
            _LOGGER.warning("Nightly retention run failed: %s", err)
            errors.append(f"retention: {err}")
        try:
            statistics_rows = await self.async_run_statistics_age()
        except Exception as err:  # noqa: BLE001 - reported in the event and the log
            _LOGGER.warning("Nightly statistics run failed: %s", err)
            errors.append(f"statistics: {err}")
        summary = {
            "trigger": trigger,
            "entities": entities,
            "statistics_rows": statistics_rows,
            "seconds": round(time.time() - started, 1),
            "errors": errors,
        }
        self.hass.bus.async_fire(EVENT_NIGHTLY_RUN, summary)
        return summary

    async def async_run_retention(self, *, include_drop: bool, include_daily: bool) -> int:
        """Enforce retention tiers (called by the scheduler); returns the entities purged."""
        groups: dict[int, list[str]] = {}
        for entity_id, tier in self.store.data.retention.items():
            keep = RETENTION_TIERS.get(tier)
            if keep is None:
                continue
            if tier == TIER_DROP and not include_drop:
                continue
            if tier != TIER_DROP and not include_daily:
                continue
            groups.setdefault(keep, []).append(entity_id)
        if (self.store.data.integrity or {}).get("result") == safety.RESULT_CORRUPT:
            _LOGGER.warning("Retention skipped: the database failed its integrity check")
            return 0
        for keep_days, entity_ids in groups.items():
            await database.async_purge_entities(self.hass, entity_ids, keep_days)
        return sum(len(ids) for ids in groups.values())


        if db["orphan_statistics"]:
            recs.append(
                {
                    "id": "statistics",
                    "bytes": 0,
                    "count": db["orphan_statistics"],
                    "action": "clean",
                    "targets": ["statistics"],
                }
            )
        if rec["repack"] > 50 * 1024 * 1024:
            recs.append(
                {
                    "id": "repack",
                    "bytes": rec["repack"],
                    "action": "clean",
                    "targets": ["repack"],
                }
            )
        potential = self.data.get("retention_potential")
        top = None if potential and potential["bytes"] else self._top_entities()
        if potential and potential["bytes"] >= 1024 * 1024:
            recs.append(
                {
                    "id": "retention",
                    "bytes": potential["bytes"],
                    "count": potential["count"],
                    "action": "navigate",
                    "view": "database",
                }
            )
        if top:
            recs.append(
                {
                    "id": "top_entities",
                    "bytes": top["bytes"],
                    "count": top["count"],
                    "share": top["share"],
                    "action": "navigate",
                    "view": "database",
                }
            )
        unused = self.data.get("unused_statistics")
        if unused and unused["bytes"] >= 1024 * 1024:
            recs.append(
                {
                    "id": "unused_statistics",
                    "bytes": unused["bytes"],
                    "count": unused["count"],
                    "action": "navigate",
                    "view": "database",
                }
            )

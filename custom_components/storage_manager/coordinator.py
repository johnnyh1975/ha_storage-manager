    def recommendations(self) -> list[dict[str, Any]]:
        """Ranked list of cleanup suggestions with a single action each."""
        if not self.data:
            return []
        recs: list[dict[str, Any]] = []
        rec = self.data["reclaimable"]
        db = self.data["database"]
        bk = self.data["backups"]
        if rec["backups"] > 0:
            recs.append(
                {
                    "id": "backups",
                    "bytes": rec["backups"],
                    "count": bk["deletable_count"],
                    "action": "clean",
                    "targets": ["backups"],
                }
            )
        elif bk["deletable_bytes"] > 0 and not bk["rotation_enabled"]:
            recs.append(
                {
                    "id": "backups_rotation_off",
                    "bytes": bk["deletable_bytes"],
                    "count": bk["deletable_count"],
                    "action": "navigate",
                    "view": "backups",
                }
            )
        elif bk["only_local_count"]:
            recs.append(
                {
                    "id": "backups_offsite",
                    "bytes": 0,
                    "count": bk["only_local_count"],
                    "action": "navigate",
                    "view": "backups",
                }
            )
        if rec["files"] > 0:
            recs.append(
                {
                    "id": "files",
                    "bytes": rec["files"],
                    "action": "clean",
                    "targets": ["files"],
                }
            )
        if db["orphan_entities"]:
            recs.append(
                {
                    "id": "orphans",
                    "bytes": db["orphan_entity_bytes"],
                    "count": db["orphan_entities"],
                    "action": "clean",
                    "targets": ["orphans"],
                }
            )
        if db["orphan_statistics"]:
            recs.append(
                {
                    "id": "statistics",
                    "bytes": 0,
                    "count": db["orphan_statistics"],
                    "action": "clean",
                    "targets": ["statistics"],
                }
            )
        if rec["repack"] > 50 * 1024 * 1024:
            recs.append(
                {
                    "id": "repack",
                    "bytes": rec["repack"],
                    "action": "clean",
                    "targets": ["repack"],
                }
            )
        top = self._top_entities()
        if top:
            recs.append(
                {
                    "id": "top_entities",
                    "bytes": top["bytes"],
                    "count": top["count"],
                    "share": top["share"],
                    "action": "navigate",
                    "view": "database",
                }
            )
        recs.sort(key=lambda r: r["bytes"], reverse=True)
        return recs

    def _top_entities(self) -> dict[str, Any] | None:
        analysis = self.store.data.analysis or {}
        entities = analysis.get("entities") or {}
        if not entities:
            return None
        total = sum(e.get("est_bytes", 0) for e in entities.values()) or 1
        data = self.store.data
        candidates = sorted(
            (
                (eid, info)
                for eid, info in entities.items()
                if eid not in data.excluded and eid not in data.retention
            ),
            key=lambda kv: kv[1].get("est_bytes", 0),
            reverse=True,
        )[:10]
        top_bytes = sum(info.get("est_bytes", 0) for _, info in candidates)
        share = top_bytes / total
        if share < 0.3 or top_bytes < 20 * 1024 * 1024:
            return None
        return {"count": len(candidates), "bytes": top_bytes, "share": round(share, 3)}


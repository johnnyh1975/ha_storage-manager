    def _stale(self, key: str, max_age: float) -> bool:
        return time.time() - self._cache_at.get(key, 0) > max_age

    async def _cached(self, key: str, max_age: float, factory: Callable[[], Awaitable[Any]]) -> Any:
        if key not in self._cache or self._stale(key, max_age):
            try:
                self._cache[key] = await factory()
            except Exception as err:  # noqa: BLE001 - keep other data flowing
                _LOGGER.warning("Collecting %s failed: %s", key, err)
                self._cache.setdefault(key, None)
            self._cache_at[key] = time.time()
        return self._cache[key]

    def invalidate(self, *keys: str) -> None:
        """Force re-collection of cached parts on the next refresh."""
        for key in keys or tuple(self._cache_at):
            self._cache_at.pop(key, None)


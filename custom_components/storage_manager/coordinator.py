    async def async_preview(
        self,
        targets: list[str],
        *,
        statistic_ids: list[str] | None = None,
        event_types: list[str] | None = None,
        entity_ids: list[str] | None = None,
    ) -> dict[str, Any]:
        """What a cleanup would do, without doing it."""
        await self.async_refresh()
        data = self.data
        preview: dict[str, Any] = {}
        if "unused_statistics" in targets:
            items = await self._unused_selection(statistic_ids)
            preview["unused_statistics"] = {
                "bytes": sum(i["bytes"] for i in items),
                "items": items,
                "switch_off": sum(1 for i in items if i["kind"] in ("noise", "time")),
            }
        if "events" in targets:
            items = self._events_selection(event_types)
            preview["events"] = {
                "bytes": sum(int(i.get("est_bytes") or 0) for i in items),
                "rows": sum(int(i["rows"]) for i in items),
                "items": items,
            }
        if "dead" in targets:
            items = await self._dead_selection(entity_ids)
            preview["dead"] = {"bytes": sum(i["bytes"] for i in items), "items": items}
        if "statistics_age" in targets:
            age = await self._statistics_age_current()
            preview["statistics_age"] = {k: v for k, v in age.items() if k != "items"}
        if "backups" in targets:
            plan = [p for p in self.backup_plan() if p["action"] == "delete_local"]
            preview["backups"] = {
                "bytes": sum(p["local_size"] for p in plan),
                "items": [
                    {"name": p["name"], "date": p["date"], "bytes": p["local_size"]} for p in plan
                ],
            }
        if "files" in targets:
            hogs = [h for h in (data["files"] or {}).get("hogs", []) if h["safety"] == "safe"]
            preview["files"] = {
                "bytes": sum(h["size_bytes"] for h in hogs),
                "items": [
                    {"name": h["key"], "bytes": h["size_bytes"], "paths": h["paths"]} for h in hogs
                ],
            }
        if "orphans" in targets:
            orphans = self.orphans()
            preview["orphans"] = {
                "bytes": orphans["entity_bytes"],
                "items": orphans["entities"],
            }
        if "statistics" in targets:
            preview["statistics"] = {"bytes": 0, "items": self.orphans()["statistics"]}
        if "purge" in targets:
            obsolete = (self.store.data.analysis or {}).get("obsolete") or {}
            preview["purge"] = {
                "bytes": int(obsolete.get("bytes") or 0),
                "rows": int(obsolete.get("states") or 0) + int(obsolete.get("events") or 0),
            }
        if "repack" in targets:
            preview["repack"] = {
                "bytes": data["reclaimable"]["repack"],
                "possible": self.repack_possible(),
                "plan": data["database"].get("repack"),
            }
        if "docker" in targets:
            preview["docker"] = {"bytes": None, "possible": bool(data["is_hassio"])}
        preview["total"] = sum(int(p.get("bytes") or 0) for p in preview.values())
        db_targets = [t for t in DB_DELETE_TARGETS if t in targets]
        if db_targets:
            preview["safety"] = await self.async_safety_plan(
                delete_bytes=sum(int((preview.get(t) or {}).get("bytes") or 0) for t in db_targets),
                backup_needed=_needs_backup(db_targets),
                undo=self._undo_planned(db_targets),
            )
        return preview

    async def _unused_selection(self, statistic_ids: list[str] | None) -> list[dict[str, Any]]:
        """Unused statistics, limited to the given ids when there are any."""
        items: list[dict[str, Any]] = (await self.async_unused_statistics())["items"]
        if statistic_ids:
            wanted = set(statistic_ids)
            items = [i for i in items if i["statistic_id"] in wanted]
        if not self.packages.available:
            # without the package file they would just be compiled again
            items = [i for i in items if i["kind"] not in ("noise", "time")]
        return items

    def _events_selection(self, event_types: list[str] | None) -> list[dict[str, Any]]:
        """Event types to delete: the given ones, else every excluded type."""
        events = [e for e in self.events_overview() if e["deletable"]]
        if event_types:
            wanted = set(event_types)
            return [e for e in events if e["event_type"] in wanted]
        return [e for e in events if e["excluded"]]

    def _live_bytes(self) -> int:
        """Data in the database file (without free pages) as far as known."""
        repack_plan = self.data["database"].get("repack")
        if repack_plan is not None:
            return int(repack_plan["live_bytes"])
        return int(self.data["database"]["size"] or 0)

    async def async_safety_plan(
        self, *, delete_bytes: int = 0, backup_needed: bool = True, undo: bool = False
    ) -> dict[str, Any]:
        """Preview of the safety chain for the current state.

        With a targeted backup the full backup is only the fallback: the plan
        shows the targeted one and how much space it needs.
        """
        plan = await self._safety_plan(
            delete_bytes=delete_bytes, backup_needed=backup_needed and not undo
        )
        if undo:
            plan["backup"] = {
                "action": "undo",
                "fallback": bool(self.options[CONF_BACKUP_BEFORE_DELETE]),
            }
            plan["space"]["undo"] = delete_bytes // 2 + UNDO_SPACE_MARGIN
        return plan

    async def _safety_plan(
        self, *, delete_bytes: int = 0, backup_needed: bool = True
    ) -> dict[str, Any]:
        return await safety.async_plan(
            self.hass,
            path=database.sqlite_path(self.hass),
            store=self.store,
            db_size=int(self.data["database"]["size"] or 0),
            live_bytes=self._live_bytes(),
            delete_bytes=delete_bytes,
            disk_free=int(self.data["disk"]["free"]),
            backup_enabled=bool(self.options[CONF_BACKUP_BEFORE_DELETE]),
            backup_needed=backup_needed,
        )

    async def _async_safety(
        self, *, skip_backup: bool, delete_bytes: int = 0, backup_needed: bool = True
    ) -> dict[str, Any]:
        """Run the safety chain on fresh numbers; raises safety.SafetyError."""
        await self.async_refresh()
        try:
            return await safety.async_run(
                self.hass,
                path=database.sqlite_path(self.hass),
                store=self.store,
                db_size=int(self.data["database"]["size"] or 0),
                live_bytes=self._live_bytes(),
                delete_bytes=delete_bytes,
                disk_free=int(self.data["disk"]["free"]),
                backup=bool(self.options[CONF_BACKUP_BEFORE_DELETE])
                and backup_needed
                and not skip_backup,
                on_step=lambda key: self._set_busy(f"safety_{key}"),
            )
        finally:
            self._set_busy(None)

    async def async_check_integrity(self) -> dict[str, Any]:
        """Run the integrity check now (from the panel)."""
        if self._lock.locked():
            raise HomeAssistantError("Another cleanup is running")
        async with self._lock:
            self._set_busy("safety_integrity")
            try:
                result = await safety.async_integrity(
                    self.hass, database.sqlite_path(self.hass), self.store, force=True
                )
            finally:
                self._set_busy(None)
        self.invalidate("health")
        await self.async_refresh()
        return result


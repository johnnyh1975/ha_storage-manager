from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers.storage import Store
from homeassistant.util import dt as dt_util

from .const import (
    ALL_TIERS,
    HISTORY_MAX,
    SAMPLE_MAX_AGE_DAYS,
    STORAGE_KEY,
    STORAGE_VERSION,
    TIER_DEFAULT,
)

SAVE_DELAY = 10


@dataclass
class ManagerData:
    """Everything Storage Manager keeps between restarts."""

    # entity_id -> retention tier (see const.RETENTION_TIERS)
    retention: dict[str, str] = field(default_factory=dict)
    # entities that should not be recorded at all (written to the package file)
    excluded: list[str] = field(default_factory=list)
    # excluded list as it was when the package file was last written
    excluded_written: list[str] = field(default_factory=list)
    # [timestamp, used_bytes, total_bytes]
    samples: list[list[float]] = field(default_factory=list)
    # cleanup log
    history: list[dict[str, Any]] = field(default_factory=list)
    freed_total: int = 0
    # cached database analysis (expensive, refreshed daily / on demand)
    analysis: dict[str, Any] | None = None
    migrated_from: list[str] = field(default_factory=list)

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> ManagerData:
        """Build from stored dict, tolerating missing keys."""
        if not data:
            return cls()
        retention = {
            str(k): str(v)
            for k, v in (data.get("retention") or {}).items()
            if str(v) in ALL_TIERS and str(v) != TIER_DEFAULT
        }
        return cls(
            retention=retention,
            excluded=sorted({str(e) for e in data.get("excluded") or []}),
            excluded_written=sorted(
                {str(e) for e in data.get("excluded_written") or []}
            ),
            samples=[list(s) for s in data.get("samples") or [] if len(s) == 3],
            history=list(data.get("history") or [])[-HISTORY_MAX:],
            freed_total=int(data.get("freed_total") or 0),
            analysis=data.get("analysis"),
            migrated_from=list(data.get("migrated_from") or []),
        )

    def as_dict(self) -> dict[str, Any]:
        """Serialize."""
        return {
            "retention": self.retention,
            "excluded": self.excluded,
            "excluded_written": self.excluded_written,
            "samples": self.samples,
            "history": self.history,
            "freed_total": self.freed_total,
            "analysis": self.analysis,
            "migrated_from": self.migrated_from,
        }


class ManagerStore:
    """Wrapper around HA's Store with delayed saving."""

    def __init__(self, hass: HomeAssistant) -> None:
        """Initialize."""
        self._store: Store[dict[str, Any]] = Store(
            hass, STORAGE_VERSION, STORAGE_KEY, private=True
        )
        self.data = ManagerData()

    async def async_load(self) -> ManagerData:
        """Load from disk."""
        self.data = ManagerData.from_dict(await self._store.async_load())
        return self.data

    def schedule_save(self) -> None:
        """Save soon (coalesces bursts of changes)."""
        self._store.async_delay_save(self.data.as_dict, SAVE_DELAY)

    async def async_save(self) -> None:
        """Save now."""
        await self._store.async_save(self.data.as_dict())

    # ---- helpers -------------------------------------------------------

    def add_sample(self, used: int, total: int) -> None:
        """Append a disk usage sample and drop old ones."""
        now = dt_util.utcnow().timestamp()
        cutoff = now - SAMPLE_MAX_AGE_DAYS * 86400
        self.data.samples = [s for s in self.data.samples if s[0] >= cutoff]
        self.data.samples.append([now, float(used), float(total)])
        self.schedule_save()

    def log(
        self, action: str, freed: int, details: dict[str, Any] | None = None
    ) -> None:
        """Record a cleanup action."""
        self.data.history.append(
            {
                "time": dt_util.utcnow().isoformat(),
                "action": action,
                "freed_bytes": int(max(freed, 0)),
                "details": details or {},
            }
        )
        self.data.history = self.data.history[-HISTORY_MAX:]
        self.data.freed_total += int(max(freed, 0))
        self.schedule_save()

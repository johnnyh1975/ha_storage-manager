ENSURE_LIST = vol.EnsureList() if hasattr(vol, "EnsureList") else cv.ensure_list

SERVICE_CLEANUP = "cleanup"
SERVICE_ANALYZE = "analyze_database"
SERVICE_SET_RETENTION = "set_retention"

CLEANUP_SCHEMA = vol.Schema(
    {
        vol.Optional("targets"): vol.All(ENSURE_LIST, [vol.In(ALL_CLEAN_TARGETS)]),
        vol.Optional("dry_run", default=False): cv.boolean,
    }
)
RETENTION_SCHEMA = vol.Schema(
    {
        vol.Required("entity_id"): cv.entity_ids,
        vol.Required("tier"): vol.In(ALL_TIERS),
        vol.Optional("purge_now", default=True): cv.boolean,
    }
)


def _coordinator(hass: HomeAssistant) -> StorageCoordinator:
    entries = hass.config_entries.async_loaded_entries(DOMAIN)
    if not entries:
        raise ServiceValidationError(
            translation_domain=DOMAIN, translation_key="not_loaded"
        )
    return entries[0].runtime_data


@callback
def async_setup_services(hass: HomeAssistant) -> None:
    """Register actions."""

    async def _cleanup(call: ServiceCall) -> ServiceResponse:
        coordinator = _coordinator(hass)
        targets: list[str] = call.data.get("targets") or coordinator.safe_targets()
        if call.data["dry_run"]:
            return {"dry_run": True, **(await coordinator.async_preview(targets))}
        result: dict[str, Any] = await coordinator.async_clean(targets)
        return {"dry_run": False, **result}

    async def _analyze(call: ServiceCall) -> ServiceResponse:
        coordinator = _coordinator(hass)
        result = await coordinator.async_run_analysis()
        top = sorted(
            result["entities"].items(), key=lambda kv: kv[1]["est_bytes"], reverse=True
        )[:20]
        return {
            "generated_at": result["generated_at"],
            "duration_s": result["duration_s"],
            "totals": result["totals"],
            "top_entities": [
                {
                    "entity_id": eid,
                    "est_bytes": info["est_bytes"],
                    "rows": info["rows"],
                    "rows_24h": info["rows_24h"],
                }
                for eid, info in top
            ],
        }

    async def _set_retention(call: ServiceCall) -> None:
        coordinator = _coordinator(hass)
        await coordinator.async_apply_recorder_changes(
            retention={eid: call.data["tier"] for eid in call.data["entity_id"]},
            purge_now=call.data["purge_now"],
        )

    hass.services.async_register(
        DOMAIN,
        SERVICE_CLEANUP,
        _cleanup,
        schema=CLEANUP_SCHEMA,
        supports_response=SupportsResponse.OPTIONAL,
    )
    hass.services.async_register(
        DOMAIN, SERVICE_ANALYZE, _analyze, supports_response=SupportsResponse.OPTIONAL
    )
    hass.services.async_register(
        DOMAIN, SERVICE_SET_RETENTION, _set_retention, schema=RETENTION_SCHEMA
    )

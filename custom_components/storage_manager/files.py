"""Scanner for known space hogs inside the configuration directory.

Only paths from a fixed catalogue can ever be deleted, and only after
resolving them and checking that they stay inside the config directory.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import logging
import os
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from homeassistant.core import HomeAssistant

_LOGGER = logging.getLogger(__name__)

LARGE_FILE_MIN = 50 * 1024 * 1024
LARGE_FILE_LIMIT = 10
SKIP_DIRS = {".storage", "custom_components", ".git", "deps", "backups", "tts"}


@dataclass(frozen=True, kw_only=True)
class HogDefinition:
    """A known category of reclaimable files."""

    key: str
    # glob patterns relative to the config dir
    patterns: tuple[str, ...]
    # "safe": regenerated automatically; "review": the user should look first
    safety: str
    # delete the matched directory itself (True) or only its contents (False)
    remove_dir: bool = False
    # use a Home Assistant action instead of deleting files
    via_action: tuple[str, str] | None = None


HOG_DEFINITIONS: tuple[HogDefinition, ...] = (
    HogDefinition(
        key="esphome_build",
        patterns=("esphome/.esphome/build", "esphome/.esphome/platformio"),
        safety="safe",
        remove_dir=True,
    ),
    HogDefinition(
        key="tts_cache",
        patterns=("tts",),
        safety="safe",
        via_action=("tts", "clear_cache"),
    ),
    HogDefinition(
        key="rotated_logs",
        patterns=(
            "home-assistant.log.[0-9]*",
            "home-assistant.log.old",
            "home-assistant.log.fault",
        ),
        # the previous run's log is often needed to debug a crash
        safety="review",
    ),
    HogDefinition(
        key="corrupt_databases",
        patterns=("home-assistant_v2.db.corrupt.*",),
        safety="review",
    ),
    HogDefinition(
        key="zigbee2mqtt_logs",
        patterns=("zigbee2mqtt/log",),
        safety="safe",
    ),
    HogDefinition(
        key="core_dumps",
        patterns=("core", "core.[0-9]*"),
        safety="safe",
    ),
)
HOGS_BY_KEY = {h.key: h for h in HOG_DEFINITIONS}


def _size(path: Path) -> int:
    """Size of a file or directory tree, not following symlinks."""
    try:
        if path.is_symlink():
            return 0
        if path.is_file():
            return path.stat().st_size
        total = 0
        for root, dirs, files in os.walk(path, followlinks=False):
            dirs[:] = [d for d in dirs if not (Path(root) / d).is_symlink()]
            for name in files:
                fp = Path(root) / name
                try:
                    if not fp.is_symlink():
                        total += fp.stat().st_size
                except OSError:
                    continue
        return total
    except OSError:
        return 0


def _inside(base: Path, candidate: Path) -> bool:
    try:
        candidate.resolve().relative_to(base.resolve())
    except (ValueError, OSError):
        return False
    return candidate.resolve() != base.resolve()


def _matches(config_dir: Path, hog: HogDefinition) -> list[Path]:
    found: list[Path] = []
    for pattern in hog.patterns:
        for match in config_dir.glob(pattern):
            if match.exists() and not match.is_symlink() and _inside(config_dir, match):
                if hog.key == "core_dumps" and not match.is_file():
                    continue
                found.append(match)
    return found


def scan(config_dir: str) -> dict[str, Any]:
    """Scan the config dir (blocking)."""
    base = Path(config_dir)
    hogs: list[dict[str, Any]] = []
    for hog in HOG_DEFINITIONS:
        paths = _matches(base, hog)
        size = sum(_size(p) for p in paths)
        if size <= 0:
            continue
        hogs.append(
            {
                "key": hog.key,
                "safety": hog.safety,
                "size_bytes": size,
                "paths": [str(p.relative_to(base)) for p in paths][:20],
            }
        )
    hogs.sort(key=lambda h: h["size_bytes"], reverse=True)

    known = {p.resolve() for h in HOG_DEFINITIONS for p in _matches(base, h)}
    large: list[dict[str, Any]] = []
    for root, dirs, files in os.walk(base, followlinks=False):
        rel_root = Path(root).relative_to(base)
        if rel_root.parts and rel_root.parts[0] in SKIP_DIRS:
            dirs[:] = []
            continue
        dirs[:] = [d for d in dirs if not d.startswith(".") or d == ".esphome"]
        for name in files:
            fp = Path(root) / name
            if name.startswith("home-assistant_v2.db"):
                continue
            try:
                if fp.is_symlink():
                    continue
                size = fp.stat().st_size
            except OSError:
                continue
            if size < LARGE_FILE_MIN:
                continue
            if any(parent in known for parent in (fp.resolve(), *fp.resolve().parents)):
                continue
            large.append({"path": str(fp.relative_to(base)), "size_bytes": size})
    large.sort(key=lambda f: f["size_bytes"], reverse=True)

    return {
        "hogs": hogs,
        "large_files": large[:LARGE_FILE_LIMIT],
        "reclaimable_safe": sum(h["size_bytes"] for h in hogs if h["safety"] == "safe"),
        "config_dir_bytes": _size(base),
    }


def _delete_paths(config_dir: str, hog: HogDefinition) -> int:
    """Delete matched paths of a hog (blocking). Returns freed bytes."""
    base = Path(config_dir)
    freed = 0
    for path in _matches(base, hog):
        size = _size(path)
        try:
            if path.is_dir():
                if hog.remove_dir:
                    shutil.rmtree(path)
                else:
                    for child in path.iterdir():
                        if child.is_symlink() or child.is_file():
                            child.unlink()
                        else:
                            shutil.rmtree(child)
            else:
                path.unlink()
            freed += size
        except OSError as err:
            _LOGGER.warning("Could not delete %s: %s", path, err)
    return freed


async def async_clean_hog(hass: HomeAssistant, key: str) -> int:
    """Clean one hog category. Returns freed bytes (best effort)."""
    hog = HOGS_BY_KEY[key]
    config_dir = hass.config.config_dir
    if hog.via_action and hass.services.has_service(*hog.via_action):
        before = await hass.async_add_executor_job(
            lambda: sum(_size(p) for p in _matches(Path(config_dir), hog))
        )
        await hass.services.async_call(*hog.via_action, {}, blocking=True)
        after = await hass.async_add_executor_job(
            lambda: sum(_size(p) for p in _matches(Path(config_dir), hog))
        )
        return max(before - after, 0)
    return await hass.async_add_executor_job(_delete_paths, config_dir, hog)

"""Turn the database analysis into concrete, explained recommendations.

Pure functions only: inputs are plain dicts so the rules are easy to test.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from dataclasses import dataclass
import re
from typing import Any

from .usage import EntityUsage

EXCLUDED = "excluded"
# strictness: higher keeps less history
STRICTNESS = {"default": 0, "7": 1, "3": 2, "1": 3, "drop": 4, EXCLUDED: 5}
TIER_DAYS = {"7": 7, "3": 3, "1": 1, "drop": 0, EXCLUDED: 0}

# object ids that are almost always technical noise
NOISE_RE = re.compile(
    r"(rssi|linkquality|link_quality|signal_strength|signal_level|wifi_signal|"
    r"uptime|last_seen|last_restart|last_boot|last_update_trigger|ip_address|"
    r"ssid|bssid|firmware|heap|free_memory|connect_count|reconnects)"
)
NOISE_DEVICE_CLASSES = frozenset({"signal_strength", "timestamp"})

FREQUENT_PER_DAY = 288  # more often than every 5 minutes
ATTRIBUTE_SHARE = 0.6  # attributes dominate the entity's size
MIN_BYTES = 1024 * 1024  # never bother with less than 1 MiB
MIN_SHARE = 0.005  # ... or less than 0.5 % of the database
TOP_SHARE = 0.8  # "top causes" = entities that make up 80 % of the size
ATTR_ONLY_SHARE = 0.8  # rows where only attributes changed, the state did not
ATTR_ONLY_PER_DAY = 48  # ... and that at least every 30 minutes

# Rules by kind of sensor (see docs/sensor-rules.md for the reasoning)
POWER_PER_DAY = 96  # power readings more often than every 15 minutes
ENERGY_PER_DAY = 96
GPS_PER_DAY = 48
FAST_PER_DAY = 1440  # more than once a minute: worth throttling at the source
TIME_PLATFORMS = frozenset({"time_date", "worldclock"})
TIME_OBJECT_RE = re.compile(
    r"^(time|date|date_time|time_utc|date_time_utc|date_time_iso|clock|beat)$"
)
PRESENCE_RE = re.compile(
    r"(distance|moving_target|still_target|target_distance|detection_distance)"
)
SOURCE_HINTS = {"esphome": "esphome", "powercalc": "powercalc", "shelly": "shelly"}
THROTTLE_REASONS = frozenset({"power_statistics", "fast_presence", "statistics_kept", "frequent"})


@dataclass(frozen=True, kw_only=True)
class EntityFacts:
    """What the advisor needs to know about one entity."""

    entity_id: str
    rows: int
    rows_24h: int
    attr_len: int
    state_len: int
    est_state_bytes: int
    est_bytes: int
    stat_rows: int
    est_attr_bytes: int
    state_class: str | None
    device_class: str | None
    entity_category: str | None
    current: str  # effective tier incl. "excluded"
    attr_only: int = 0  # rows where only attributes changed
    platform: str | None = None  # integration that provides the entity
    unit: str | None = None
    source_type: str | None = None  # device trackers: gps, router, ...

    @property
    def domain(self) -> str:
        """Entity domain."""
        return self.entity_id.split(".", 1)[0]


def saving(facts: EntityFacts, action: str) -> int:
    """Bytes freed when the entity's history is cut to the action's days."""
    if not facts.rows:
        return 0
    keep = TIER_DAYS.get(action)
    if keep is None:
        return 0
    kept = 0 if keep == 0 else min(facts.rows_24h * keep, facts.rows)
    return int(facts.est_state_bytes * (1 - kept / facts.rows))


def attribute_share(facts: EntityFacts) -> float:
    """Share of the entity's state history that is attribute payload."""
    if not facts.est_state_bytes:
        return 0.0
    return min(facts.est_attr_bytes / facts.est_state_bytes, 1.0)


def _is_noise(facts: EntityFacts) -> bool:
    object_id = facts.entity_id.split(".", 1)[-1]
    return (
        facts.entity_category == "diagnostic"
        or facts.device_class in NOISE_DEVICE_CLASSES
        or bool(NOISE_RE.search(object_id))
    )


def _is_time(facts: EntityFacts) -> bool:
    object_id = facts.entity_id.split(".", 1)[-1]
    return facts.platform in TIME_PLATFORMS or (
        facts.domain == "sensor"
        and facts.platform in (None, "template")
        and bool(TIME_OBJECT_RE.match(object_id))
    )


def _kind_rule(facts: EntityFacts) -> tuple[str, str] | None:
    """Rules by kind of sensor; long-term statistics are always kept."""
    has_statistics = facts.state_class is not None
    if _is_time(facts):
        return ("1", "time_statistics") if has_statistics else (EXCLUDED, "time")
    if (
        facts.device_class == "power"
        and facts.state_class == "measurement"
        and facts.rows_24h >= POWER_PER_DAY
    ):
        return "3", "power_statistics"
    if (
        facts.device_class == "energy"
        and facts.state_class in ("total", "total_increasing")
        and facts.rows_24h >= ENERGY_PER_DAY
    ):
        return "7", "energy_statistics"
    if facts.domain == "device_tracker" and facts.source_type == "gps":
        return ("7", "gps_tracker") if facts.rows_24h >= GPS_PER_DAY else None
    object_id = facts.entity_id.split(".", 1)[-1]
    if (
        facts.rows_24h >= FAST_PER_DAY
        and facts.domain in ("sensor", "binary_sensor")
        and (facts.device_class == "distance" or PRESENCE_RE.search(object_id))
    ):
        return "1", "fast_presence"
    return None


def base_rule(facts: EntityFacts) -> tuple[str, str] | None:
    """(action, reason) before usage constraints are applied."""
    has_statistics = facts.state_class is not None
    if _is_noise(facts):
        # excluding would also drop long-term statistics, so keep 1 day for those
        return ("1", "noise_statistics") if has_statistics else (EXCLUDED, "noise")
    kind = _kind_rule(facts)
    if kind is not None:
        return kind
    if (
        facts.rows
        and facts.rows_24h >= ATTR_ONLY_PER_DAY
        and facts.attr_only / facts.rows >= ATTR_ONLY_SHARE
    ):
        return ("3", "attribute_updates") if has_statistics else ("1", "attribute_updates")
    if facts.est_state_bytes and attribute_share(facts) >= ATTRIBUTE_SHARE:
        return ("3", "attributes") if has_statistics else ("1", "attributes")
    if facts.rows_24h >= FREQUENT_PER_DAY:
        return ("3", "statistics_kept") if has_statistics else ("3", "frequent")
    return None


def _conflict(facts: EntityFacts, usage: EntityUsage | None) -> tuple[str, str] | None:
    """A current setting that breaks something -> the setting to go back to."""
    if usage is None or facts.current == "default":
        return None
    if usage.history_readers:
        return "default", "conflict_history_reader"
    if facts.current == EXCLUDED and usage.energy:
        return "3", "conflict_energy"
    min_days = usage.min_days
    if min_days and TIER_DAYS[facts.current] < min_days:
        fitting = [t for t in ("1", "3", "7") if TIER_DAYS[t] >= min_days]
        return (fitting[0] if fitting else "default"), "conflict_dashboard"
    return None


def recommend(
    facts: EntityFacts,
    usage: EntityUsage | None,
    *,
    keep_days: int,
    total_bytes: int,
    dismissed: str | None = None,
    group_saving: int = 0,
) -> dict[str, Any]:
    """Recommendation for one entity, including why and what it costs.

    ``group_saving`` is what the same rule saves for all entities of the same
    integration: many small sensors of one kind are worth it together even if
    each alone is not.
    """
    result: dict[str, Any] = {
        "action": None,
        "reason": None,
        "saving": 0,
        "protected": None,
        "notes": [],
    }
    conflict = _conflict(facts, usage)
    if conflict is not None:
        action, reason = conflict
        if dismissed == action:
            result["dismissed"] = True
            return result
        result.update(action=action, reason=reason, conflict=True)
        return result
    if usage is not None and usage.history_readers:
        result["protected"] = "history_reader"
        return result

    threshold = max(MIN_BYTES, total_bytes * MIN_SHARE)
    rule = base_rule(facts)
    if rule is None:
        return result
    action, reason = rule
    alone = facts.est_state_bytes >= threshold
    if not alone and group_saving < threshold:
        return result
    result["group"] = group_key(facts, reason)
    result["group_member"] = not alone
    if reason in THROTTLE_REASONS and facts.rows_24h >= FAST_PER_DAY:
        result["hint"] = SOURCE_HINTS.get(facts.platform or "", "generic")

    if usage is not None:
        if action == EXCLUDED and usage.energy:
            action, reason = "3", "energy"
            result["notes"].append("energy")
        min_days = usage.min_days
        if min_days and (action == EXCLUDED or TIER_DAYS[action] < min_days):
            result["notes"].append("dashboard")
            fitting = [t for t in ("1", "3", "7") if TIER_DAYS[t] >= min_days]
            if not fitting:
                result["protected"] = "dashboard"
                return result
            action = fitting[0]
        if usage.automations or usage.scripts:
            result["notes"].append("automation")

    if TIER_DAYS.get(action, 0) >= keep_days and action != EXCLUDED:
        return result  # would not shorten anything
    if STRICTNESS[facts.current] >= STRICTNESS[action]:
        return result  # already at least as strict
    if dismissed == action:
        result["dismissed"] = True
        return result

    result.update(action=action, reason=reason, saving=saving(facts, action))
    return result


def group_key(facts: EntityFacts, reason: str) -> str:
    """Rule and integration: the unit that is judged and shown together."""
    return f"{reason}:{facts.platform or facts.domain}"


def group_savings(all_facts: list[EntityFacts]) -> dict[str, int]:
    """What each rule would save per integration, before usage constraints."""
    totals: dict[str, int] = {}
    for facts in all_facts:
        rule = base_rule(facts)
        if rule is None:
            continue
        action, reason = rule
        key = group_key(facts, reason)
        totals[key] = totals.get(key, 0) + saving(facts, action)
    return totals


def mark_top(sizes: dict[str, int]) -> set[str]:
    """Largest entities that together make up TOP_SHARE of the total."""
    total = sum(sizes.values())
    if total <= 0:
        return set()
    top: set[str] = set()
    running = 0
    for entity_id, size in sorted(sizes.items(), key=lambda kv: kv[1], reverse=True):
        if running >= total * TOP_SHARE or size <= 0:
            break
        top.add(entity_id)
        running += size
    return top

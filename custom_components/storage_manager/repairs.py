def _gb(value: float) -> str:
    return f"{value / 1024**3:.1f}"


def _human(value: float | None) -> str:
    value = float(value or 0)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024 or unit == "GB":
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} TB"


@callback
def async_update_issues(hass: HomeAssistant, coordinator: StorageCoordinator) -> None:
    """Create or delete issues from the latest data."""
    data = coordinator.data
    if not data:
        return
    disk = data["disk"]
    free_pct = 100 - disk["percent_used"]
    reclaim = _gb(data["reclaimable"]["total"])

    if free_pct < float(coordinator.options[CONF_LOW_SPACE_PERCENT]):
        ir.async_create_issue(
            hass,
            DOMAIN,
            ISSUE_LOW_SPACE,
            is_fixable=True,
            severity=ir.IssueSeverity.ERROR
            if free_pct < 5
            else ir.IssueSeverity.WARNING,
            translation_key=ISSUE_LOW_SPACE,
            translation_placeholders={
                "free": _gb(disk["free"]),
                "percent": f"{free_pct:.0f}",
                "reclaimable": reclaim,
            },
        )
    else:
        ir.async_delete_issue(hass, DOMAIN, ISSUE_LOW_SPACE)

    days = data["forecast"]["days_until_full"]
    if days is not None and days < float(coordinator.options[CONF_FORECAST_DAYS]):
        ir.async_create_issue(
            hass,
            DOMAIN,
            ISSUE_FORECAST,
            is_fixable=True,
            severity=ir.IssueSeverity.WARNING,
            translation_key=ISSUE_FORECAST,
            translation_placeholders={
                "days": f"{days:.0f}",
                "growth": f"{(data['forecast']['growth_per_day'] or 0) / 1024**2:.0f}",
                "reclaimable": reclaim,
            },
        )
    else:
        ir.async_delete_issue(hass, DOMAIN, ISSUE_FORECAST)

    recorder = data["recorder"]
    if recorder["restart_required"]:
        ir.async_create_issue(
            hass,
            DOMAIN,
            ISSUE_RESTART,
            is_fixable=True,
            severity=ir.IssueSeverity.WARNING,
            translation_key=ISSUE_RESTART,
            translation_placeholders={"count": str(len(recorder["pending_restart"]))},
        )
    else:
        ir.async_delete_issue(hass, DOMAIN, ISSUE_RESTART)

    if recorder["unwritten"] and not recorder["packages"]["available"]:
        ir.async_create_issue(
            hass,
            DOMAIN,
            ISSUE_PACKAGES,
            is_fixable=True,
            severity=ir.IssueSeverity.WARNING,
            translation_key=ISSUE_PACKAGES,
            translation_placeholders={"snippet": packages_snippet()},
        )
    else:
        ir.async_delete_issue(hass, DOMAIN, ISSUE_PACKAGES)


@callback
def async_clear_issues(hass: HomeAssistant) -> None:
    """Delete all issues of this integration."""
    for issue_id in (ISSUE_LOW_SPACE, ISSUE_FORECAST, ISSUE_RESTART, ISSUE_PACKAGES):
        ir.async_delete_issue(hass, DOMAIN, issue_id)


def _coordinator(hass: HomeAssistant) -> StorageCoordinator | None:
    entries = hass.config_entries.async_loaded_entries(DOMAIN)
    return entries[0].runtime_data if entries else None


class CleanupRepairFlow(RepairsFlow):
    """Offer the safe cleanup with a preview."""

    def __init__(self) -> None:
        """Initialize."""
        self._preview: dict[str, Any] = {}
        self._targets: list[str] = []

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> data_entry_flow.FlowResult:
        """Show preview."""
        coordinator = _coordinator(self.hass)
        if coordinator is None:
            return self.async_abort(reason="not_loaded")
        self._targets = coordinator.safe_targets()
        self._preview = await coordinator.async_preview(self._targets)
        return await self.async_step_confirm()

    async def async_step_confirm(
        self, user_input: dict[str, Any] | None = None
    ) -> data_entry_flow.FlowResult:
        """Run cleanup after confirmation."""
        coordinator = _coordinator(self.hass)
        if coordinator is None:
            return self.async_abort(reason="not_loaded")
        if not self._preview.get("total"):
            return self.async_abort(
                reason="nothing_to_clean",
                description_placeholders={"panel": f"/{PANEL_URL_PATH}"},
            )
        if user_input is not None:
            await coordinator.async_clean(self._targets)
            return self.async_create_entry(data={})
        return self.async_show_form(
            step_id="confirm",
            description_placeholders={
                "backups": _human(self._preview.get("backups", {}).get("bytes", 0)),
                "files": _human(self._preview.get("files", {}).get("bytes", 0)),
                "panel": f"/{PANEL_URL_PATH}",
            },
        )


class RestartRepairFlow(RepairsFlow):
    """Restart Home Assistant to apply recorder exclusions."""

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> data_entry_flow.FlowResult:
        """Confirm restart."""
        if user_input is not None:
            await self.hass.services.async_call(
                "homeassistant", "restart", {}, blocking=False
            )
            return self.async_create_entry(data={})
        return self.async_show_form(step_id="init")


def setup_packages(config_dir: str) -> str:
    """Add a packages include to configuration.yaml if that is safe (blocking).

    Returns "added", "exists" or "manual" (homeassistant: block present,
    the user has to add the line themselves).
    """
    config_file = Path(config_dir) / "configuration.yaml"
    content = config_file.read_text(encoding="utf-8")
    if PACKAGES_RE.search(content):
        return "exists"
    if "packages:" in content or HOMEASSISTANT_RE.search(content):
        return "manual"
    shutil.copy2(
        config_file, config_file.with_name("configuration.yaml.storage_manager.bak")
    )
    separator = "" if content.endswith("\n") else "\n"
    config_file.write_text(
        content + separator + "\n# Added by Storage Manager\n" + packages_snippet(),
        encoding="utf-8",
    )
    (Path(config_dir) / "packages").mkdir(exist_ok=True)
    return "added"


class PackagesRepairFlow(RepairsFlow):
    """Set up packages so recorder exclusions can be written."""

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> data_entry_flow.FlowResult:
        """Confirm adding the packages include."""
        if user_input is not None:
            result = await self.hass.async_add_executor_job(
                setup_packages, self.hass.config.config_dir
            )
            if result == "manual":
                return self.async_abort(
                    reason="manual",
                    description_placeholders={"snippet": packages_snippet()},
                )
            coordinator = _coordinator(self.hass)
            if coordinator is not None:
                await coordinator.async_detect_packages()
                await coordinator.async_apply_recorder_changes(purge_now=False)
            return self.async_create_entry(data={})
        return self.async_show_form(
            step_id="init", description_placeholders={"snippet": packages_snippet()}
        )


async def async_create_fix_flow(
    hass: HomeAssistant, issue_id: str, data: dict[str, Any] | None
) -> RepairsFlow:
    """Create a fix flow for an issue."""
    if issue_id == ISSUE_RESTART:
        return RestartRepairFlow()
    if issue_id == ISSUE_PACKAGES:
        return PackagesRepairFlow()
    return CleanupRepairFlow()

def undo_dir(config_dir: str) -> Path:
    return Path(config_dir) / UNDO_DIR


def path_for(config_dir: str, undo_id: str) -> Path:
    """The file of an undo id; refuses ids that would leave the folder."""
    if not undo_id or any(c not in "0123456789abcdef-" for c in undo_id):
        raise UndoError("unknown")
    return undo_dir(config_dir) / f"{undo_id}{SUFFIX}"


def new_id() -> str:
    return f"{int(time.time())}-{secrets.token_hex(4)}"


def prune(
    config_dir: str, *, keep_days: int = KEEP_DAYS, max_bytes: int = MAX_TOTAL_BYTES
) -> list[str]:
    """Delete files older than ``keep_days`` and the oldest beyond ``max_bytes`` (blocking)."""
    folder = undo_dir(config_dir)
    if not folder.is_dir():
        return []
    files = sorted(
        (p for p in folder.glob(f"*{SUFFIX}") if p.is_file() and not p.is_symlink()),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    removed: list[str] = []
    limit = time.time() - keep_days * 86400
    total = 0
    for path in files:
        size = path.stat().st_size
        if path.stat().st_mtime < limit or total + size > max_bytes:
            path.unlink(missing_ok=True)
            removed.append(path.name[: -len(SUFFIX)])
            continue
        total += size
    for tmp in folder.glob("*.tmp"):
        if tmp.stat().st_mtime < time.time() - 86400:
            tmp.unlink(missing_ok=True)
    return removed


def existing(config_dir: str) -> set[str]:
    """Undo ids that still have a file (blocking)."""
    folder = undo_dir(config_dir)
    if not folder.is_dir():
        return set()
    return {p.name[: -len(SUFFIX)] for p in folder.glob(f"*{SUFFIX}")}



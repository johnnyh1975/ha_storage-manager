def _ids(session: Session, column: Any, key: Any, values: list[str]) -> dict[str, int]:
    found: dict[str, int] = {}
    for i in range(0, len(values), 500):
        for name, ident in session.execute(
            select(column, key).where(column.in_(values[i : i + 500]))
        ):
            found[str(name)] = int(ident)
    return found


# larger than any row id: "no bound" in a comparison
MAX_ID = 2**63 - 1


def _paged(session: Session, table: Any, pk: Any, where: Any) -> Iterator[dict[str, Any]]:
    last = -1
    while True:
        rows = (
            session.execute(select(table).where(where, pk > last).order_by(pk).limit(PAGE))
            .mappings()
            .all()
        )
        if not rows:
            return
        for row in rows:
            yield dict(row)
        last = int(rows[-1][pk.name])


def count(session: Session, spec: Spec) -> int:
    """Rows the export would write (data rows only), for the size limit."""
    total = 0
    st = States.__table__
    meta = _ids(session, StatesMeta.entity_id, StatesMeta.metadata_id, list(spec.states))
    for entity_id, metadata_id in meta.items():
        before = spec.states[entity_id]
        where = st.c.metadata_id == metadata_id
        if before is not None:
            where = where & (st.c.last_updated_ts < before)
        total += int(
            session.execute(select(func.count()).select_from(st).where(where)).scalar() or 0
        )
    smeta = _ids(session, StatisticsMeta.statistic_id, StatisticsMeta.id, spec.statistics)
    if smeta:
        for table in (Statistics, StatisticsShortTerm):
            t = table.__table__
            total += int(
                session.execute(
                    select(func.count())
                    .select_from(t)
                    .where(t.c.metadata_id.in_(list(smeta.values())))
                ).scalar()
                or 0
            )
    old = _ids(session, StatisticsMeta.statistic_id, StatisticsMeta.id, list(spec.old_statistics))
    stt = Statistics.__table__
    for statistic_id, meta_id in old.items():
        total += int(
            session.execute(
                select(func.count())
                .select_from(stt)
                .where(
                    stt.c.metadata_id == meta_id,
                    stt.c.start_ts < spec.old_statistics[statistic_id],
                )
            ).scalar()
            or 0
        )
    types = _ids(session, EventTypes.event_type, EventTypes.event_type_id, spec.event_types)
    if types:
        et = Events.__table__
        total += int(
            session.execute(
                select(func.count())
                .select_from(et)
                .where(
                    et.c.event_type_id.in_(list(types.values())),
                    et.c.event_id
                    <= (spec.events_max_id if spec.events_max_id is not None else MAX_ID),
                )
            ).scalar()
            or 0
        )
    return total


def export(session: Session, path: Path, spec: Spec) -> dict[str, Any]:
    """Write the rows ``spec`` covers to ``path`` and verify the file (blocking)."""
    if not AVAILABLE:  # pragma: no cover - recorder internals changed
        raise UndoError("unavailable")
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    rows: dict[str, int] = {}

    def put(out: Any, line: dict[str, Any]) -> None:
        out.write(json.dumps(line, separators=(",", ":")).encode() + b"\n")
        if "t" in line:
            rows[line["t"]] = rows.get(line["t"], 0) + 1

    with gzip.open(tmp, "wb", compresslevel=6) as out:
        put(
            out,
            {
                "kind": "header",
                "format": FORMAT,
                "schema": SCHEMA_VERSION,
                "created": time.time(),
                "spec": spec.as_dict(),
            },
        )
        # states with their entity ids and attributes
        st = States.__table__
        meta = _ids(session, StatesMeta.entity_id, StatesMeta.metadata_id, list(spec.states))
        attr_ids: set[int] = set()
        for entity_id, metadata_id in sorted(meta.items()):
            put(out, {"t": "meta", "id": metadata_id, "entity_id": entity_id})
            before = spec.states[entity_id]
            where = st.c.metadata_id == metadata_id
            if before is not None:
                where = where & (st.c.last_updated_ts < before)
            for row in _paged(session, st, st.c.state_id, where):
                if row.get("attributes_id") is not None:
                    attr_ids.add(int(row["attributes_id"]))
                put(
                    out,
                    {
                        "t": "state",
                        "m": metadata_id,
                        "a": row.get("attributes_id"),
                        "r": _row(
                            row, ("state_id", "metadata_id", "attributes_id", "old_state_id")
                        ),
                    },
                )
        at = StateAttributes.__table__
        ordered = sorted(attr_ids)
        for i in range(0, len(ordered), 500):
            for attr in session.execute(
                select(at).where(at.c.attributes_id.in_(ordered[i : i + 500]))
            ).mappings():
                put(
                    out,
                    {"t": "attr", "id": attr["attributes_id"], "r": _row(attr, ("attributes_id",))},
                )
        # statistics with their metadata
        sm = StatisticsMeta.__table__
        for i in range(0, len(spec.statistics), 500):
            for smeta in session.execute(
                select(sm).where(sm.c.statistic_id.in_(spec.statistics[i : i + 500]))
            ).mappings():
                meta_id = int(smeta["id"])
                put(out, {"t": "smeta", "id": meta_id, "r": _row(smeta, ("id",))})
                for kind, table in (("stat", Statistics), ("stst", StatisticsShortTerm)):
                    t = table.__table__
                    for stat in _paged(session, t, t.c.id, t.c.metadata_id == meta_id):
                        put(out, {"t": kind, "m": meta_id, "r": _row(stat, ("id", "metadata_id"))})
        # old long-term rows of statistics that stay
        exported = set(spec.statistics)
        old = sorted(set(spec.old_statistics) - exported)
        st_long = Statistics.__table__
        for i in range(0, len(old), 500):
            for smeta in session.execute(
                select(sm).where(sm.c.statistic_id.in_(old[i : i + 500]))
            ).mappings():
                meta_id = int(smeta["id"])
                before = spec.old_statistics[str(smeta["statistic_id"])]
                put(out, {"t": "smeta", "id": meta_id, "r": _row(smeta, ("id",))})
                where = (st_long.c.metadata_id == meta_id) & (st_long.c.start_ts < before)
                for stat in _paged(session, st_long, st_long.c.id, where):
                    put(out, {"t": "stat", "m": meta_id, "r": _row(stat, ("id", "metadata_id"))})
        # events with their types and data
        types = _ids(session, EventTypes.event_type, EventTypes.event_type_id, spec.event_types)
        ev = Events.__table__
        data_ids: set[int] = set()
        for event_type, type_id in sorted(types.items()):
            put(out, {"t": "etype", "id": type_id, "event_type": event_type})
            where = ev.c.event_type_id == type_id
            if spec.events_max_id is not None:
                where = where & (ev.c.event_id <= spec.events_max_id)
            for row in _paged(session, ev, ev.c.event_id, where):
                if row.get("data_id") is not None:
                    data_ids.add(int(row["data_id"]))
                put(
                    out,
                    {
                        "t": "event",
                        "ty": type_id,
                        "d": row.get("data_id"),
                        "r": _row(row, ("event_id", "event_type_id", "data_id")),
                    },
                )
        ed = EventData.__table__
        ordered = sorted(data_ids)
        for i in range(0, len(ordered), 500):
            for data in session.execute(
                select(ed).where(ed.c.data_id.in_(ordered[i : i + 500]))
            ).mappings():
                put(out, {"t": "edata", "id": data["data_id"], "r": _row(data, ("data_id",))})
        out.write(json.dumps({"kind": "end", "rows": rows}).encode() + b"\n")
    header, found, _columns = read_header(tmp)
    if found != rows:  # pragma: no cover - the file system lost data
        tmp.unlink(missing_ok=True)
        raise UndoError("not_verified")
    tmp.replace(path)
    return {"bytes": path.stat().st_size, "rows": _summary(rows), "schema": header["schema"]}


def _summary(rows: dict[str, int]) -> dict[str, int]:
    """Data rows per kind, as the panel shows them."""
    return {
        "states": rows.get("state", 0),
        "statistics": rows.get("stat", 0) + rows.get("stst", 0),
        "events": rows.get("event", 0),
    }



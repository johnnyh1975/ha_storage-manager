"""Targeted undo: the rows a cleanup deletes, saved before it deletes them.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

A cleanup of orphaned history, statistics, dead entities or events can be
undone without restoring a whole Home Assistant backup. Before it deletes,
Storage Manager writes the affected rows to a gzip-compressed NDJSON file:

    {"kind": "header", ...}           format, recorder schema, what was saved
    {"t": "meta", ...}                lookup rows: entity ids, attributes,
    {"t": "attr", ...}                statistic metadata, event types and data,
    {"t": "smeta", ...}               each with its id at export time
    {"t": "state", ...}               data rows pointing to those ids
    {"kind": "end", "rows": {...}}    row counts; a file without it is refused

Restoring runs on the recorder thread. Lookup rows are matched to what the
database holds now (or inserted), data rows that exist already are skipped,
so restoring twice adds nothing.
"""

from __future__ import annotations

import base64
from collections.abc import Iterator
from dataclasses import dataclass, field
from datetime import datetime
import gzip
import json
import logging
from pathlib import Path
import secrets
import time
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

_LOGGER = logging.getLogger(__name__)

FORMAT = 1
UNDO_DIR = ".storage/storage_manager/undo"
SUFFIX = ".ndjson.gz"
PAGE = 5000
CHUNK = 2000
COMMIT_EVERY = 20
MAX_ROWS = 5_000_000  # larger cleanups fall back to the full backup
KEEP_DAYS = 14
MAX_TOTAL_BYTES = 1024 * 1024 * 1024
# cleanup targets whose deletions a targeted undo can take back
UNDO_TARGETS = frozenset(
    {"orphans", "statistics", "unused_statistics", "events", "dead", "statistics_age"}
)

try:
    from homeassistant.components.recorder.db_schema import (
        SCHEMA_VERSION,
        EventData,
        Events,
        EventTypes,
        StateAttributes,
        States,
        StatesMeta,
        Statistics,
        StatisticsMeta,
        StatisticsShortTerm,
    )

    AVAILABLE = True
except ImportError:  # pragma: no cover - recorder internals changed
    AVAILABLE = False
    SCHEMA_VERSION = 0


class UndoError(Exception):
    """The file cannot be restored; ``reason`` is a translation key."""

    def __init__(self, reason: str, detail: str = "") -> None:
        super().__init__(f"{reason}: {detail}" if detail else reason)
        self.reason = reason
        self.detail = detail


@dataclass
class Spec:
    """What a cleanup is about to delete."""

    # entity_id -> delete rows older than this timestamp (None: all rows)
    states: dict[str, float | None] = field(default_factory=dict)
    statistics: list[str] = field(default_factory=list)
    event_types: list[str] = field(default_factory=list)
    # events up to this id (None: all): newer ones are not deleted either
    events_max_id: int | None = None
    # statistic_id -> long-term rows older than this timestamp (metadata stays)
    old_statistics: dict[str, float] = field(default_factory=dict)

    def empty(self) -> bool:
        return not (self.states or self.statistics or self.event_types or self.old_statistics)

    def as_dict(self) -> dict[str, Any]:
        return {
            "entities": sorted(self.states),
            "statistics": sorted(self.statistics),
            "event_types": sorted(self.event_types),
            "old_statistics": sorted(self.old_statistics),
        }



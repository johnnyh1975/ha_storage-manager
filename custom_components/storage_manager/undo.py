def _lookup(session: Session, table: Any, pk: Any, match: dict[str, Any]) -> int | None:
    where = [getattr(table.__table__.c, k) == v for k, v in match.items()]
    found = session.execute(select(pk).where(*where).limit(1)).scalar()
    return int(found) if found is not None else None


def _insert_one(session: Session, table: Any, values: dict[str, Any]) -> int:
    result: Any = session.execute(table.__table__.insert().values(**values))
    return int(result.inserted_primary_key[0])


def _existing(
    session: Session, column_key: Any, column_ts: Any, key: int, stamps: list[float]
) -> set[float]:
    found = session.execute(
        select(column_ts).where(
            column_key == key, column_ts >= min(stamps), column_ts <= max(stamps)
        )
    ).scalars()
    return {float(v) for v in found if v is not None}


class _Batch:
    """Data rows of one table, inserted in chunks, skipping existing ones."""

    def __init__(self, session: Session, table: Any, key: str, ts: str) -> None:
        self.session = session
        self.table = table
        self.key = key
        self.ts = ts
        self.pending: list[dict[str, Any]] = []
        self.added = 0
        self.skipped = 0
        self.chunks = 0

    def add(self, values: dict[str, Any]) -> None:
        self.pending.append(values)
        if len(self.pending) >= CHUNK:
            self.flush()

    def flush(self) -> None:
        if not self.pending:
            return
        cols = self.table.__table__.c
        by_key: dict[int, list[dict[str, Any]]] = {}
        for values in self.pending:
            by_key.setdefault(int(values[self.key]), []).append(values)
        fresh: list[dict[str, Any]] = []
        for key, rows in by_key.items():
            stamps = [float(r[self.ts]) for r in rows if r.get(self.ts) is not None]
            have = (
                _existing(self.session, cols[self.key], cols[self.ts], key, stamps)
                if stamps
                else set()
            )
            for r in rows:
                stamp = r.get(self.ts)
                if stamp is not None and float(stamp) in have:
                    self.skipped += 1
                    continue
                if stamp is not None:
                    have.add(float(stamp))
                fresh.append(r)
        if fresh:
            self.session.execute(self.table.__table__.insert(), fresh)
            self.added += len(fresh)
        self.pending = []
        self.chunks += 1
        if self.chunks % COMMIT_EVERY == 0:
            self.session.commit()


def restore(session: Session, path: Path) -> dict[str, Any]:
    """Bring the rows of ``path`` back (blocking, on the recorder thread)."""
    if not AVAILABLE:  # pragma: no cover - recorder internals changed
        raise UndoError("unavailable")
    _header, _rows, columns = read_header(path)
    missing = missing_columns(columns)
    if missing:
        raise UndoError("schema", ", ".join(missing))

    meta: dict[int, int] = {}
    attrs: dict[int, int] = {}
    smeta: dict[int, int] = {}
    etypes: dict[int, int] = {}
    edata: dict[int, int] = {}
    # pass 1: lookup rows
    for line in _lines(path):
        kind = line.get("t")
        if kind == "meta":
            entity_id = line["entity_id"]
            meta[int(line["id"])] = _lookup(
                session, StatesMeta, StatesMeta.metadata_id, {"entity_id": entity_id}
            ) or _insert_one(session, StatesMeta, {"entity_id": entity_id})
        elif kind == "attr":
            values = _columns(StateAttributes, line["r"])
            attrs[int(line["id"])] = _lookup(
                session,
                StateAttributes,
                StateAttributes.attributes_id,
                {"hash": values.get("hash"), "shared_attrs": values.get("shared_attrs")},
            ) or _insert_one(session, StateAttributes, values)
        elif kind == "smeta":
            values = _columns(StatisticsMeta, line["r"])
            smeta[int(line["id"])] = _lookup(
                session, StatisticsMeta, StatisticsMeta.id, {"statistic_id": values["statistic_id"]}
            ) or _insert_one(session, StatisticsMeta, values)
        elif kind == "etype":
            event_type = line["event_type"]
            etypes[int(line["id"])] = _lookup(
                session, EventTypes, EventTypes.event_type_id, {"event_type": event_type}
            ) or _insert_one(session, EventTypes, {"event_type": event_type})
        elif kind == "edata":
            values = _columns(EventData, line["r"])
            edata[int(line["id"])] = _lookup(
                session,
                EventData,
                EventData.data_id,
                {"hash": values.get("hash"), "shared_data": values.get("shared_data")},
            ) or _insert_one(session, EventData, values)
    session.commit()

    # pass 2: data rows
    states = _Batch(session, States, "metadata_id", "last_updated_ts")
    stats = _Batch(session, Statistics, "metadata_id", "start_ts")
    short = _Batch(session, StatisticsShortTerm, "metadata_id", "start_ts")
    events = _Batch(session, Events, "event_type_id", "time_fired_ts")
    for line in _lines(path):
        kind = line.get("t")
        if kind == "state":
            values = _columns(States, line["r"], ("state_id", "old_state_id"))
            values["metadata_id"] = meta[int(line["m"])]
            values["attributes_id"] = (
                attrs.get(int(line["a"])) if line.get("a") is not None else None
            )
            states.add(values)
        elif kind in ("stat", "stst"):
            table = Statistics if kind == "stat" else StatisticsShortTerm
            values = _columns(table, line["r"], ("id",))
            values["metadata_id"] = smeta[int(line["m"])]
            (stats if kind == "stat" else short).add(values)
        elif kind == "event":
            values = _columns(Events, line["r"], ("event_id",))
            values["event_type_id"] = etypes[int(line["ty"])]
            values["data_id"] = edata.get(int(line["d"])) if line.get("d") is not None else None
            events.add(values)
    for batch in (states, stats, short, events):
        batch.flush()
    session.commit()
    return {
        "added": {
            "states": states.added,
            "statistics": stats.added + short.added,
            "events": events.added,
        },
        "skipped": {
            "states": states.skipped,
            "statistics": stats.skipped + short.skipped,
            "events": events.skipped,
        },
    }


def reset_caches(instance: Any) -> None:
    """Drop the recorder's id caches: rows came back under new ids."""
    for name in (
        "states_meta_manager",
        "state_attributes_manager",
        "statistics_meta_manager",
        "event_type_manager",
        "event_data_manager",
    ):
        manager = getattr(instance, name, None)
        reset = getattr(manager, "reset", None)
        if callable(reset):
            reset()

async def async_database_size(hass: HomeAssistant, analysis: dict[str, Any] | None) -> int | None:
    """Best known size of the recorder database in bytes."""
    path = sqlite_path(hass)
    if path is not None:
        return await hass.async_add_executor_job(sqlite_file_size, path)
    if analysis and analysis.get("table_sizes"):
        return int(sum(analysis["table_sizes"].values()))
    return None



EVENT_DELETE_CHUNK = 20000
# never offered: legacy state rows may still point at these, and HA's own
# purge handles them together with the states
PROTECTED_EVENT_TYPES = frozenset({"state_changed"})


def delete_events_chunk(
    session: Session,
    event_types: list[str],
    limit: int,
    purged_data: set[int] | None = None,
    max_id: int | None = None,
) -> int:
    """Delete up to ``limit`` events of the given types and the event data only they used.

    Only the data rows of the deleted events are checked, so a chunk stays
    small on a large table. Deleted data ids go to ``purged_data``: the
    recorder keeps them in a cache and must forget them, or the next event
    with the same data points at a row that is gone.
    """
    type_ids = [
        int(row[0])
        for row in session.execute(
            text("SELECT event_type_id FROM event_types WHERE event_type IN :types").bindparams(
                bindparam("types", expanding=True)
            ),
            {"types": event_types},
        )
    ]
    if not type_ids:
        return 0
    # events up to max_id only: newer ones are not in the backup for undo
    bound = "" if max_id is None else " AND event_id <= :max"
    params: dict[str, Any] = {"types": type_ids, "n": limit}
    if max_id is not None:
        params["max"] = max_id
    rows = session.execute(
        text(
            f"SELECT event_id, data_id FROM events WHERE event_type_id IN :types{bound} LIMIT :n"  # noqa: S608
        ).bindparams(bindparam("types", expanding=True)),
        params,
    ).all()
    ids = [int(event_id) for event_id, _ in rows]
    data_ids = sorted({int(data_id) for _, data_id in rows if data_id is not None})
    if ids:
        session.execute(
            text("DELETE FROM events WHERE event_id IN :ids").bindparams(
                bindparam("ids", expanding=True)
            ),
            {"ids": ids},
        )
    loose: list[int] = []
    if data_ids:
        used = {
            int(row[0])
            for row in session.execute(
                text("SELECT DISTINCT data_id FROM events WHERE data_id IN :ids").bindparams(
                    bindparam("ids", expanding=True)
                ),
                {"ids": data_ids},
            )
        }
        loose = [d for d in data_ids if d not in used]
    if loose:
        session.execute(
            text("DELETE FROM event_data WHERE data_id IN :ids").bindparams(
                bindparam("ids", expanding=True)
            ),
            {"ids": loose},
        )
        if purged_data is not None:
            purged_data.update(loose)
    return len(ids) + len(loose)


def evict_event_data(instance: Any, data_ids: set[int]) -> None:
    """Make the recorder forget deleted event data (recorder thread)."""
    manager = getattr(instance, "event_data_manager", None)
    if manager is None or not data_ids:
        return
    try:
        manager.evict_purged(data_ids)
    except Exception:  # noqa: BLE001 - an older recorder: drop the whole cache
        _LOGGER.debug("evict_purged failed, resetting the event data cache", exc_info=True)
        manager.reset()


async def async_delete_events(
    hass: HomeAssistant,
    event_types: list[str],
    *,
    chunk: int = EVENT_DELETE_CHUNK,
    max_id: int | None = None,
) -> int:
    """Delete recorded events of these types in chunks on the recorder thread.

    The recorder has no purge by event type: excluding a type only stops new
    rows. Each chunk is its own recorder task, so state writes keep flowing
    between chunks. With ``max_id`` only events up to that id go: a type that
    is still recorded keeps writing while the cleanup runs. Returns the number
    of events deleted.
    """
    types = sorted(set(event_types) - PROTECTED_EVENT_TYPES)
    if not types:
        return 0
    total = 0
    while True:
        counted: list[int] = []

        def job(instance: Any, out: list[int] = counted) -> None:
            purged: set[int] = set()
            with session_scope(session=instance.get_session()) as session:
                out.append(delete_events_chunk(session, types, chunk, purged, max_id))
            evict_event_data(instance, purged)

        if not await async_run_on_recorder(hass, job):  # pragma: no cover
            raise HomeAssistantError("Recorder tasks are not available")
        done = counted[0] if counted else 0
        total += done
        if done == 0:
            return total
        await asyncio.sleep(0)



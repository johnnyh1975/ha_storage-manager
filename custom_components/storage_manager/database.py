async def async_wait_idle(hass: HomeAssistant, timeout: float = 900) -> bool:
    """Wait until queued recorder work (purges re-queue themselves) is done.

    Recorder services only enqueue tasks. We enqueue a synchronize marker
    behind them and repeat until the queue is drained. Returns False on timeout.
    """
    instance = get_instance(hass)
    try:
        from homeassistant.components.recorder.tasks import (  # noqa: PLC0415
            SynchronizeTask,
        )
    except ImportError:  # pragma: no cover - recorder internals changed
        await asyncio.sleep(5)
        return True

    loop = asyncio.get_running_loop()
    deadline = loop.time() + timeout
    idle_rounds = 0
    while loop.time() < deadline:
        future: asyncio.Future[None] = loop.create_future()
        instance.queue_task(SynchronizeTask(future))
        try:
            await asyncio.wait_for(future, max(deadline - loop.time(), 1))
        except TimeoutError:
            return False
        if instance.backlog == 0:
            idle_rounds += 1
            if idle_rounds >= 2:
                return True
        else:
            idle_rounds = 0
        await asyncio.sleep(0.2)
    return False

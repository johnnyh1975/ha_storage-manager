"""Recorder database analysis (bytes, not just rows) and maintenance.

All queries run in the recorder's own database executor through a
read-only session, so they work for SQLite, MariaDB/MySQL and PostgreSQL.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import asyncio
import logging
from pathlib import Path
import time
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers.recorder import get_instance, session_scope
from sqlalchemy import text
from sqlalchemy.orm import Session

_LOGGER = logging.getLogger(__name__)

# Fallback row sizes when the engine cannot report table sizes
DEFAULT_STATE_ROW = 110
DEFAULT_STAT_ROW = 90
DEFAULT_ATTR_FACTOR = 1.25

TOP_EVENTS = 15

Q_STATES = text(
    """
    SELECT sm.entity_id,
           COUNT(*) AS cnt,
           SUM(CASE WHEN s.last_updated_ts >= :since THEN 1 ELSE 0 END) AS cnt24,
           COALESCE(SUM(LENGTH(s.state)), 0) AS state_len,
           MIN(s.last_updated_ts) AS oldest
    FROM states s
    JOIN states_meta sm ON s.metadata_id = sm.metadata_id
    GROUP BY sm.entity_id
    """
)

Q_ATTRS = text(
    """
    SELECT sm.entity_id, COALESCE(SUM(LENGTH(sa.shared_attrs)), 0) AS attr_len
    FROM (SELECT DISTINCT metadata_id, attributes_id
          FROM states WHERE attributes_id IS NOT NULL) d
    JOIN state_attributes sa ON sa.attributes_id = d.attributes_id
    JOIN states_meta sm ON sm.metadata_id = d.metadata_id
    GROUP BY sm.entity_id
    """
)

Q_STATS = text(
    """
    SELECT m.statistic_id, m.source, COUNT(*) AS cnt
    FROM {table} st
    JOIN statistics_meta m ON st.metadata_id = m.id
    GROUP BY m.statistic_id, m.source
    """
)

Q_EVENTS = text(
    """
    SELECT et.event_type, COUNT(*) AS cnt
    FROM events e
    JOIN event_types et ON e.event_type_id = et.event_type_id
    GROUP BY et.event_type
    """
)

Q_TABLE_SIZES = {
    # dbstat reports tables and indexes; sqlite_master maps each to its table
    "sqlite": text(
        "SELECT m.tbl_name, SUM(d.pgsize) FROM dbstat d "
        "JOIN sqlite_master m ON d.name = m.name GROUP BY m.tbl_name"
    ),
    "mysql": text(
        "SELECT table_name, data_length + index_length FROM information_schema.tables "
        "WHERE table_schema = DATABASE()"
    ),
    "postgresql": text(
        "SELECT relname, pg_total_relation_size(relid) FROM pg_catalog.pg_statio_user_tables"
    ),
}


def _dialect(hass: HomeAssistant) -> str:
    instance = get_instance(hass)
    dialect = instance.dialect_name
    if dialect is None:
        return "sqlite"
    return str(getattr(dialect, "value", dialect))


def sqlite_path(hass: HomeAssistant) -> Path | None:
    """Resolve the SQLite file of the recorder, None for other engines."""
    url = str(get_instance(hass).db_url or "")
    if not url.startswith("sqlite"):
        return None
    _, _, raw = url.partition("://")
    raw = raw.split("?", 1)[0]
    if not raw.strip("/"):
        return None
    if raw.startswith("//"):
        return Path(raw[1:])
    return Path(hass.config.path(raw.lstrip("/")))


def sqlite_file_size(path: Path | None) -> int | None:
    """Size of the SQLite file incl. WAL and SHM sidecars (blocking)."""
    if path is None:
        return None
    total = 0
    for suffix in ("", "-wal", "-shm"):
        candidate = path.with_name(path.name + suffix)
        try:
            total += candidate.stat().st_size
        except OSError:
            continue
    return total


def _table_sizes(session: Session, dialect: str) -> dict[str, int]:
    query = Q_TABLE_SIZES.get(dialect)
    if query is None:
        return {}
    sizes: dict[str, int] = {}
    try:
        for name, size in session.execute(query):
            sizes[str(name).lower()] = int(size or 0)
    except Exception as err:  # noqa: BLE001 - dbstat may be compiled out
        _LOGGER.debug("Table sizes not available on %s: %s", dialect, err)
        session.rollback()
        return {}
    return sizes


def _analyze(hass: HomeAssistant, dialect: str) -> dict[str, Any]:
    """Run the analysis (blocking, recorder executor)."""
    started = time.monotonic()
    since = time.time() - 86400
    entities: dict[str, dict[str, Any]] = {}
    with session_scope(hass=hass, read_only=True) as session:
        for entity_id, cnt, cnt24, state_len, oldest in session.execute(Q_STATES, {"since": since}):
            entities[entity_id] = {
                "rows": int(cnt or 0),
                "rows_24h": int(cnt24 or 0),
                "state_len": int(state_len or 0),
                "attr_len": 0,
                "oldest": float(oldest) if oldest else None,
                "stat_rows": 0,
            }
        for entity_id, attr_len in session.execute(Q_ATTRS):
            entities.setdefault(
                entity_id,
                {
                    "rows": 0,
                    "rows_24h": 0,
                    "state_len": 0,
                    "oldest": None,
                    "stat_rows": 0,
                },
            )["attr_len"] = int(attr_len or 0)

        statistics: dict[str, dict[str, Any]] = {}
        for table in ("statistics", "statistics_short_term"):
            for statistic_id, source, cnt in session.execute(
                text(Q_STATS.text.format(table=table))
            ):
                entry = statistics.setdefault(statistic_id, {"source": source, "rows": 0})
                entry["rows"] += int(cnt or 0)

        events = sorted(
            ({"event_type": et, "rows": int(c or 0)} for et, c in session.execute(Q_EVENTS)),
            key=lambda e: e["rows"],
            reverse=True,
        )
        table_sizes = _table_sizes(session, dialect)
        freelist_bytes = None
        if dialect == "sqlite":
            try:
                page_size = int(session.execute(text("PRAGMA page_size")).scalar() or 0)
                free_pages = int(session.execute(text("PRAGMA freelist_count")).scalar() or 0)
                freelist_bytes = page_size * free_pages
            except Exception as err:  # noqa: BLE001
                _LOGGER.debug("PRAGMA freelist_count failed: %s", err)

    total_rows = sum(e["rows"] for e in entities.values())
    total_attr_len = sum(e["attr_len"] for e in entities.values())
    total_stat_rows = sum(s["rows"] for s in statistics.values())

    # Calibrate byte estimates with real table sizes when available
    states_bytes = table_sizes.get("states", 0) + table_sizes.get("states_meta", 0)
    state_row = states_bytes / total_rows if states_bytes and total_rows else DEFAULT_STATE_ROW
    attr_table = table_sizes.get("state_attributes", 0)
    attr_factor = (
        attr_table / total_attr_len if attr_table and total_attr_len else DEFAULT_ATTR_FACTOR
    )
    stat_bytes = table_sizes.get("statistics", 0) + table_sizes.get("statistics_short_term", 0)
    stat_row = stat_bytes / total_stat_rows if stat_bytes and total_stat_rows else DEFAULT_STAT_ROW

    for entity_id, info in entities.items():
        stat = statistics.get(entity_id)
        info["stat_rows"] = stat["rows"] if stat else 0
        info["est_state_bytes"] = int(info["rows"] * state_row + info["attr_len"] * attr_factor)
        info["est_bytes"] = info["est_state_bytes"] + int(info["stat_rows"] * stat_row)

    return {
        "generated_at": time.time(),
        "duration_s": round(time.monotonic() - started, 2),
        "dialect": dialect,
        "entities": entities,
        "statistics": statistics,
        "events": events[:TOP_EVENTS],
        "table_sizes": table_sizes,
        "freelist_bytes": freelist_bytes,
        "totals": {
            "state_rows": total_rows,
            "statistic_rows": total_stat_rows,
            "event_rows": sum(e["rows"] for e in events),
            "calibrated": bool(table_sizes),
        },
    }


async def async_analyze(hass: HomeAssistant) -> dict[str, Any]:
    """Analyze the recorder database."""
    instance = get_instance(hass)
    await instance.async_db_ready
    dialect = _dialect(hass)
    result = await instance.async_add_executor_job(_analyze, hass, dialect)
    _LOGGER.debug(
        "Database analysis finished in %ss (%s entities)",
        result["duration_s"],
        len(result["entities"]),
    )
    return result


async def async_database_size(hass: HomeAssistant, analysis: dict[str, Any] | None) -> int | None:
    """Best known size of the recorder database in bytes."""
    path = sqlite_path(hass)
    if path is not None:
        return await hass.async_add_executor_job(sqlite_file_size, path)
    if analysis and analysis.get("table_sizes"):
        return int(sum(analysis["table_sizes"].values()))
    return None


async def async_purge_entities(hass: HomeAssistant, entity_ids: list[str], keep_days: int) -> None:
    """Purge recorded data of entities older than keep_days (0 = everything)."""
    if not entity_ids:
        return
    await hass.services.async_call(
        "recorder",
        "purge_entities",
        {"entity_id": sorted(entity_ids), "keep_days": keep_days},
        blocking=True,
    )


async def async_repack(hass: HomeAssistant) -> None:
    """Repack (VACUUM / OPTIMIZE) without deleting anything extra."""
    await hass.services.async_call(
        "recorder",
        "purge",
        {"keep_days": get_instance(hass).keep_days, "repack": True},
        blocking=True,
    )


async def async_clear_statistics(hass: HomeAssistant, statistic_ids: list[str]) -> None:
    """Delete long-term statistics of the given ids."""
    if statistic_ids:
        get_instance(hass).async_clear_statistics(statistic_ids)


async def async_wait_idle(hass: HomeAssistant, timeout: float = 900) -> bool:
    """Wait until queued recorder work (purges re-queue themselves) is done.

    Recorder services only enqueue tasks. We enqueue a synchronize marker
    behind them and repeat until the queue is drained. Returns False on timeout.
    """
    instance = get_instance(hass)
    try:
        from homeassistant.components.recorder.tasks import (  # noqa: PLC0415
            SynchronizeTask,
        )
    except ImportError:  # pragma: no cover - recorder internals changed
        await asyncio.sleep(5)
        return True

    loop = asyncio.get_running_loop()
    deadline = loop.time() + timeout
    idle_rounds = 0
    while loop.time() < deadline:
        future: asyncio.Future[None] = loop.create_future()
        instance.queue_task(SynchronizeTask(future))
        try:
            await asyncio.wait_for(future, max(deadline - loop.time(), 1))
        except TimeoutError:
            return False
        if instance.backlog == 0:
            idle_rounds += 1
            if idle_rounds >= 2:
                return True
        else:
            idle_rounds = 0
        await asyncio.sleep(0.2)
    return False

PURGE_WAIT_TIMEOUT = 1800
PURGE_POLL_INTERVAL = 2.0
_IDS_PER_QUERY = 400


def _rows_older(hass: HomeAssistant, entity_ids: list[str], before: float) -> int:
    """State rows of these entities older than ``before`` (blocking)."""
    query = text(
        "SELECT COUNT(*) FROM states s JOIN states_meta m ON m.metadata_id = s.metadata_id "
        "WHERE m.entity_id IN :ids AND s.last_updated_ts < :before"
    ).bindparams(bindparam("ids", expanding=True))
    total = 0
    with session_scope(hass=hass, read_only=True) as session:
        for i in range(0, len(entity_ids), _IDS_PER_QUERY):
            chunk = entity_ids[i : i + _IDS_PER_QUERY]
            total += int(session.execute(query, {"ids": chunk, "before": before}).scalar() or 0)
    return total


def _read(hass: HomeAssistant, job: Callable[[Session], Any]) -> Any:
    with session_scope(hass=hass, read_only=True) as session:
        return job(session)


async def async_read(hass: HomeAssistant, job: Callable[[Session], Any]) -> Any:
    """Run a read-only job with a database session in the recorder's executor."""
    return await get_instance(hass).async_add_executor_job(_read, hass, job)


class _Rows:
    """A query result read to the end, usable after its session closed."""

    def __init__(self, rows: list[Any]) -> None:
        self._rows = rows

    def __iter__(self) -> Any:
        return iter(self._rows)

    def all(self) -> list[Any]:
        return list(self._rows)

    def mappings(self) -> _Rows:
        return _Rows([row._mapping for row in self._rows])


class ShortSessions:
    """Runs every query in a read session of its own.

    A long export then holds no read transaction open, so SQLite's
    write-ahead log can be checkpointed while it runs.
    """

    def __init__(self, hass: HomeAssistant) -> None:
        self._hass = hass

    def execute(self, *args: Any, **kwargs: Any) -> _Rows:
        with session_scope(hass=self._hass, read_only=True) as session:
            return _Rows(list(session.execute(*args, **kwargs)))


async def async_read_short(hass: HomeAssistant, job: Callable[[Any], Any]) -> Any:
    """Like async_read, but every query of the job in a short session of its own."""
    return await get_instance(hass).async_add_executor_job(job, ShortSessions(hass))



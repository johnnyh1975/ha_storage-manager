"""Folder explorer: what takes the space below a folder, read-only.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

Only a fixed list of roots can be scanned (the config folder and the
Supervisor's media, share and backup folders when they exist). The scan never
follows symbolic links, counts a file with several hard links once, and stops
after MAX_ITEMS entries with a partial result. Nothing is changed or deleted.
"""

from __future__ import annotations

import heapq
import os
from pathlib import Path
import time
from typing import Any

ROOT_CANDIDATES = ("/media", "/share", "/backup", "/addon_configs", "/ssl")
MAX_ITEMS = 200_000
TOP_FILES = 2000
CHILDREN_SHOWN = 40
LARGEST_SHOWN = 12


def roots(config_dir: str) -> list[str]:
    """Folders that may be scanned (blocking)."""
    found = [str(Path(config_dir))]
    for candidate in ROOT_CANDIDATES:
        path = Path(candidate)
        if path.is_dir() and not path.is_symlink() and str(path) not in found:
            found.append(str(path))
    return found


def scan(root: str, *, max_items: int = MAX_ITEMS) -> dict[str, Any]:
    """Sizes of every folder below ``root`` and the largest files (blocking)."""
    started = time.time()
    dirs: dict[str, dict[str, Any]] = {}
    largest: list[tuple[int, str]] = []
    seen_links: set[tuple[int, int]] = set()
    warnings = 0
    items = 0
    partial = False
    order: list[str] = []
    stack = [root]
    while stack:
        current = stack.pop()
        node: dict[str, Any] = {"size": 0, "files": 0, "children": []}
        dirs[current] = node
        order.append(current)
        try:
            entries = list(os.scandir(current))
        except OSError:
            warnings += 1
            continue
        for entry in entries:
            items += 1
            if items > max_items:
                partial = True
                break
            try:
                if entry.is_symlink():
                    continue
                if entry.is_dir(follow_symlinks=False):
                    node["children"].append(entry.path)
                    stack.append(entry.path)
                    continue
                if not entry.is_file(follow_symlinks=False):
                    continue
                stat = entry.stat(follow_symlinks=False)
            except OSError:
                warnings += 1
                continue
            if stat.st_nlink > 1:
                key = (stat.st_dev, stat.st_ino)
                if key in seen_links:
                    continue
                seen_links.add(key)
            node["size"] += stat.st_size
            node["files"] += 1
            if len(largest) < TOP_FILES:
                heapq.heappush(largest, (stat.st_size, entry.path))
            elif stat.st_size > largest[0][0]:
                heapq.heapreplace(largest, (stat.st_size, entry.path))
        if partial:
            break
    # folder totals: children were visited after their parents
    for path in reversed(order):
        node = dirs[path]
        node["own"] = node["size"]
        for child in node["children"]:
            if child in dirs:
                node["size"] += dirs[child]["size"]
                node["files"] += dirs[child]["files"]
    return {
        "root": root,
        "dirs": dirs,
        "largest": sorted(largest, reverse=True),
        "items": min(items, max_items),
        "partial": partial,
        "warnings": warnings,
        "scanned_at": started,
        "seconds": round(time.time() - started, 1),
    }


def browse(result: dict[str, Any], path: str) -> dict[str, Any]:
    """One folder of a scan: its subfolders, its own files and the largest files below."""
    dirs: dict[str, dict[str, Any]] = result["dirs"]
    node = dirs.get(path)
    if node is None:
        raise KeyError(path)
    root = result["root"]
    children = sorted(
        (
            {
                "name": os.path.basename(c),
                "path": c,
                "size": dirs[c]["size"],
                "files": dirs[c]["files"],
            }
            for c in node["children"]
            if c in dirs
        ),
        key=lambda c: -c["size"],
    )
    prefix = path.rstrip("/") + "/"
    largest = [
        {"path": os.path.relpath(p, path), "size": size}
        for size, p in result["largest"]
        if p.startswith(prefix)
    ][:LARGEST_SHOWN]
    crumbs = []
    current = path
    while True:
        crumbs.append({"name": os.path.basename(current) or current, "path": current})
        if current == root or len(current) <= len(root):
            break
        current = os.path.dirname(current)
    return {
        "root": root,
        "path": path,
        "size": node["size"],
        "files": node["files"],
        "own": node["own"],
        "children": children[:CHILDREN_SHOWN],
        "rest": {
            "count": max(len(children) - CHILDREN_SHOWN, 0),
            "size": sum(c["size"] for c in children[CHILDREN_SHOWN:]),
        },
        "largest": largest,
        "crumbs": list(reversed(crumbs)),
        "scanned_at": result["scanned_at"],
        "partial": result["partial"],
        "warnings": result["warnings"],
        "items": result["items"],
    }

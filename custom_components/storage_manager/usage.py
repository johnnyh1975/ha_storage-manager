"""Where is an entity used, and does that use need its recorded history?

Sources:
- automations and scripts (live state only, no history needed)
- UI helpers (config entries): statistics, history_stats and filter read the
  recorder history; all others only follow the live state
- the energy dashboard (needs long-term statistics, so never "don't record")
- storage-mode dashboards: history-type cards need N days of history

YAML-configured helpers are not visible from here and are therefore not
detected.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
import logging
import math
import re
from typing import Any

from homeassistant.core import HomeAssistant

_LOGGER = logging.getLogger(__name__)

ENTITY_RE = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+$")

# helper domains whose sensors read the recorder history
HISTORY_READERS = frozenset({"statistics", "history_stats", "filter"})

# card types that draw recorded history, with their time-span option and default hours
HISTORY_CARDS: dict[str, tuple[str, float]] = {
    "history-graph": ("hours_to_show", 24),
    "sensor": ("hours_to_show", 24),
    "logbook": ("hours_to_show", 24),
    "map": ("hours_to_show", 0),
    "custom:mini-graph-card": ("hours_to_show", 24),
    "custom:apexcharts-card": ("graph_span", 24),
    "custom:history-explorer-card": ("defaultTimeRange", 24),
}
SPAN_RE = re.compile(r"^\s*(\d+(?:\.\d+)?)\s*([smhdw]?)\s*$")
SPAN_HOURS = {"s": 1 / 3600, "m": 1 / 60, "h": 1, "d": 24, "w": 168, "": 1}


@dataclass
class EntityUsage:
    """Where one entity is referenced."""

    automations: list[str] = field(default_factory=list)
    scripts: list[str] = field(default_factory=list)
    helpers: list[dict[str, str]] = field(default_factory=list)
    dashboards: list[dict[str, Any]] = field(default_factory=list)
    energy: bool = False

    @property
    def history_readers(self) -> list[dict[str, str]]:
        """Helpers that read this entity's recorded history."""
        return [h for h in self.helpers if h["domain"] in HISTORY_READERS]

    @property
    def min_days(self) -> int:
        """History a dashboard needs (0 = none)."""
        return max((int(d["days"]) for d in self.dashboards), default=0)

    def as_dict(self) -> dict[str, Any]:
        """JSON-serializable form."""
        return {
            "automations": self.automations,
            "scripts": self.scripts,
            "helpers": self.helpers,
            "dashboards": self.dashboards,
            "energy": self.energy,
            "history_readers": self.history_readers,
            "min_days": self.min_days,
        }


def _entity_refs(value: Any) -> Iterable[str]:
    """All entity ids inside nested config values."""
    if isinstance(value, str):
        if ENTITY_RE.match(value):
            yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from _entity_refs(item)
    elif isinstance(value, list | tuple):
        for item in value:
            yield from _entity_refs(item)


def span_hours(value: Any, default: float) -> float:
    """Parse hours_to_show / graph_span style values ("7d", "48h", 24)."""
    if value is None:
        return default
    if isinstance(value, int | float):
        return float(value)
    match = SPAN_RE.match(str(value))
    if not match:
        return default
    return float(match.group(1)) * SPAN_HOURS[match.group(2)]


def _card_entities(card: dict[str, Any]) -> list[str]:
    found: list[str] = []
    entity = card.get("entity")
    if isinstance(entity, str):
        found.append(entity)
    for item in card.get("entities") or []:
        if isinstance(item, str):
            found.append(item)
        elif isinstance(item, dict) and isinstance(item.get("entity"), str):
            found.append(item["entity"])
    return [e for e in found if ENTITY_RE.match(e)]


def walk_cards(config: Any) -> Iterable[dict[str, Any]]:
    """Every card dict in a dashboard config (views, sections, stacks, ...)."""
    if isinstance(config, dict):
        if isinstance(config.get("type"), str):
            yield config
        for value in config.values():
            yield from walk_cards(value)
    elif isinstance(config, list):
        for item in config:
            yield from walk_cards(item)


def dashboard_requirements(config: dict[str, Any], title: str) -> dict[str, dict[str, Any]]:
    """entity_id -> strongest history requirement within one dashboard."""
    result: dict[str, dict[str, Any]] = {}
    for card in walk_cards(config):
        spec = HISTORY_CARDS.get(str(card["type"]))
        if spec is None:
            continue
        option, default = spec
        hours = span_hours(card.get(option), default)
        if hours <= 0:
            continue
        days = max(1, math.ceil(hours / 24))
        for entity_id in _card_entities(card):
            current = result.get(entity_id)
            if current is None or days > current["days"]:
                result[entity_id] = {"dashboard": title, "card": card["type"], "days": days}
    return result


async def _dashboards(hass: HomeAssistant) -> dict[str, list[dict[str, Any]]]:
    try:
        from homeassistant.components.lovelace.const import (  # noqa: PLC0415
            LOVELACE_DATA,
        )
    except ImportError:  # pragma: no cover
        return {}
    data = hass.data.get(LOVELACE_DATA)
    if data is None:
        return {}
    out: dict[str, list[dict[str, Any]]] = {}
    for url_path, dashboard in list(data.dashboards.items()):
        try:
            config = await dashboard.async_load(False)
        except Exception as err:  # noqa: BLE001 - empty/auto-generated/invalid dashboards
            _LOGGER.debug("Skipping dashboard %s: %s", url_path, err)
            continue
        title = str(config.get("title") or url_path or "Overview")
        for entity_id, need in dashboard_requirements(config, title).items():
            out.setdefault(entity_id, []).append(need)
    return out


async def _energy_entities(hass: HomeAssistant) -> set[str]:
    try:
        from homeassistant.components.energy.data import (  # noqa: PLC0415
            async_get_manager,
        )

        manager = await async_get_manager(hass)
    except Exception as err:  # noqa: BLE001 - energy not set up
        _LOGGER.debug("Energy preferences not available: %s", err)
        return set()
    found: set[str] = set()

    def _collect(value: Any) -> None:
        if isinstance(value, dict):
            for key, item in value.items():
                if key.startswith("stat_") and isinstance(item, str):
                    found.add(item)
                else:
                    _collect(item)
        elif isinstance(value, list):
            for item in value:
                _collect(item)

    _collect(manager.data or {})
    return found


def _helpers(hass: HomeAssistant) -> dict[str, list[dict[str, str]]]:
    out: dict[str, list[dict[str, str]]] = {}
    for entry in hass.config_entries.async_entries():
        if entry.domain in ("storage_manager",):
            continue
        refs = set(_entity_refs(dict(entry.options))) | set(_entity_refs(dict(entry.data)))
        for entity_id in refs:
            out.setdefault(entity_id, []).append({"domain": entry.domain, "title": entry.title})
    return out


async def async_collect(hass: HomeAssistant, entity_ids: Iterable[str]) -> dict[str, EntityUsage]:
    """Usage for the given entities (others are skipped for speed)."""
    wanted = set(entity_ids)
    dashboards = await _dashboards(hass)
    energy = await _energy_entities(hass)
    helpers = _helpers(hass)
    automations_fn = scripts_fn = None
    if "automation" in hass.config.components:
        from homeassistant.components.automation import (  # noqa: PLC0415
            automations_with_entity,
        )

        automations_fn = automations_with_entity
    if "script" in hass.config.components:
        from homeassistant.components.script import scripts_with_entity  # noqa: PLC0415

        scripts_fn = scripts_with_entity

    result: dict[str, EntityUsage] = {}
    for entity_id in wanted:
        usage = EntityUsage(
            automations=sorted(automations_fn(hass, entity_id)) if automations_fn else [],
            scripts=sorted(scripts_fn(hass, entity_id)) if scripts_fn else [],
            helpers=helpers.get(entity_id, []),
            dashboards=dashboards.get(entity_id, []),
            energy=entity_id in energy,
        )
        result[entity_id] = usage
    return result

"""Where is an entity used, and does that use need its recorded history?

Sources:
- automations and scripts (live state only, no history needed)
- UI helpers (config entries): statistics, history_stats and filter read the
  recorder history; all others only follow the live state
- the energy dashboard (needs long-term statistics, so never "don't record")
- storage-mode and YAML dashboards: history-type cards need N days of
  history, statistics cards need long-term statistics
- YAML helpers (statistics, history_stats, filter) found through their
  running entities, so packages and !include files are covered too
- a text scan of the YAML files in the config folder (packages, templates,
  scenes, ...) for literal entity ids, and templates that loop over a whole
  domain (states.sensor, expand(), area_entities(), ...), which no scan can
  resolve to single entities

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
import logging
import math
import re
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers import entity_registry as er

_LOGGER = logging.getLogger(__name__)

ENTITY_RE = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+$")

# helper domains whose sensors read the recorder history
HISTORY_READERS = frozenset({"statistics", "history_stats", "filter"})

# card types that draw recorded history, with their time-span option and default hours
HISTORY_CARDS: dict[str, tuple[str, float]] = {
    "history-graph": ("hours_to_show", 24),
    "sensor": ("hours_to_show", 24),
    "logbook": ("hours_to_show", 24),
    "map": ("hours_to_show", 0),
    "custom:mini-graph-card": ("hours_to_show", 24),
    "custom:apexcharts-card": ("graph_span", 24),
    "custom:history-explorer-card": ("defaultTimeRange", 24),
}
# card types that draw long-term statistics
STATISTICS_CARDS = frozenset({"statistics-graph", "statistic"})

# YAML text scan
YAML_SKIP_DIRS = frozenset(
    {
        "custom_components",
        "deps",
        "backups",
        "tts",
        "www",
        "media",
        "share",
        "ssl",
        "node_modules",
        "__pycache__",
        "blueprints",
        "image",
        "venv",
        ".venv",
    }
)
YAML_SKIP_FILES = frozenset({"secrets.yaml", "automations.yaml", "scripts.yaml"})
YAML_MAX_FILES = 600
YAML_MAX_BYTES = 2_000_000
YAML_REFS_MAX = 10
TOKEN_RE = re.compile(r"(?<![\w.])([a-z_]+\.[a-z0-9_]+)(?![\w])")
DOMAIN_WIDE_RE = re.compile(r"\bstates\.([a-z_]+)(?![a-z0-9_.(\[])")
DYNAMIC_RE = re.compile(
    r"\b(?:expand|area_entities|device_entities|integration_entities|label_entities|"
    r"floor_entities)\s*\(|\bstates\s*\|"
)

SPAN_RE = re.compile(r"^\s*(\d+(?:\.\d+)?)\s*([smhdw]?)\s*$")
SPAN_HOURS = {"s": 1 / 3600, "m": 1 / 60, "h": 1, "d": 24, "w": 168, "": 1}


@dataclass
class EntityUsage:
    """Where one entity is referenced."""

    automations: list[str] = field(default_factory=list)
    scripts: list[str] = field(default_factory=list)
    helpers: list[dict[str, str]] = field(default_factory=list)
    dashboards: list[dict[str, Any]] = field(default_factory=list)
    energy: bool = False
    statistics_cards: list[str] = field(default_factory=list)
    yaml: list[dict[str, Any]] = field(default_factory=list)
    dynamic: list[str] = field(default_factory=list)
    # dashboards that show the entity in any card (titles)
    dashboard_cards: list[str] = field(default_factory=list)

    @property
    def history_readers(self) -> list[dict[str, str]]:
        """Helpers that read this entity's recorded history."""
        return [h for h in self.helpers if h["domain"] in HISTORY_READERS]

    @property
    def min_days(self) -> int:
        """History a dashboard needs (0 = none)."""
        return max((int(d["days"]) for d in self.dashboards), default=0)

    def as_dict(self) -> dict[str, Any]:
        """JSON-serializable form."""
        return {
            "automations": self.automations,
            "scripts": self.scripts,
            "helpers": self.helpers,
            "dashboards": self.dashboards,
            "energy": self.energy,
            "history_readers": self.history_readers,
            "min_days": self.min_days,
            "statistics_cards": self.statistics_cards,
            "yaml": self.yaml,
            "dynamic": self.dynamic,
            "dashboard_cards": self.dashboard_cards,
        }

    @property
    def used(self) -> bool:
        """Referenced anywhere at all (domain-wide templates do not count)."""
        return bool(
            self.automations
            or self.scripts
            or self.helpers
            or self.dashboards
            or self.energy
            or self.statistics_cards
            or self.yaml
            or self.dashboard_cards
        )

    @property
    def needs_statistics(self) -> bool:
        """Long-term statistics of this entity are shown or used somewhere."""
        return self.energy or bool(self.statistics_cards)


def _entity_refs(value: Any) -> Iterable[str]:
    """All entity ids inside nested config values."""
    if isinstance(value, str):
        if ENTITY_RE.match(value):
            yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from _entity_refs(item)
    elif isinstance(value, list | tuple):
        for item in value:
            yield from _entity_refs(item)


def span_hours(value: Any, default: float) -> float:
    """Parse hours_to_show / graph_span style values ("7d", "48h", 24)."""
    if value is None:
        return default
    if isinstance(value, int | float):
        return float(value)
    match = SPAN_RE.match(str(value))
    if not match:
        return default
    return float(match.group(1)) * SPAN_HOURS[match.group(2)]


def _card_entities(card: dict[str, Any]) -> list[str]:
    found: list[str] = []
    entity = card.get("entity")
    if isinstance(entity, str):
        found.append(entity)
    for item in card.get("entities") or []:
        if isinstance(item, str):
            found.append(item)
        elif isinstance(item, dict) and isinstance(item.get("entity"), str):
            found.append(item["entity"])
    return [e for e in found if ENTITY_RE.match(e)]


def walk_cards(config: Any) -> Iterable[dict[str, Any]]:
    """Every card dict in a dashboard config (views, sections, stacks, ...)."""
    if isinstance(config, dict):
        if isinstance(config.get("type"), str):
            yield config
        for value in config.values():
            yield from walk_cards(value)
    elif isinstance(config, list):
        for item in config:
            yield from walk_cards(item)


def dashboard_requirements(config: dict[str, Any], title: str) -> dict[str, dict[str, Any]]:
    """entity_id -> strongest history requirement within one dashboard."""
    result: dict[str, dict[str, Any]] = {}
    for card in walk_cards(config):
        spec = HISTORY_CARDS.get(str(card["type"]))
        if spec is None:
            continue
        option, default = spec
        hours = span_hours(card.get(option), default)
        if hours <= 0:
            continue
        days = max(1, math.ceil(hours / 24))
        for entity_id in _card_entities(card):
            current = result.get(entity_id)
            if current is None or days > current["days"]:
                result[entity_id] = {"dashboard": title, "card": card["type"], "days": days}
    return result


def dashboard_mentions(config: dict[str, Any]) -> set[str]:
    """Every entity id a dashboard names, in any card or template text."""
    import json  # noqa: PLC0415

    return set(TOKEN_RE.findall(json.dumps(config)))


def dashboard_statistics(config: dict[str, Any], title: str) -> set[str]:
    """Entities whose long-term statistics a dashboard draws."""
    found: set[str] = set()
    for card in walk_cards(config):
        if str(card["type"]) in STATISTICS_CARDS:
            found.update(_card_entities(card))
    return found


def scan_yaml(
    config_dir: str, wanted: set[str]
) -> tuple[dict[str, list[dict[str, Any]]], dict[str, list[str]]]:
    """Literal references in the YAML files of the config folder (blocking).

    Returns entity -> [{"file", "line"}] and domain -> files with templates
    that read every entity of a domain. Automations and scripts are left to
    Home Assistant's own lookups.
    """
    import os  # noqa: PLC0415

    refs: dict[str, list[dict[str, Any]]] = {}
    dynamic: dict[str, list[str]] = {}
    files = 0
    for root, dirs, names in os.walk(config_dir):
        dirs[:] = sorted(d for d in dirs if d not in YAML_SKIP_DIRS and not d.startswith("."))
        for name in sorted(names):
            if not name.endswith((".yaml", ".yml")) or name in YAML_SKIP_FILES:
                continue
            path = os.path.join(root, name)
            files += 1
            if files > YAML_MAX_FILES:
                return refs, dynamic
            try:
                if os.path.getsize(path) > YAML_MAX_BYTES:
                    continue
                with open(path, encoding="utf-8", errors="replace") as handle:
                    lines = handle.read().splitlines()
            except OSError:
                continue
            rel = os.path.relpath(path, config_dir)
            if rel.startswith("packages") and name.startswith("storage_manager"):
                continue  # our own package names every excluded entity
            for number, line in enumerate(lines, start=1):
                if line.lstrip().startswith("#"):
                    continue
                for token in TOKEN_RE.findall(line):
                    if token in wanted:
                        found = refs.setdefault(token, [])
                        if len(found) < YAML_REFS_MAX:
                            found.append({"file": rel, "line": number})
                for domain in DOMAIN_WIDE_RE.findall(line):
                    if rel not in dynamic.setdefault(domain, []):
                        dynamic[domain].append(rel)
                if DYNAMIC_RE.search(line) and rel not in dynamic.setdefault("*", []):
                    dynamic["*"].append(rel)  # a caveat for the panel, not per entity
    return refs, dynamic


def _platform_entities(hass: HomeAssistant, integration: str) -> list[Any]:
    """Running entities of an integration that were set up from YAML."""
    from homeassistant.helpers.entity_platform import (  # noqa: PLC0415
        async_get_platforms,
    )

    out: list[Any] = []
    for platform in async_get_platforms(hass, integration):
        if platform.config_entry is None:
            out.extend(platform.entities.values())
    return out


def yaml_history_readers(hass: HomeAssistant) -> dict[str, list[dict[str, str]]]:
    """YAML helpers that read the recorded history of another entity.

    UI helpers are found through their config entries; YAML ones only
    through their running entities. The attribute names are internal to the
    helpers, so a missing one simply means the helper is not found.
    """
    found: dict[str, list[dict[str, str]]] = {}

    def add(source: Any, domain: str, entity: Any) -> None:
        if isinstance(source, str) and ENTITY_RE.match(source):
            found.setdefault(source, []).append(
                {"domain": domain, "title": str(getattr(entity, "entity_id", None) or domain)}
            )

    for entity in _platform_entities(hass, "statistics"):
        add(getattr(entity, "_source_entity_id", None), "statistics", entity)
    for entity in _platform_entities(hass, "history_stats"):
        stats = getattr(getattr(entity, "coordinator", None), "_history_stats", None)
        add(getattr(stats, "entity_id", None), "history_stats", entity)
    for entity in _platform_entities(hass, "filter"):
        add(getattr(entity, "_entity", None), "filter", entity)
    return found


async def _dashboards(
    hass: HomeAssistant,
) -> tuple[dict[str, list[dict[str, Any]]], dict[str, set[str]]]:
    """History needs per entity, and the dashboards that name each entity."""
    mentions: dict[str, set[str]] = {}
    try:
        from homeassistant.components.lovelace.const import (  # noqa: PLC0415
            LOVELACE_DATA,
        )
    except ImportError:  # pragma: no cover
        return {}, mentions
    data = hass.data.get(LOVELACE_DATA)
    if data is None:
        return {}, mentions
    out: dict[str, list[dict[str, Any]]] = {}
    for url_path, dashboard in list(data.dashboards.items()):
        try:
            config = await dashboard.async_load(False)
        except Exception as err:  # noqa: BLE001 - empty/auto-generated/invalid dashboards
            _LOGGER.debug("Skipping dashboard %s: %s", url_path, err)
            continue
        title = str(config.get("title") or url_path or "Overview")
        for entity_id in dashboard_mentions(config):
            mentions.setdefault(entity_id, set()).add(title)
        for entity_id, need in dashboard_requirements(config, title).items():
            out.setdefault(entity_id, []).append(need)
        for entity_id in dashboard_statistics(config, title):
            out.setdefault(entity_id, []).append(
                {"dashboard": title, "card": "statistics", "days": 0}
            )
    return out, mentions


async def _energy_entities(hass: HomeAssistant) -> set[str]:
    try:
        from homeassistant.components.energy.data import (  # noqa: PLC0415
            async_get_manager,
        )

        manager = await async_get_manager(hass)
    except Exception as err:  # noqa: BLE001 - energy not set up
        _LOGGER.debug("Energy preferences not available: %s", err)
        return set()
    found: set[str] = set()

    def _collect(value: Any) -> None:
        if isinstance(value, dict):
            for key, item in value.items():
                if key.startswith("stat_") and isinstance(item, str):
                    found.add(item)
                else:
                    _collect(item)
        elif isinstance(value, list):
            for item in value:
                _collect(item)

    _collect(manager.data or {})
    # cost and compensation sensors the energy integration creates itself:
    # the dashboard reads their statistics although no preference names them
    for entry in er.async_get(hass).entities.values():
        if entry.platform == "energy":
            found.add(entry.entity_id)
    return found


async def async_energy_statistics(hass: HomeAssistant) -> set[str]:
    """Statistic ids the energy dashboard reads (configured ones and its cost sensors)."""
    return await _energy_entities(hass)


def _helpers(hass: HomeAssistant) -> dict[str, list[dict[str, str]]]:
    out: dict[str, list[dict[str, str]]] = {}
    for entry in hass.config_entries.async_entries():
        if entry.domain in ("storage_manager",):
            continue
        refs = set(_entity_refs(dict(entry.options))) | set(_entity_refs(dict(entry.data)))
        for entity_id in refs:
            out.setdefault(entity_id, []).append({"domain": entry.domain, "title": entry.title})
    return out


async def async_collect(hass: HomeAssistant, entity_ids: Iterable[str]) -> dict[str, EntityUsage]:
    """Usage for the given entities (others are skipped for speed)."""
    wanted = set(entity_ids)
    dashboards, mentions = await _dashboards(hass)
    energy = await _energy_entities(hass)
    helpers = _helpers(hass)
    for entity_id, readers in yaml_history_readers(hass).items():
        helpers.setdefault(entity_id, []).extend(readers)
    try:
        yaml_refs, dynamic = await hass.async_add_executor_job(
            scan_yaml, hass.config.config_dir, wanted
        )
    except Exception as err:  # noqa: BLE001 - an unreadable config folder is no reason to fail
        _LOGGER.debug("YAML scan failed: %s", err)
        yaml_refs, dynamic = {}, {}
    automations_fn = scripts_fn = None
    if "automation" in hass.config.components:
        from homeassistant.components.automation import (  # noqa: PLC0415
            automations_with_entity,
        )

        automations_fn = automations_with_entity
    if "script" in hass.config.components:
        from homeassistant.components.script import scripts_with_entity  # noqa: PLC0415

        scripts_fn = scripts_with_entity

    result: dict[str, EntityUsage] = {}
    for entity_id in wanted:
        usage = EntityUsage(
            automations=sorted(automations_fn(hass, entity_id)) if automations_fn else [],
            scripts=sorted(scripts_fn(hass, entity_id)) if scripts_fn else [],
            helpers=helpers.get(entity_id, []),
            dashboards=[d for d in dashboards.get(entity_id, []) if d["days"]],
            energy=entity_id in energy,
            statistics_cards=sorted(
                {d["dashboard"] for d in dashboards.get(entity_id, []) if not d["days"]}
            ),
            yaml=yaml_refs.get(entity_id, []),
            # only templates that loop over the entity's own domain; expand()
            # or area_entities() could reach anything and would flag everything
            dynamic=dynamic.get(entity_id.split(".", 1)[0], []),
            dashboard_cards=sorted(mentions.get(entity_id, set())),
        )
        result[entity_id] = usage
    return result

from __future__ import annotations

import logging

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import Platform
from homeassistant.core import HomeAssistant, callback
from homeassistant.helpers import config_validation as cv
from homeassistant.helpers.event import async_track_time_change
from homeassistant.helpers.storage import Store
from homeassistant.helpers.typing import ConfigType

from . import panel, recorder_config, repairs, services, websocket_api
from .const import CONF_ANALYSIS_HOUR, DOMAIN, STORAGE_KEY, STORAGE_VERSION
from .coordinator import StorageCoordinator
from .store import ManagerStore

_LOGGER = logging.getLogger(__name__)

PLATFORMS: list[Platform] = [Platform.SENSOR, Platform.BUTTON]
CONFIG_SCHEMA = cv.config_entry_only_config_schema(DOMAIN)

type StorageConfigEntry = ConfigEntry[StorageCoordinator]


async def async_setup(hass: HomeAssistant, config: ConfigType) -> bool:
    """Set up actions and the websocket API once."""
    services.async_setup_services(hass)
    websocket_api.async_setup(hass)
    return True


async def async_setup_entry(hass: HomeAssistant, entry: StorageConfigEntry) -> bool:
    """Set up Storage Manager from a config entry."""
    store = ManagerStore(hass)
    await store.async_load()

    coordinator = StorageCoordinator(hass, entry, store)
    await coordinator.async_prepare()
    await coordinator.async_config_entry_first_refresh()
    entry.runtime_data = coordinator

    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    await panel.async_register(hass)

    @callback
    def _update_issues() -> None:
        repairs.async_update_issues(hass, coordinator)

    _update_issues()
    entry.async_on_unload(coordinator.async_add_listener(_update_issues))

    async def _hourly(_now) -> None:
        await coordinator.async_run_retention(include_drop=True, include_daily=False)

    async def _daily(_now) -> None:
        await coordinator.async_run_retention(include_drop=False, include_daily=True)

    async def _analysis(_now) -> None:
        coordinator.async_schedule_analysis()

    # Hourly for "keep nothing", daily after HA's own nightly purge (04:12)
    entry.async_on_unload(async_track_time_change(hass, _hourly, minute=17, second=0))
    entry.async_on_unload(
        async_track_time_change(hass, _daily, hour=4, minute=37, second=0)
    )
    entry.async_on_unload(
        async_track_time_change(
            hass,
            _analysis,
            hour=int(coordinator.options[CONF_ANALYSIS_HOUR]),
            minute=5,
            second=0,
        )
    )
    entry.async_on_unload(entry.add_update_listener(_async_reload))
    return True


async def _async_reload(hass: HomeAssistant, entry: StorageConfigEntry) -> None:
    await hass.config_entries.async_reload(entry.entry_id)


async def async_unload_entry(hass: HomeAssistant, entry: StorageConfigEntry) -> bool:
    """Unload a config entry."""
    unloaded = await hass.config_entries.async_unload_platforms(entry, PLATFORMS)
    if unloaded:
        await entry.runtime_data.store.async_save()
        panel.async_unregister(hass)
    return unloaded


async def async_remove_entry(hass: HomeAssistant, entry: StorageConfigEntry) -> None:
    """Remove the managed package file, stored data and repairs."""
    repairs.async_clear_issues(hass)
    info = await hass.async_add_executor_job(
        recorder_config.detect_packages, hass.config.config_dir
    )
    if info.file is not None:
        await hass.async_add_executor_job(recorder_config.write_package, info, [])
    await Store(hass, STORAGE_VERSION, STORAGE_KEY).async_remove()

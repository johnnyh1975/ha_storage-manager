"""Recorder exclusions through a Home Assistant package file.

Home Assistant only reads recorder include/exclude filters from YAML at
startup. Packages are merged into the main configuration and list values
are concatenated, so a package that only contributes ``exclude.entities``
coexists with any recorder block the user already has.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from homeassistant.core import HomeAssistant
from homeassistant.helpers.recorder import get_instance

from .const import PACKAGE_FILE, PACKAGE_NAME

_LOGGER = logging.getLogger(__name__)

PACKAGES_RE = re.compile(
    r"^\s*packages\s*:\s*!(include_dir_named|include_dir_merge_named)\s+['\"]?([^'\"\s#]+)",
    re.MULTILINE,
)
HOMEASSISTANT_RE = re.compile(r"^homeassistant\s*:", re.MULTILINE)
HEADER = (
    "# Managed by Storage Manager - do not edit, changes are overwritten.\n"
    "# Entities listed here are not written to the recorder database.\n"
)


@dataclass(frozen=True, kw_only=True)
class PackagesInfo:
    """Where (and how) the user's packages are included."""

    mode: str | None  # include_dir_named / include_dir_merge_named / None
    directory: Path | None
    file: Path | None

    @property
    def available(self) -> bool:
        return self.directory is not None

    def as_dict(self) -> dict[str, Any]:
        return {
            "available": self.available,
            "mode": self.mode,
            "directory": str(self.directory) if self.directory else None,
            "file": str(self.file) if self.file else None,
        }


def detect_packages(config_dir: str) -> PackagesInfo:
    """Find a directory based packages include in configuration.yaml (blocking)."""
    config_file = Path(config_dir) / "configuration.yaml"
    try:
        content = config_file.read_text(encoding="utf-8")
    except OSError:
        return PackagesInfo(mode=None, directory=None, file=None)
    match = PACKAGES_RE.search(content)
    if not match:
        return PackagesInfo(mode=None, directory=None, file=None)
    mode, rel_dir = match.group(1), match.group(2)
    directory = (Path(config_dir) / rel_dir).resolve()
    try:
        directory.relative_to(Path(config_dir).resolve())
    except ValueError:
        return PackagesInfo(mode=None, directory=None, file=None)
    return PackagesInfo(mode=mode, directory=directory, file=directory / PACKAGE_FILE)


def packages_snippet() -> str:
    """The lines a user needs to add when packages are not set up yet."""
    return "homeassistant:\n  packages: !include_dir_named packages\n"


def render_package(entities: list[str], mode: str | None) -> str:
    """YAML content of the managed package file."""
    recorder: dict[str, Any] = {"recorder": {"exclude": {"entities": sorted(entities)}}}
    if not entities:
        recorder = {}
    body: dict[str, Any] = recorder
    if mode == "include_dir_merge_named":
        body = {PACKAGE_NAME: recorder} if recorder else {}
    text = yaml.safe_dump(body, sort_keys=True, allow_unicode=True) if body else "{}\n"
    return HEADER + text


def write_package(info: PackagesInfo, entities: list[str]) -> None:
    """Write (or remove) the managed package file (blocking)."""
    if info.file is None or info.directory is None:
        raise FileNotFoundError("Packages directory not configured")
    if not entities:
        if info.file.exists():
            info.file.unlink()
        return
    info.directory.mkdir(parents=True, exist_ok=True)
    tmp = info.file.with_suffix(".tmp")
    tmp.write_text(render_package(entities, info.mode), encoding="utf-8")
    tmp.replace(info.file)


def read_package(info: PackagesInfo) -> list[str]:
    """Entities currently in the managed package file (blocking)."""
    if info.file is None or not info.file.exists():
        return []
    try:
        data = yaml.safe_load(info.file.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return []
    if PACKAGE_NAME in data:
        data = data[PACKAGE_NAME] or {}
    entities = ((data.get("recorder") or {}).get("exclude") or {}).get("entities") or []
    return sorted({str(e) for e in entities})


def is_recorded(hass: HomeAssistant, entity_id: str) -> bool:
    """Whether the running recorder writes this entity."""
    entity_filter = get_instance(hass).entity_filter
    return entity_filter is None or bool(entity_filter(entity_id))


async def async_yaml_recorder_config(hass: HomeAssistant) -> dict[str, Any]:
    """The effective recorder YAML (main config + packages), best effort."""
    try:
        from homeassistant.config import async_hass_config_yaml  # noqa: PLC0415

        conf = await async_hass_config_yaml(hass)
    except Exception as err:  # noqa: BLE001 - invalid YAML etc.
        _LOGGER.debug("Could not read configuration: %s", err)
        return {}
    recorder = conf.get("recorder") or {}
    return recorder if isinstance(recorder, dict) else {}


def summarize_filters(recorder_conf: dict[str, Any]) -> dict[str, Any]:
    """Short description of include/exclude filters for the UI."""
    out: dict[str, Any] = {}
    for section in ("include", "exclude"):
        block = recorder_conf.get(section) or {}
        if not isinstance(block, dict):
            continue
        filters = {
            key: sorted(str(v) for v in (block.get(key) or []))
            for key in ("domains", "entity_globs", "entities", "event_types")
            if block.get(key)
        }
        if filters:
            out[section] = filters
    out["purge_keep_days"] = recorder_conf.get("purge_keep_days")
    out["uses_include"] = bool(out.get("include"))
    return out

from __future__ import annotations

from enum import StrEnum


class Target(StrEnum):
    """What a cleanup can do. Values are the names used by actions and the panel."""

    BACKUPS = "backups"
    FILES = "files"
    ORPHANS = "orphans"
    STATISTICS = "statistics"
    PURGE = "purge"
    REPACK = "repack"
    DOCKER = "docker"
    UNUSED_STATISTICS = "unused_statistics"
    EVENTS = "events"
    DEAD = "dead"
    STATISTICS_AGE = "statistics_age"


SAFE_CLEAN_TARGETS = (Target.BACKUPS, Target.FILES)
ALL_CLEAN_TARGETS = tuple(Target)
# targets that delete rows from the database and run the safety chain first
DB_DELETE_TARGETS = (
    Target.ORPHANS,
    Target.STATISTICS,
    Target.UNUSED_STATISTICS,
    Target.EVENTS,
    Target.DEAD,
    Target.STATISTICS_AGE,
    Target.PURGE,
)

LOG_IDS_MAX = 200
UNDO_SPACE_MARGIN = 64 * 1024 * 1024
# purge_entities is queued: keep some rows more in the undo file than it deletes
UNDO_CUTOFF_MARGIN = 3600


def chosen(given: list[str] | None, valid: list[str]) -> list[str]:
    """The given ids that are valid, or all valid ones when none are given."""
    if not given:
        return list(valid)
    allowed = set(valid)
    return [i for i in given if i in allowed]


def needs_backup(db_targets: list[str]) -> bool:
    """Outdated rows go anyway in Home Assistant's nightly purge: no backup for those."""
    return any(t != Target.PURGE for t in db_targets)

def growth(samples: list[list[float]], now: float) -> dict[str, Any] | None:
    """Growth of the stored data in the last 7 days vs the 28 days before.

    ``samples`` are ``[timestamp, file_bytes, data_bytes]`` after each analysis.
    """
    points = sorted((s[0], s[2]) for s in samples if len(s) == 3)
    if len(points) < 2:
        return None
    last_ts, last = points[-1]
    week = [p for p in points if p[0] <= now - 7 * DAY]
    if not week:
        return None
    week_ts, week_value = week[-1]
    recent = last - week_value
    recent_rate = recent / max((last_ts - week_ts) / DAY, 1)
    before = [p for p in points if p[0] <= week_ts - 14 * DAY]
    before_rate: float | None = None
    if before:
        start_ts, start_value = max(
            (p for p in before if p[0] >= week_ts - 28 * DAY), default=before[-1]
        )
        before_rate = (week_value - start_value) / max((week_ts - start_ts) / DAY, 1)
    return {"recent_bytes": int(recent), "recent_rate": recent_rate, "before_rate": before_rate}


def database_checks(
    *,
    dialect: str | None,
    file_bytes: int | None,
    wal_bytes: int | None,
    samples: list[list[float]],
    integrity: dict[str, Any] | None,
    statistics_issues: dict[str, int] | None,
    now: float,
) -> list[dict[str, Any]]:
    """Checks for the recorder database."""
    checks: list[dict[str, Any]] = []
    sqlite = dialect in (None, "sqlite")

    if sqlite and wal_bytes is not None and file_bytes:
        main = max(file_bytes - wal_bytes, 1)
        large = wal_bytes >= WAL_ABSOLUTE or wal_bytes >= main * WAL_SHARE
        checks.append(
            _check(
                "wal", WARNING if large else OK, bytes=wal_bytes, share=round(wal_bytes / main, 3)
            )
        )

    trend = growth(samples, now)
    if trend is None:
        checks.append(_check("growth", UNKNOWN))
    else:
        before = trend["before_rate"]
        fast = trend["recent_bytes"] >= GROWTH_MIN_BYTES and (
            before is None or before <= 0 or trend["recent_rate"] >= before * GROWTH_FACTOR
        )
        checks.append(
            _check(
                "growth",
                WARNING if fast else OK,
                bytes=trend["recent_bytes"],
                per_day=int(trend["recent_rate"]),
                before_per_day=int(before) if before is not None else None,
            )
        )

    if sqlite:
        if not integrity or integrity.get("result") in (None, "timeout", "error"):
            status = UNKNOWN
        elif integrity["result"] == "corrupt":
            status = ERROR
        elif now - float(integrity.get("at") or 0) > INTEGRITY_STALE:
            status = INFO
        else:
            status = OK
        checks.append(
            _check(
                "integrity",
                status,
                result=(integrity or {}).get("result"),
                at=(integrity or {}).get("at"),
                details=list((integrity or {}).get("details") or [])[:3],
            )
        )

    if statistics_issues is None:
        checks.append(_check("statistics", UNKNOWN))
    else:
        count = sum(statistics_issues.values())
        checks.append(
            _check("statistics", WARNING if count else OK, count=count, types=statistics_issues)
        )
    return checks


def _validate(hass: HomeAssistant) -> dict[str, int]:
    from homeassistant.components.recorder.statistics import (  # noqa: PLC0415
        validate_statistics,
    )

    counts: dict[str, int] = {}
    for issues in validate_statistics(hass).values():
        for issue in issues:
            counts[issue.type] = counts.get(issue.type, 0) + 1
    return counts


async def async_statistics_issues(hass: HomeAssistant) -> dict[str, int] | None:
    """What Home Assistant's own statistics check reports, by type."""
    try:
        return await get_instance(hass).async_add_executor_job(_validate, hass)
    except Exception as err:  # noqa: BLE001 - recorder internals may change
        _LOGGER.debug("Statistics validation failed: %s", err)
        return None



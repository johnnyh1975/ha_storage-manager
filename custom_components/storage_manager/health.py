def _iso(value: datetime | None) -> str | None:
    return value.isoformat() if value is not None else None


async def async_backup_info(hass: HomeAssistant) -> dict[str, Any] | None:
    """Plain facts about the backup setup; None without the backup integration."""
    manager = backup_mod.backup_manager(hass)
    if manager is None:
        return None
    try:
        backups, errors = await manager.async_get_backups()
    except Exception as err:  # noqa: BLE001 - an agent may be down
        _LOGGER.debug("Listing backups failed: %s", err)
        return None
    config = manager.config.data
    local_ids = backup_mod.local_agent_ids(manager)
    return {
        "recurrence": str(getattr(config.schedule.recurrence, "value", config.schedule.recurrence)),
        "last_attempted": _iso(config.last_attempted_automatic_backup),
        "last_completed": _iso(config.last_completed_automatic_backup),
        "include_database": bool(config.create_backup.include_database),
        "agent_ids": list(config.create_backup.agent_ids),
        "protected": {k: bool(v.protected) for k, v in (config.agents or {}).items()},
        "local_ids": sorted(local_ids),
        "agent_errors": sorted(errors),
        "backups": [
            {
                "date": b.date,
                "size": max((s.size for s in b.agents.values()), default=0),
                "database_included": bool(b.database_included),
                "agents": {k: bool(v.protected) for k, v in b.agents.items()},
                "failed_agent_ids": list(b.failed_agent_ids or []),
                "automatic": bool(b.with_automatic_settings),
            }
            for b in backups.values()
        ],
    }


def _parse(value: str | None) -> datetime | None:
    return dt_util.parse_datetime(value) if value else None


def backup_checks(
    info: dict[str, Any] | None,
    *,
    disk_free: int,
    attestations: dict[str, str],
    now: datetime,
) -> list[dict[str, Any]]:
    """Checks for the backup setup."""
    if info is None:
        return [_check("backup_integration", UNKNOWN)]
    checks: list[dict[str, Any]] = []
    recurrence = info["recurrence"]
    checks.append(
        _check("schedule", WARNING if recurrence == "never" else OK, recurrence=recurrence)
    )

    items = []
    for backup in info["backups"]:
        when = _parse(backup["date"])
        if when is not None:
            items.append((when, backup))
    items.sort(key=lambda item: item[0], reverse=True)
    with_db = [(w, b) for w, b in items if b["database_included"]]

    limit = BACKUP_MAX_AGE_DAILY if recurrence == "daily" else BACKUP_MAX_AGE_CUSTOM
    if not with_db:
        checks.append(_check("newest", ERROR))
    else:
        age = now - with_db[0][0]
        checks.append(
            _check(
                "newest",
                WARNING if age > limit else OK,
                date=with_db[0][1]["date"],
                hours=int(age.total_seconds() // 3600),
            )
        )

    attempted = _parse(info["last_attempted"])
    completed = _parse(info["last_completed"])
    failed = attempted is not None and (completed is None or attempted - completed > ATTEMPT_GRACE)
    checks.append(
        _check(
            "last_attempt",
            ERROR if failed else (OK if attempted else UNKNOWN),
            attempted=info["last_attempted"],
            completed=info["last_completed"],
        )
    )

    local_ids = set(info["local_ids"])
    offsite = [(w, b) for w, b in items if set(b["agents"]) - local_ids]
    if not offsite:
        checks.append(_check("offsite", WARNING))
    else:
        days = int((now - offsite[0][0]).total_seconds() // DAY)
        checks.append(
            _check(
                "offsite",
                WARNING if timedelta(days=days) > BACKUP_MAX_AGE_CUSTOM else OK,
                date=offsite[0][1]["date"],
                days=days,
            )
        )

    sizes = [b["size"] for _, b in items[1 : SIZE_HISTORY + 1] if b["size"]]
    if items and items[0][1]["size"] and len(sizes) >= 3:
        typical = median(sizes)
        ratio = items[0][1]["size"] / typical
        odd = ratio < SIZE_LOW or ratio > SIZE_HIGH
        checks.append(
            _check(
                "size",
                WARNING if odd else OK,
                bytes=items[0][1]["size"],
                typical=int(typical),
                ratio=round(ratio, 2),
            )
        )
    else:
        checks.append(_check("size", UNKNOWN))

    remote_agents = [a for a in info["agent_ids"] if a not in local_ids]
    unprotected = sorted(a for a in remote_agents if not info["protected"].get(a, True))
    if not remote_agents:
        checks.append(_check("encryption", UNKNOWN, agents=[]))
    else:
        checks.append(_check("encryption", WARNING if unprotected else OK, agents=unprotected))

    checks.append(_check("database_included", OK if info["include_database"] else WARNING))

    last_size = items[0][1]["size"] if items else 0
    need = int(last_size * SPACE_FACTOR)
    checks.append(
        _check(
            "space",
            (WARNING if disk_free < need else OK) if last_size else UNKNOWN,
            need=need,
            free=disk_free,
        )
    )

    failed_agents = sorted(
        set(info["agent_errors"]) | set(items[0][1]["failed_agent_ids"] if items else [])
    )
    checks.append(_check("agents", WARNING if failed_agents else OK, agents=failed_agents))

    kit = attestations.get("emergency_kit")
    checks.append(_check("emergency_kit", OK if kit else INFO, date=kit))
    tested = _parse(attestations.get("restore_test"))
    if tested is None:
        status = INFO
    elif now - tested > RESTORE_TEST_MAX_AGE:
        status = WARNING
    else:
        status = OK
    checks.append(_check("restore_test", status, date=attestations.get("restore_test")))
    return checks


def summary(checks: list[dict[str, Any]]) -> str:
    """Worst status of a list of checks (unknown and info count as ok)."""
    statuses = {c["status"] for c in checks}
    if ERROR in statuses:
        return ERROR
    if WARNING in statuses:
        return WARNING
    return OK

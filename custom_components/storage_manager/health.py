"""Health checks for the database and the backups.

The rules are pure functions over plain dicts so they are easy to test;
the ``async_*`` helpers collect those dicts from Home Assistant.
Several checks follow ideas from HA Housekeeper (MIT licence).

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from datetime import datetime, timedelta
import logging
from statistics import median
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers.recorder import get_instance
from homeassistant.util import dt as dt_util

from . import backups as backup_mod

_LOGGER = logging.getLogger(__name__)

GIB = 1024**3
MIB = 1024**2
DAY = 86400

OK = "ok"
WARNING = "warning"
ERROR = "error"
INFO = "info"
UNKNOWN = "unknown"

WAL_ABSOLUTE = 1 * GIB
WAL_SHARE = 0.25
GROWTH_FACTOR = 2.0
GROWTH_MIN_BYTES = 100 * MIB
INTEGRITY_STALE = 30 * DAY

BACKUP_MAX_AGE_DAILY = timedelta(hours=36)
BACKUP_MAX_AGE_CUSTOM = timedelta(days=8)
ATTEMPT_GRACE = timedelta(hours=1)
SIZE_LOW = 0.5
SIZE_HIGH = 2.0
SIZE_HISTORY = 5
SPACE_FACTOR = 1.5
RESTORE_TEST_MAX_AGE = timedelta(days=180)

ATTESTATIONS = ("emergency_kit", "restore_test")


def _check(key: str, status: str, **values: Any) -> dict[str, Any]:
    return {"key": key, "status": status, "values": values}



"""Targeted backup before a cleanup and Undo afterwards.

The rows a cleanup is about to delete are saved to a file (undo.py writes
and reads the format); Undo brings them back and reverts what the cleanup
switched off. The coordinator owns the state; this service works on it.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import logging
from typing import TYPE_CHECKING, Any

from homeassistant.exceptions import HomeAssistantError
from homeassistant.util import dt as dt_util

from . import database, safety, undo
from .const import CONF_BACKUP_BEFORE_DELETE, CONF_TARGETED_BACKUP, TIER_DEFAULT
from .recorder_tasks import async_run_on_recorder
from .targets import UNDO_SPACE_MARGIN

if TYPE_CHECKING:
    from .cleanup import Selection
    from .coordinator import StorageCoordinator

_LOGGER = logging.getLogger(__name__)


class UndoService:
    """Targeted backup and Undo for the cleanups of one coordinator."""

    def __init__(self, coordinator: StorageCoordinator) -> None:
        """Initialize."""
        self._c = coordinator

    def planned(self, db_targets: list[str]) -> bool:
        """Whether a targeted backup replaces the full one for these targets."""
        return (
            undo.AVAILABLE
            and bool(self._c.options[CONF_TARGETED_BACKUP])
            and bool(db_targets)
            and set(db_targets) <= undo.UNDO_TARGETS
        )

    def spec_for(self, db_targets: list[str], sel: Selection) -> undo.Spec:
        """The rows a cleanup will delete, from the same selection the cleanup uses."""
        spec = undo.Spec()
        statistics: set[str] = set(sel.statistics)
        spec.states.update(dict.fromkeys(sel.orphans))
        statistics.update(i["statistic_id"] for i in sel.unused)
        dead = [i["entity_id"] for i in sel.dead]
        spec.states.update(dict.fromkeys(dead))
        statistics.update(dead)
        spec.event_types = [e["event_type"] for e in sel.events]
        spec.events_max_id = sel.events_max_id
        for item in (sel.age or {}).get("items") or []:
            spec.old_statistics[item["statistic_id"]] = item["cutoff"]
        spec.statistics = sorted(statistics)
        return spec

    async def async_spec(
        self,
        db_targets: list[str],
        entity_ids: list[str] | None = None,
        statistic_ids: list[str] | None = None,
        event_types: list[str] | None = None,
    ) -> undo.Spec:
        """The rows the targets would delete, chosen as a cleanup chooses them."""
        sel = await self._c.cleanup.async_select(
            db_targets, entity_ids=entity_ids, statistic_ids=statistic_ids, event_types=event_types
        )
        return self.spec_for(db_targets, sel)

    async def async_protect(
        self,
        spec: undo.Spec,
        delete_bytes: int,
        skip_backup: bool,
        safety_result: dict[str, Any],
    ) -> dict[str, Any] | None:
        """Write the targeted backup; fall back to the full backup if it fails.

        Raises safety.SafetyError when neither is possible but a backup is
        required, so the deletion does not run.
        """
        if spec.empty():
            return None
        try:
            return await self._async_export(spec, delete_bytes)
        except undo.UndoError as err:
            _LOGGER.warning("Targeted backup not possible (%s), using the full backup", err)
        except Exception:
            _LOGGER.exception("Targeted backup failed, using the full backup")
        if self._c.options[CONF_BACKUP_BEFORE_DELETE] and not skip_backup:
            self._c._set_busy("safety_backup")
            backup = await safety.async_recent_backup(self._c.hass)
            if backup is None:
                # the safety chain checked the space without a backup: check
                # again before the fallback fills the disk
                size, _ = await safety.async_backup_size(
                    self._c.hass, int(self._c.data["database"]["size"] or 0)
                )
                need = safety.space_needed(
                    live_bytes=self._c._live_bytes(), delete_bytes=delete_bytes, backup_bytes=size
                )
                free = int(self._c.data["disk"]["free"])
                if free < need:
                    raise safety.SafetyError("no_space", str(need))
                backup = await safety.async_create_backup(self._c.hass)
            safety_result["backup"] = backup
        return None

    async def _async_export(self, spec: undo.Spec, delete_bytes: int) -> dict[str, Any]:
        hass = self._c.hass
        config_dir = hass.config.config_dir
        # the safety chain has just refreshed the numbers
        free = int(self._c.data["disk"]["free"])
        need = safety.work_space(self._c._live_bytes(), delete_bytes) + (
            delete_bytes // 2 + UNDO_SPACE_MARGIN
        )
        if free < need:
            raise undo.UndoError("no_space", str(need))
        self._c._set_busy("undo_export")
        rows = int(await database.async_read(hass, lambda s: undo.count(s, spec)))
        if rows > undo.MAX_ROWS:
            raise undo.UndoError("too_many", str(rows))
        undo_id = undo.new_id()
        path = undo.path_for(config_dir, undo_id)
        info: dict[str, Any] = await database.async_read_short(
            hass, lambda s: undo.export(s, path, spec)
        )
        await hass.async_add_executor_job(undo.prune, config_dir)
        self._c.invalidate("files")
        return {"id": undo_id, "bytes": info["bytes"], "rows": info["rows"]}

    async def async_prune(self) -> None:
        """Remove undo files past their age or the size limit (daily)."""
        removed = await self._c.hass.async_add_executor_job(
            undo.prune, self._c.hass.config.config_dir
        )
        if removed:
            _LOGGER.debug("Removed undo files %s", removed)
            self._c.invalidate("files")
        # what Undo knows about a file lives as long as the file
        existing = set(await self.async_available())
        meta = self._c.store.data.undo_meta
        for undo_id in [k for k in meta if k not in existing]:
            meta.pop(undo_id)
        self._c.store.schedule_save()

    async def async_available(self) -> list[str]:
        """Undo ids whose file is still there."""
        return sorted(
            await self._c.hass.async_add_executor_job(undo.existing, self._c.hass.config.config_dir)
        )

    def entry(self, undo_id: str) -> dict[str, Any] | None:
        """The cleanup an undo file belongs to: kept with the file, else in the history."""
        meta = self._c.store.data.undo_meta.get(undo_id)
        if meta is not None:
            return meta
        for entry in reversed(self._c.store.data.history):
            info = (entry.get("details") or {}).get("undo")
            if isinstance(info, dict) and info.get("id") == undo_id:
                found: dict[str, Any] = entry
                return found
        return None

    async def async_preview(self, undo_id: str) -> dict[str, Any]:
        """What restoring would bring back and undo."""
        path = undo.path_for(self._c.hass.config.config_dir, undo_id)
        try:
            info: dict[str, Any] = await self._c.hass.async_add_executor_job(undo.describe, path)
        except undo.UndoError as err:
            raise HomeAssistantError(f"undo_{err.reason}") from err
        entry = self.entry(undo_id)
        deleted = ((entry or {}).get("details") or {}).get("deleted") or {}
        info["enable"] = [
            e for e in deleted.get("dead") or [] if e in self._c.store.data.disabled_dead
        ]
        info["statistics_on"] = [
            e for e in deleted.get("statistics_off") or [] if e in self._c.store.data.stats_off
        ]
        info["undone"] = ((entry or {}).get("details") or {}).get("undone")
        revert = ((entry or {}).get("details") or {}).get("revert") or {}
        data = self._c.store.data
        # only settings nobody changed since: a later choice of the user stays
        info["retention"] = {
            e: old
            for e, (old, new) in (revert.get("retention") or {}).items()
            if data.retention.get(e, TIER_DEFAULT) == new
        }
        info["include"] = [
            e
            for e, (old, new) in (revert.get("excluded") or {}).items()
            if (e in data.excluded) == bool(new)
        ]
        info["statistics_limits"] = bool(
            "statistics_age" in deleted and data.stats_limits_applied is not None
        )
        info["need"] = info["bytes"] * 10 + UNDO_SPACE_MARGIN
        info["free"] = int(self._c.data["disk"]["free"])
        return info

    async def async_undo(self, undo_id: str) -> dict[str, Any]:
        """Bring the rows of a cleanup back and revert what it switched off."""
        preview = await self.async_preview(undo_id)
        if not preview["schema_ok"]:
            raise HomeAssistantError("undo_schema")
        if preview["free"] < preview["need"]:
            raise HomeAssistantError("undo_no_space")
        if self._c._lock.locked():
            raise HomeAssistantError("Another cleanup is running")
        path = undo.path_for(self._c.hass.config.config_dir, undo_id)
        result: dict[str, Any] = {}

        def job(instance: Any) -> None:
            result.update(database.run_write(instance, lambda s: undo.restore(s, path)))
            undo.reset_caches(instance)

        async with self._c._lock:
            self._c._set_busy("undo")
            await self._c.store.async_mark_running("undo", {"undo_id": undo_id})
            try:
                if not await async_run_on_recorder(self._c.hass, job):  # pragma: no cover
                    raise HomeAssistantError("undo_unavailable")
            finally:
                self._c._set_busy(None)
                await self._c.store.async_clear_running()
        if preview["enable"]:
            await self._c.async_enable_dead(preview["enable"])
        if preview["statistics_on"]:
            await self._c.async_statistics_on(preview["statistics_on"])
        if preview["retention"] or preview["include"]:
            await self._async_revert_settings(preview["retention"], preview["include"])
        if preview["statistics_limits"]:
            # the limits stay set but wait for the next confirmed run again
            self._c.store.data.stats_limits_applied = None
            self._c.store.schedule_save()
        entry = self.entry(undo_id)
        if entry is not None and not entry["details"].get("undone"):
            entry["details"]["undone"] = dt_util.utcnow().isoformat()
            # after a restart the history holds its own copy of the entry
            for logged in self._c.store.data.history:
                info = (logged.get("details") or {}).get("undo")
                if logged is not entry and isinstance(info, dict) and info.get("id") == undo_id:
                    logged["details"]["undone"] = entry["details"]["undone"]
            # the space is taken again: the running total should say so
            data = self._c.store.data
            data.freed_total = max(data.freed_total - int(entry.get("freed_bytes") or 0), 0)
        self._c.store.log("undo", 0, {"undo_id": undo_id, **result})
        self._c._schedule_reanalysis()
        self._c.invalidate("breakdown")
        await self._c.async_refresh()
        return {
            **result,
            "enabled": preview["enable"],
            "statistics_on": preview["statistics_on"],
            "retention": preview["retention"],
            "include": preview["include"],
            "statistics_limits": preview["statistics_limits"],
        }

    async def _async_revert_settings(self, retention: dict[str, str], include: list[str]) -> None:
        """Put retention tiers and recorder exclusions back as they were."""
        data = self._c.store.data
        for entity_id, tier in retention.items():
            if tier == TIER_DEFAULT:
                data.retention.pop(entity_id, None)
            else:
                data.retention[entity_id] = tier
        data.excluded = sorted(set(data.excluded) - set(include))
        self._c.store.schedule_save()
        await self._c._async_sync_package()
        self._c._usage_at = 0.0

"""Ready-made template entities for entities whose attributes fill the database.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home

An entity with large or fast-changing attributes writes a new attribute row
again and again. The usual fix: record a template entity that carries only
the state (and, if needed, one or two attributes as their own entities), and
stop recording the original. This module builds that YAML.
"""

from __future__ import annotations

from typing import Any

from homeassistant.util import slugify
import yaml

# domains whose state is on/off: a binary sensor fits better than a sensor
BINARY_DOMAINS = frozenset(
    {"binary_sensor", "switch", "light", "fan", "input_boolean", "automation", "siren"}
)
UNIQUE_PREFIX = "storage_manager"
SUFFIX = {"de": "Verlauf", "en": "history"}


class _Dumper(yaml.SafeDumper):
    """Templates in double quotes and on one line, as people write them."""


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = '"' if "{{" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def _slug(text: str) -> str:
    return slugify(text) or "x"


def _quote(value: str) -> str:
    """An entity id or attribute name inside a Jinja string literal."""
    return value.replace("\\", "\\\\").replace("'", "\\'")


def build(
    entity_id: str,
    *,
    name: str,
    attributes: dict[str, Any],
    extra: list[str],
    language: str,
) -> dict[str, Any]:
    """YAML for a lean copy of ``entity_id`` plus one entity per wanted attribute.

    ``attributes`` are the entity's current state attributes, ``extra`` the
    attribute names to keep as entities of their own. Returns the YAML text
    and the entity ids the new entities will most likely get.
    """
    domain, object_id = entity_id.split(".", 1)
    suffix = SUFFIX.get(language.split("-", 1)[0], SUFFIX["en"])
    source = _quote(entity_id)
    binary = domain in BINARY_DOMAINS
    main_name = f"{name} ({suffix})"
    main: dict[str, Any] = {
        "name": main_name,
        "unique_id": f"{UNIQUE_PREFIX}_{object_id}_state",
    }
    if binary:
        if attributes.get("device_class") and domain == "binary_sensor":
            main["device_class"] = attributes["device_class"]
        main["state"] = f"{{{{ is_state('{source}', 'on') }}}}"
    else:
        for key in ("unit_of_measurement", "device_class", "state_class"):
            if attributes.get(key):
                main[key] = attributes[key]
        main["state"] = f"{{{{ states('{source}') }}}}"
    main["availability"] = f"{{{{ has_value('{source}') }}}}"
    sensors: list[dict[str, Any]] = []
    blocks: list[dict[str, Any]] = []
    if binary:
        blocks.append({"binary_sensor": [main]})
    else:
        sensors.append(main)
    new_ids = [f"{'binary_sensor' if binary else 'sensor'}.{_slug(main_name)}"]
    for attribute in extra:
        attr_name = f"{name} {attribute.replace('_', ' ')}"
        quoted = _quote(attribute)
        sensors.append(
            {
                "name": attr_name,
                "unique_id": f"{UNIQUE_PREFIX}_{object_id}_{_slug(attribute)}",
                "state": f"{{{{ state_attr('{source}', '{quoted}') }}}}",
                "availability": f"{{{{ state_attr('{source}', '{quoted}') is not none }}}}",
            }
        )
        new_ids.append(f"sensor.{_slug(attr_name)}")
    if sensors:
        blocks.insert(0, {"sensor": sensors})
    text = yaml.dump(
        {"template": blocks},
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=10000,
    )
    return {"yaml": text, "entity_ids": new_ids}
